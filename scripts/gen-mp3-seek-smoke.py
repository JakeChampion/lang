#!/usr/bin/env python3
"""Freeze a small independent MP3 seek slice for the self-host interpreter."""
import argparse
import hashlib
from pathlib import Path
import re
import runpy
import struct
import subprocess
import tempfile
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
REFERENCE = runpy.run_path(str(ROOT/'scripts/gen-mp3-vectors.py'))
TABLES = REFERENCE['tables']


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--minimp3', type=Path)
    parser.add_argument('--minimp3-ex', type=Path)
    parser.add_argument('--fern', type=Path, default=ROOT/'bin/fern-selfhost')
    parser.add_argument('--output', type=Path, default=ROOT/'tests/stdlib/mp3_seek_smoke_vectors.fern')
    args = parser.parse_args()
    with tempfile.TemporaryDirectory() as directory:
        temp = Path(directory)
        for name, source, digest in [('minimp3.h', args.minimp3, TABLES.SHA),
                                     ('minimp3_ex.h', args.minimp3_ex, REFERENCE['EX_SHA'])]:
            raw = source.read_bytes() if source else urllib.request.urlopen(
                f'https://raw.githubusercontent.com/lieff/minimp3/{TABLES.REV}/{name}', timeout=30).read()
            if hashlib.sha256(raw).hexdigest() != digest:
                raise ValueError('reference header hash mismatch: '+name)
            (temp/name).write_bytes(raw)
        fixture = (ROOT/'tests/stdlib/mp3_vectors.fern').read_text()
        encoded = bytes.fromhex(re.search(r'name: "mpeg-8000-1", bytes: "([0-9a-f]+)"', fixture)[1])
        at, size, rate, channels = REFERENCE['frame_offsets'](encoded)[0]
        encoded = encoded[at:at+size]
        (temp/'input.mp3').write_bytes(encoded)
        helper = temp/'reference'
        subprocess.run(['cc', '-O3', '-ffp-contract=off', '-I'+str(temp),
                        '-o', str(helper), str(ROOT/'scripts/audio-reference/mp3.c')], check=True)
        subprocess.run([str(helper), str(temp/'input.mp3'), str(temp/'output.f32'), 'raw'], check=True)
        pcm = (temp/'output.f32').read_bytes()
        if (rate, channels, len(pcm)) != (8000, 1, 576*4):
            raise ValueError('unexpected independent MP3 frame')
        position = 537
        bits = struct.unpack('<'+'I'*(576-position), pcm[position*4:])
        text = ('// Generated by scripts/gen-mp3-seek-smoke.py.\n'
                '// Scalar minimp3 '+TABLES.REV+' (CC0).\n'
                'pub const INPUT: string = "'+encoded.hex()+'";\n'
                'pub const POSITION: i64 = '+str(position)+'i64;\n'
                'pub const SAMPLE_BITS: u32[] = ['+', '.join(str(x)+'u32' for x in bits)+'];\n')
        args.output.write_text(text)
        subprocess.run([str(args.fern), '-fmt', '-w', str(args.output)], check=True)


if __name__ == '__main__':
    main()
