#!/usr/bin/env python3
"""Freeze SILK resampler output checksums and boundary samples."""
import argparse
from pathlib import Path
import runpy
import subprocess

ROOT = Path(__file__).resolve().parent.parent
REFERENCE = runpy.run_path(str(Path(__file__).with_name('gen-silk-predict-vectors.py')))
DRIVER = r'''
package silk
import("fmt";"encoding/binary";"hash/crc32";resample "github.com/pion/opus/internal/resample/silk")

func FernResampleReference() {
 fmt.Println("// Generated by scripts/gen-silk-resample-vectors.py.")
 fmt.Println("// Pion Opus e7b8aa55508cfd30a968dbc695d4272a8e04f2f2, MIT and BSD-3-Clause.")
 fmt.Println("pub const OUTPUTS: i32[] = [")
 for _,inputRate:=range []int{8,12,16} {for _,outputRate:=range []int{8,12,16,24,48} {
  var r resample.Resampler;if err:=r.Init(inputRate*1000,outputRate*1000);err!=nil {panic(err)}
  seed:=uint32(1234567)
  for trial,duration:=range []int{1,10,20,60,1} {
   input:=make([]float32,inputRate*duration);for i:=range input {
    seed=seed*1664525+1013904223;v:=int16(seed>>16)
    switch trial {case 0: if i%2==0 {v=32767}else{v=-32768};case 1: v=0;if i==0 {v=32767};case 2:v=int16(i*997)}
    input[i]=float32(v)/32768
   }
   output:=make([]float32,outputRate*duration);if err:=r.Resample(input,output);err!=nil {panic(err)}
   bytes:=make([]byte,len(output)*2);samples:=make([]int16,len(output));for i,v:=range output {samples[i]=int16(v*32768);binary.LittleEndian.PutUint16(bytes[i*2:],uint16(samples[i]))}
   fmt.Printf("  %d, %d, %d, %d, %d, ",inputRate,outputRate,duration,trial,int32(crc32.ChecksumIEEE(bytes)))
   for _,v:=range samples[:8] {fmt.Printf("%d, ",v)};for _,v:=range samples[len(samples)-8:] {fmt.Printf("%d, ",v)};fmt.Println()
  }
 }}
 fmt.Println("];")
}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-dir', type=Path, required=True)
    parser.add_argument('--output', type=Path, default=ROOT/'tests/stdlib/opus_silk_resample_vectors.fern')
    parser.add_argument('--fern', type=Path, default=ROOT/'bin/fern-selfhost')
    args = parser.parse_args()
    args.output.write_bytes(REFERENCE['reference'](args.source_dir, DRIVER, 'FernResampleReference'))
    subprocess.run([str(args.fern), '-fmt', '-w', str(args.output)], check=True)


if __name__ == '__main__':
    main()
