#!/usr/bin/env python3
"""Generate pinned Vorbis floor values and mathematical transform coefficients."""
import argparse
import hashlib
import math
from pathlib import Path
import re
import struct
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
PIN = '6d533f26150953a882a6a111ebd13f0abf7129d5'
FLOOR_SHA = '8b2fedec670306702cdd3b5c594de0960273d0b829956fddbffa6316a61b1503'


def declaration(name, values, floats=False):
    def literal(value):
        if not floats:
            return str(value)
        value = struct.unpack('<f', struct.pack('<f', value))[0]
        text = format(value, '.9g')
        if '.' not in text and 'e' not in text:
            text += '.0'
        return text + 'f32'
    rows = [', '.join(literal(v) for v in values[i:i + 10]) for i in range(0, len(values), 10)]
    return f'pub const {name}: {"f32" if floats else "i32"}[] = [\n  ' + ',\n  '.join(rows) + ',\n];\n\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-dir', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = 'symphonia-codec-vorbis/src/floor.rs'
    data = (args.source_dir / path).read_bytes() if args.source_dir else urllib.request.urlopen(
        f'https://raw.githubusercontent.com/pdeljanov/Symphonia/{PIN}/{path}', timeout=30).read()
    if hashlib.sha256(data).hexdigest() != FLOOR_SHA:
        parser.exit(1, 'Vorbis floor reference digest mismatch\n')
    match = re.search(r'const FLOOR1_INVERSE_DB_TABLE:.*?=\s*\[(.*?)\];', data.decode(), re.S)
    floor = [float(x.strip()) for x in match[1].split(',') if x.strip()]
    assert len(floor) == 256
    text = '''# Vorbis floor and transform tables

These tables support both Vorbis floor types and every standard block size.
The inverse-decibel table follows pinned Symphonia source.
Transform and window coefficients use binary32 values from their mathematical definitions.

This module is available under MPL-2.0. See `licenses/vorbis/NOTICE.txt`.
Regenerate with `scripts/gen-vorbis-tables.py`. Use `--check` for a byte-exact check.

```fern
<<*>>=
// Generated by scripts/gen-vorbis-tables.py. DO NOT EDIT.
// Copyright (c) 2019-2023 The Project Symphonia Developers.
// This Source Code Form is subject to the Mozilla Public License, v. 2.0.
// See licenses/vorbis/MPL-2.0.txt or https://mozilla.org/MPL/2.0/.
'''
    text += '// Reference pin: ' + PIN + '\n\n'
    text += declaration('INVERSE_DB', floor, True)
    starts, twiddles, windows = [], [], []
    for exponent in range(6, 14):
        n = (1 << exponent) // 2
        starts.append(len(twiddles))
        twiddles.extend(v for k in range(n // 2) for v in (math.cos(math.pi * (k + .125) / n), math.sin(math.pi * (k + .125) / n)))
        windows.extend(math.sin(math.pi * .5 * math.sin(math.pi * .5 * (i + .5) / n)**2) for i in range(n))
    text += declaration('STARTS', starts)
    text += declaration('MDCT', twiddles, True)
    text += declaration('WINDOW', windows, True)
    text += declaration('FFT', [v for k in range(1024) for v in (math.cos(-2 * math.pi * k / 2048), math.sin(-2 * math.pi * k / 2048))], True)
    text = text.rstrip() + '\n```\n'
    target = ROOT / 'internal/stdlib/std/audio/vorbis/tables.fern.md'
    if args.check:
        if not target.exists() or target.read_text() != text:
            parser.exit(1, 'Vorbis tables are stale; run scripts/gen-vorbis-tables.py\n')
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)


if __name__ == '__main__':
    main()
