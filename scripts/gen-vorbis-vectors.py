#!/usr/bin/env python3
"""Freeze FFmpeg packets and libvorbis public-API float PCM."""
import argparse
import base64
import hashlib
from pathlib import Path
import runpy
import struct
import subprocess
import tempfile
import zlib

ROOT = Path(__file__).resolve().parent.parent
AAC = runpy.run_path(str(ROOT / 'scripts/gen-aac-vectors.py'))


def packets(data):
    at, pending, result = 0, b'', []
    while at < len(data):
        assert data[at:at + 4] == b'OggS'
        count = data[at + 26]
        lengths = data[at + 27:at + 27 + count]
        position = at + 27 + count
        for size in lengths:
            pending += data[position:position + size]
            position += size
            if size < 255:
                result.append(pending)
                pending = b''
        at = position
    assert not pending
    return result


def pack(data):
    return base64.b64encode(zlib.compress(data, 9)).decode()


class Bits:
    def __init__(self):
        self.values = []

    def put(self, value, width):
        assert 0 <= value < 1 << width
        self.values += [(value >> i) & 1 for i in range(width)]

    def bytes(self):
        result = bytearray((len(self.values) + 7) // 8)
        for i, value in enumerate(self.values):
            result[i // 8] |= value << (i % 8)
        return bytes(result)


def floor0_packets(amplitude_bits, order, dimension, residue_type):
    ident = b'\x01vorbis' + struct.pack('<IBIiiiBB', 0, 1, 44100, 0, 0, 0, 0x66, 1)
    comments = b'\x03vorbis' + struct.pack('<II', 0, 0) + b'\x01'
    setup = Bits()
    # Three complete one-bit books: classifications, LSPs, and small residues.
    setup.put(2, 8)
    for dim, lookup, exponent in [(1, 0, 788), (dimension, 2, 788), (dimension, 2, 773)]:
        for value, width in [(0x564342, 24), (dim, 16), (2, 24), (0, 1), (0, 1), (0, 5), (0, 5), (lookup, 4)]:
            setup.put(value, width)
        if lookup:
            # Residues use a smaller scale to retain normalized test PCM.
            setup.put((exponent << 21) | 1, 32)
            setup.put(((exponent - 1) << 21) | 1, 32)
            setup.put(1, 4)
            setup.put(0, 1)
            for value in range(2 * dim):
                setup.put(value % 3, 2)
    for value, width in [(0, 6), (0, 16), (0, 6), (0, 16), (order, 8), (44100, 16), (64, 16),
                         (amplitude_bits, 6), (1, 8), (0, 4), (1, 8), (0, 6), (residue_type, 16),
                         (0, 24), (32, 24), (31, 24), (0, 6), (0, 8), (1, 3), (0, 1), (2, 8),
                         (0, 6), (0, 16), (0, 1), (0, 1), (0, 2), (0, 8), (0, 8), (0, 8),
                         (0, 6), (0, 1), (0, 16), (0, 16), (0, 8), (1, 1)]:
        setup.put(value, width)
    result = [ident, comments, b'\x05vorbis' + setup.bytes()]
    for packet in range(4):
        audio = Bits()
        audio.put(0, 1)
        audio.put((1 << amplitude_bits) - 1 if packet & 1 else 1 << (amplitude_bits - 1), amplitude_bits)
        audio.put(0, 1)  # Floor codebook selector, ilog(1) == 1.
        for _ in range((order + dimension - 1) // dimension):
            audio.put(0, 1)
        audio.put(0, 1)  # Class zero.
        words = 32 // dimension if residue_type == 0 else (32 + dimension - 1) // dimension
        for i in range(words):
            audio.put((i + packet) & 1, 1)
        result.append(audio.bytes())
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--keep', type=Path)
    parser.add_argument('--reference', type=Path, required=True, help='compiled scripts/audio-reference/vorbis-packets.c')
    args = parser.parse_args()
    version = subprocess.check_output(['ffmpeg', '-version'], text=True).splitlines()[0]
    decoder = subprocess.check_output([str(args.reference), '--version'], text=True).strip()
    text = '// Generated by scripts/gen-vorbis-vectors.py.\n// Reference: ' + version + '\n'
    text += '// Float synthesis: ' + decoder + ', public API, container timestamps unset.\n'
    text += 'pub struct Vector { name: string, rate: i32, channels: i32, frames: i32, counts: string, identification: string, setup: string, packets: string, ogg: string, pcm: string }\n\n'
    smoke = text
    text += 'pub function vectors(): Vector[] {\n  return [\n'
    def freeze(name, rate, channels, encoded, values):
        nonlocal text, smoke
        framed = b''.join(struct.pack('<I', len(value)) + value for value in values)
        raw = subprocess.check_output([str(args.reference)], input=framed)
        position, reference, counts = 0, b'', b''
        for _ in values[3:]:
            count = raw[position:position + 4]
            frames = struct.unpack('<I', count)[0]
            position += 4
            counts += count
            reference += raw[position:position + frames * channels * 4]
            position += frames * channels * 4
        assert position == len(raw)
        rows = b''.join(struct.pack('<I', len(value)) + value for value in values[3:])
        row = f'Vector {{ name: "{name}", rate: {rate}, channels: {channels}, frames: {len(reference) // (4 * channels)}, counts: "{pack(counts)}", identification: "{pack(values[0])}", setup: "{pack(values[2])}", packets: "{pack(rows)}", ogg: "{pack(encoded)}", pcm: "{pack(reference)}" }}'
        text += '    ' + row + ',\n'
        if name == 'floor0-a8-o1-d1-r0':
            smoke += 'pub function vector(): Vector {\n  return ' + row + ';\n}\n'
        print(name, len(encoded), len(reference) // (4 * channels), len(values) - 3, hashlib.sha256(reference).hexdigest())
        if args.keep:
            args.keep.mkdir(parents=True, exist_ok=True)
            (args.keep / (name + '.ogg')).write_bytes(encoded)
            (args.keep / (name + '.f32')).write_bytes(reference)

    fixtures = [('mono', 44100, 1, 4099, 'tone', 4), ('stereo', 48000, 2, 8193, 'tone', 4),
        ('low-quality', 44100, 2, 4099, 'tone', -1), ('high-quality', 48000, 2, 4099, 'tone', 10),
        ('transients', 48000, 2, 8193, 'transient', 4), ('silence', 44100, 1, 2048, 'silence', 4)]
    fixtures += [(f'rate-{rate}', rate, 1, 3077, 'tone', 4) for rate in [8000, 11025, 16000, 22050, 32000, 96000, 192000]]
    fixtures += [(f'channels-{channels}', 48000, channels, 4099, 'tone', 4) for channels in range(3, 9)]
    with tempfile.TemporaryDirectory() as directory:
        temp = Path(directory)
        for name, rate, channels, frames, mode, quality in fixtures:
            (temp / 'input.f32').write_bytes(AAC['signal'](channels, frames, mode))
            layout = ['-channel_layout', {3: '3.0', 4: 'quad'}[channels]] if channels in [3, 4] else []
            AAC['run'](['-f', 'f32le', '-ar', str(rate), '-ac', str(channels), *layout, '-i', str(temp / 'input.f32'),
                '-c:a', 'libvorbis', '-q:a', str(quality), '-map_metadata', '-1', '-fflags', '+bitexact', '-flags:a', '+bitexact',
                str(temp / 'encoded.ogg')])
            encoded = (temp / 'encoded.ogg').read_bytes()
            values = packets(encoded)
            assert values[0][:7] == b'\x01vorbis' and values[2][:7] == b'\x05vorbis'
            freeze(name, rate, channels, encoded, values)
    for amplitude, order, dimension, residue in [(8, 1, 1, 0), (16, 1, 1, 1), (8, 3, 2, 1), (8, 4, 3, 1), (8, 3, 2, 2)]:
        name = f'floor0-a{amplitude}-o{order}-d{dimension}-r{residue}'
        freeze(name, 44100, 1, b'', floor0_packets(amplitude, order, dimension, residue))
    text += '  ];\n}\n'
    for name, content in [('vorbis_vectors.fern', text), ('vorbis_smoke_vectors.fern', smoke)]:
        target = ROOT / 'tests/stdlib' / name
        if args.check:
            if not target.exists() or target.read_text() != content:
                parser.exit(1, f'{name} is stale; run scripts/gen-vorbis-vectors.py\n')
        else:
            target.write_text(content)


if __name__ == '__main__':
    main()
