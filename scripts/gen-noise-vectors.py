def fern_str(s):
    return '"' + s + '"'


def strings(xs):
    if not xs:
        return "[]"
    return "[" + ", ".join(fern_str(x) for x in xs) + "]"


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: gen-noise-vectors.py cacophony.txt")
    raw = open(sys.argv[1], "rb").read()
    vectors = [v for v in json.loads(raw)["vectors"] if NAME.match(v["protocol_name"])]
    lines = []
    for v in vectors:
        fields = ["name: " + fern_str(v["protocol_name"])]
        fields += [f + ": " + fern_str(v.get(f, "")) for f in FIELDS]
        fields.append("init_psks: " + strings(v.get("init_psks", [])))
        fields.append("resp_psks: " + strings(v.get("resp_psks", [])))
        fields.append("payloads: " + strings([m["payload"] for m in v["messages"]]))
        fields.append("ciphertexts: " + strings([m["ciphertext"] for m in v["messages"]]))
        lines.append("    Vector { " + ", ".join(fields) + " },")
    body = TEMPLATE.replace("@SOURCE@", hashlib.sha256(raw).hexdigest()).replace("@COUNT@", str(len(vectors))).replace("@VECTORS@\n", "\n".join(lines) + "\n")
    with open(OUT, "w") as f:
        f.write(body)


main()
