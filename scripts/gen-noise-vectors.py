#!/usr/bin/env python3
# gen-noise-vectors.py: writes tests/stdlib/noise_cacophony_test.fern from the
# cacophony test vectors (vectors/cacophony.txt of
# https://github.com/haskell-cryptography/cacophony). The suite runs each
# vector that std/noise supports through both sides of the handshake and the
# transport, and checks each ciphertext and the handshake hash.
# Usage: scripts/gen-noise-vectors.py PATH/TO/cacophony.txt
import json
import os
import re
import sys

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "stdlib", "noise_cacophony_test.fern")

PATTERNS = {"NN", "NK", "XX", "IK", "KK"}
CIPHERS = {"ChaChaPoly": "noise.ChaChaPoly", "AESGCM": "noise.AesGcm"}
NAME = re.compile(r"^Noise_([A-Z]{2})(?:psk([0-2]))?_25519_(ChaChaPoly|AESGCM)_SHA256$")

HEADER = """// Generated by scripts/gen-noise-vectors.py from the cacophony test vectors
// ({n} vectors). Do not edit by hand.

import "std/test";
import "std/hex";
import "std/noise";

function bytes(h: string): u8[] {
  match (hex.decode(h)) {
    Ok(b) => {
      return b;
    },
    Err(e) => {
      return [];
    }
  }
  return [];
}

function config(pattern: noise.Pattern, cipher: noise.Cipher, psk_at: i32, psk: string, prologue: string, s: string, rs: string): noise.Config {
  let mode = if (psk_at < 0) { noise.NoPsk } else { noise.Psk(psk_at, bytes(psk)) };
  return noise.Config { pattern: pattern, cipher: cipher, prologue: bytes(prologue), static_key: bytes(s), remote_static: bytes(rs), psk: mode };
}

// One vector. The initiator writes the even messages and the responder the
// odd ones, in the handshake and then in the transport.
function run(i_config: noise.Config, i_e: string, r_config: noise.Config, r_e: string, hash: string, payloads: string[], ciphertexts: string[]): string {
  let Ok(i) = noise.initiator_derand(i_config, bytes(i_e)) else {
    return "initiator refused";
  };
  let Ok(r) = noise.responder_derand(r_config, bytes(r_e)) else {
    return "responder refused";
  };
  let k = 0;
  while (!i.is_finished()) {
    let writer_is_initiator = k % 2 == 0;
    let p = bytes(payloads[k]);
    if (writer_is_initiator) {
      let Ok((m, ni)) = i.write_message(p) else {
        return "message " + k.to_string() + ": write refused";
      };
      i = ni;
      if (hex.encode(m) != ciphertexts[k]) {
        return "message " + k.to_string() + ": ciphertext differs";
      }
      let Ok((got, nr)) = r.read_message(m) else {
        return "message " + k.to_string() + ": read refused";
      };
      r = nr;
      if (got != p) {
        return "message " + k.to_string() + ": payload differs";
      }
    } else {
      let Ok((m, nr)) = r.write_message(p) else {
        return "message " + k.to_string() + ": write refused";
      };
      r = nr;
      if (hex.encode(m) != ciphertexts[k]) {
        return "message " + k.to_string() + ": ciphertext differs";
      }
      let Ok((got, ni)) = i.read_message(m) else {
        return "message " + k.to_string() + ": read refused";
      };
      i = ni;
      if (got != p) {
        return "message " + k.to_string() + ": payload differs";
      }
    }
    k = k + 1;
  }
  if (!r.is_finished()) {
    return "the responder has more messages";
  }
  if (hex.encode(i.handshake_hash()) != hash || hex.encode(r.handshake_hash()) != hash) {
    return "handshake hash differs";
  }
  let Ok(ti) = i.split() else {
    return "initiator split refused";
  };
  let Ok(tr) = r.split() else {
    return "responder split refused";
  };
  while (k < payloads.len()) {
    let p = bytes(payloads[k]);
    if (k % 2 == 0) {
      let Ok((m, n)) = ti.send(p) else {
        return "message " + k.to_string() + ": send refused";
      };
      ti = n;
      if (hex.encode(m) != ciphertexts[k]) {
        return "message " + k.to_string() + ": ciphertext differs";
      }
      let Ok((got, n2)) = tr.receive(m) else {
        return "message " + k.to_string() + ": receive refused";
      };
      tr = n2;
      if (got != p) {
        return "message " + k.to_string() + ": payload differs";
      }
    } else {
      let Ok((m, n)) = tr.send(p) else {
        return "message " + k.to_string() + ": send refused";
      };
      tr = n;
      if (hex.encode(m) != ciphertexts[k]) {
        return "message " + k.to_string() + ": ciphertext differs";
      }
      let Ok((got, n2)) = ti.receive(m) else {
        return "message " + k.to_string() + ": receive refused";
      };
      ti = n2;
      if (got != p) {
        return "message " + k.to_string() + ": payload differs";
      }
    }
    k = k + 1;
  }
  return "";
}
"""


def s(x):
    return '"' + x + '"'


def arr(xs):
    return "[" + ", ".join(s(x) for x in xs) + "]"


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: gen-noise-vectors.py cacophony.txt")
    with open(sys.argv[1]) as f:
        vectors = json.load(f)["vectors"]
    chosen = []
    for v in vectors:
        m = NAME.match(v.get("protocol_name", ""))
        if not m or m.group(1) not in PATTERNS:
            continue
        if len(v.get("init_psks", [])) > 1 or v.get("fallback"):
            continue
        chosen.append((m, v))
    out = [HEADER.replace("{n}", str(len(chosen)))]
    its = []
    for idx, (m, v) in enumerate(chosen):
        pattern, at, cipher = m.group(1), m.group(2), m.group(3)
        psk_at = at if at is not None else "0 - 1"
        ipsk = v.get("init_psks", [""])[0]
        rpsk = v.get("resp_psks", [""])[0]
        fn = "test_" + str(idx + 1)
        out.append("function " + fn + "(): test.TestOutcome {")
        out.append("  let r = run(")
        out.append("    config(noise." + pattern + ", " + CIPHERS[cipher] + ", " + psk_at + ", " + s(ipsk) + ", " + s(v["init_prologue"]) + ", " + s(v.get("init_static", "")) + ", " + s(v.get("init_remote_static", "")) + "),")
        out.append("    " + s(v["init_ephemeral"]) + ",")
        out.append("    config(noise." + pattern + ", " + CIPHERS[cipher] + ", " + psk_at + ", " + s(rpsk) + ", " + s(v["resp_prologue"]) + ", " + s(v.get("resp_static", "")) + ", " + s(v.get("resp_remote_static", "")) + "),")
        out.append("    " + s(v["resp_ephemeral"]) + ",")
        out.append("    " + s(v["handshake_hash"]) + ",")
        out.append("    " + arr([x["payload"] for x in v["messages"]]) + ",")
        out.append("    " + arr([x["ciphertext"] for x in v["messages"]]) + ",")
        out.append("  );")
        out.append("  if (r != \"\") {")
        out.append("    return test.fail(r);")
        out.append("  }")
        out.append("  return test.pass();")
        out.append("}")
        out.append("")
        its.append((v["protocol_name"], fn))
    out.append("function main(): i32 {")
    out.append("  let r = test.new(\"std/noise cacophony vectors\");")
    for name, fn in its:
        out.append("  r = r.it(" + s(name) + ", " + fn + ");")
    out.append("  return r.finish();")
    out.append("}")
    with open(OUT, "w") as f:
        f.write("\n".join(out) + "\n")


main()
