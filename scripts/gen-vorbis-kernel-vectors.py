#!/usr/bin/env python3
"""Freeze independent C Vorbis transform and whole-timeline overlap equations."""
import argparse
import base64
import hashlib
from pathlib import Path
import struct
import subprocess
import tempfile
import zlib

ROOT = Path(__file__).resolve().parent.parent


def packed(raw):
    return base64.b64encode(zlib.compress(raw, 9)).decode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = ROOT / 'scripts/audio-reference/vorbis-kernels.c'
    with tempfile.TemporaryDirectory() as directory:
        program = Path(directory) / 'reference'
        subprocess.run(['cc', '-O2', '-ffp-contract=off', str(source), '-lm', '-o', str(program)], check=True)
        raw = subprocess.check_output([str(program)])
    at = 0
    def word():
        nonlocal at
        value = struct.unpack_from('<I', raw, at)[0]
        at += 4
        return value
    def take(count):
        nonlocal at
        value = raw[at:at + count]
        assert len(value) == count
        at += count
        return value
    text = '// Generated by scripts/gen-vorbis-kernel-vectors.py.\n'
    text += '// Independent C equation SHA-256: ' + hashlib.sha256(source.read_bytes()).hexdigest() + '\n'
    text += '// Complete raw reference SHA-256: ' + hashlib.sha256(raw).hexdigest() + '\n'
    text += 'pub struct Transform { exponent: i32, impulse: boolean, data: string }\n\n'
    text += 'pub struct Overlap { small: i32, large: i32, frames: i32, data: string }\n\n'
    text += 'pub function transforms(): Transform[] {\n  return [\n'
    for _ in range(word()):
        exponent, impulse = word(), word()
        data = take(3 * (1 << (exponent - 1)) * 4)
        text += f'    Transform {{ exponent: {exponent}, impulse: {str(bool(impulse)).lower()}, data: "{packed(data)}" }},\n'
    text += '  ];\n}\n\n'
    text += 'pub function overlaps(): Overlap[] {\n  return [\n'
    for _ in range(word()):
        small, large, count = word(), word(), word()
        start = at
        for _ in range(count):
            exponent, frames = word(), word()
            take(((1 << (exponent - 1)) + frames) * 4)
        text += f'    Overlap {{ small: {small}, large: {large}, frames: {count}, data: "{packed(raw[start:at])}" }},\n'
    text += '  ];\n}\n'
    assert at == len(raw)
    target = ROOT / 'tests/stdlib/vorbis_kernel_vectors.fern'
    if args.check:
        if not target.exists() or target.read_text() != text:
            parser.exit(1, 'Vorbis kernel vectors are stale; run scripts/gen-vorbis-kernel-vectors.py\n')
    else:
        target.write_text(text)
    print('Vorbis independent reference bytes:', len(raw))


if __name__ == '__main__':
    main()
