#!/usr/bin/env python3
"""Freeze CELT, transform, vector, and band traces from pinned libopus."""
import argparse
from pathlib import Path
import runpy
import subprocess
import zlib

ROOT = Path(__file__).resolve().parent.parent
REFERENCE = runpy.run_path(str(Path(__file__).with_name('gen-silk-loss-vectors.py')))
CASES = {
    'CELT': ('celt_trace.c', [['1', '3', '8'], ['2', '6', '10']]),
    'MDCT': ('mdct_trace.c', [['1', '12'], ['2', '100']]),
    'VQ': ('vq_trace.c', [['2', '300'], ['3', '2000']]),
    'BANDS': ('bands_trace.c', [['2', '50'], ['3', '200']]),
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--archive', type=Path)
    parser.add_argument('--cmake', default='cmake')
    parser.add_argument('--output', type=Path, default=ROOT/'tests/stdlib/opus_kernel_vectors.fern')
    parser.add_argument('--fern', type=Path, default=ROOT/'bin/fern-selfhost')
    args = parser.parse_args()
    lines = ['// Generated by scripts/gen-opus-kernel-vectors.py.',
             '// Unmodified libopus '+REFERENCE['PIN']+', BSD-3-Clause.',
             '// The VQ trace converts the C Q30 stereo angle to the Fern Q14 interface.', '']
    for name, (helper, calls) in CASES.items():
        results = REFERENCE['reference'](args.archive, args.cmake, helper, calls)
        for size, result in zip(['SHORT', 'LONG'], results, strict=True):
            lines.append(f'pub const {name}_{size}: u32 = {zlib.crc32(result)}u32;')
    args.output.write_text('\n'.join(lines)+'\n')
    subprocess.run([str(args.fern), '-fmt', '-w', str(args.output)], check=True)


if __name__ == '__main__':
    main()
