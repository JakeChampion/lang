#!/usr/bin/env python3
"""Freeze ALAC packets and exact independent FFmpeg integer PCM."""
import argparse
import base64
import hashlib
import json
import math
from pathlib import Path
import struct
import subprocess
import tempfile
import zlib

ROOT = Path(__file__).resolve().parent.parent


class Bits:
    def __init__(self):
        self.value = ''

    def put(self, value, width):
        self.value += format(value & ((1 << width) - 1), f'0{width}b')

    def bytes(self):
        value = self.value + '0' * (-len(self.value) % 8)
        return int(value, 2).to_bytes(len(value) // 8, 'big')


def pack(value):
    return base64.b64encode(zlib.compress(value, 9)).decode()


def cookie(depth, channels=1, frames=4096, rate=48000, pb=0, mb=255):
    return struct.pack('>IBBBBBBHIII', frames, 0, depth, pb, mb, 14, channels, 0, 0, 0, rate)


def varint(value):
    groups = [value & 127]
    value >>= 7
    while value:
        groups.insert(0, (value & 127) | 128)
        value >>= 7
    return bytes(groups)


def caf(configuration, packets, frames):
    rate = struct.unpack_from('>I', configuration, 20)[0]
    count = configuration[9]
    block = struct.unpack_from('>I', configuration)[0]
    def chunk(tag, value):
        return tag + struct.pack('>q', len(value)) + value
    desc = struct.pack('>d4sIIIII', rate, b'alac', 0, 0, block, count, 0)
    pakt = struct.pack('>qqii', len(packets), frames, 0, 0) + b''.join(varint(len(p)) for p in packets)
    return b'caff' + struct.pack('>HH', 1, 0) + chunk(b'desc', desc) + chunk(b'kuki', configuration) + chunk(b'pakt', pakt) + chunk(b'data', bytes(4) + b''.join(packets))


def synthetic(depth=16, paired=False, mode=0, coefficients=(), shift=0, raw=False, ancillary=False):
    frames = 19
    channels = 2 if paired else 1
    configuration = cookie(depth, channels, frames=32)
    bits = Bits()
    if ancillary:
        bits.put(4, 3)
        bits.put(3, 4)
        bits.put(0, 1)
        bits.put(2, 8)
        bits.put(0x1234, 16)
        bits.put(6, 3)
        bits.put(1, 4)
        bits.put(0xab, 8)
    bits.put(1 if paired else 0, 3)
    bits.put(0, 16)
    bits.put(8 | (shift // 8 << 1) | int(raw), 4)
    bits.put(frames, 32)
    values = [[((i * 43 + c * 17) % 251) - 125 for i in range(frames)] for c in range(channels)]
    if raw:
        for i in range(frames):
            for c in range(channels):
                value = values[c][i]
                if i == 0:
                    value = -(1 << (depth - 1))
                if i == 1:
                    value = (1 << (depth - 1)) - 1
                bits.put(value, depth)
    else:
        bits.put(1 if paired else 0, 8)
        bits.put(1 if paired else 0, 8)
        for _ in range(channels):
            bits.put(mode, 4)
            bits.put(3, 4)
            bits.put(0, 3)
            bits.put(len(coefficients), 5)
            for coefficient in coefficients:
                bits.put(coefficient, 16)
        if shift:
            for i in range(frames):
                for c in range(channels):
                    bits.put(i * 3 + c, shift)
        width = depth - shift + int(paired)
        for channel in values:
            for value in channel:
                folded = (value << 1) ^ (value >> 31)
                bits.put(511, 9)
                bits.put(folded, width)
    bits.put(7, 3)
    return configuration, [bits.bytes()], frames


def extra_bytes(text):
    output = b''
    for line in text.splitlines():
        if ':' in line:
            output += bytes.fromhex(line.split(':', 1)[1].split('  ', 1)[0].replace(' ', ''))
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--keep', type=Path)
    parser.add_argument('--apple-reference', required=True, type=Path)
    args = parser.parse_args()
    version = subprocess.check_output(['ffmpeg', '-version'], text=True).splitlines()[0]
    header = '// Generated by scripts/gen-alac-vectors.py.\n// Reference: ' + version + '\n'
    header += '// Apple ALAC reference: c38887c5c5e64a4b31108733bd79ca9b2496d987.\n'
    header += 'pub struct Vector { name: string, rate: i32, channels: i32, depth: i32, frames: i32, configuration: string, packets: string, pcm: string }\n\n'
    rows = []
    with tempfile.TemporaryDirectory() as directory:
        temp = Path(directory)
        def freeze(name, configuration, packets, frames):
            source = temp / 'input.caf'
            source.write_bytes(caf(configuration, packets, frames))
            channels, depth = configuration[9], configuration[5]
            rate = struct.unpack_from('>I', configuration, 20)[0]
            config_path = temp / 'configuration'
            packet_path = temp / 'packet'
            config_path.write_bytes(configuration)
            decoded = []
            for packet in packets:
                packet_path.write_bytes(packet)
                decoded.append(subprocess.check_output([str(args.apple_reference), str(config_path), str(packet_path)]))
            pcm = b''.join(decoded)
            assert len(pcm) == frames * channels * 4, (name, len(pcm), frames)
            if depth != 32 and not name.startswith('two-pass') and name != 'data-and-fill':
                raw = subprocess.check_output(['ffmpeg', '-v', 'error', '-i', str(source), '-f', 's32le', '-c:a', 'pcm_s32le', '-'])
                values = [v[0] >> (32 - depth) for v in struct.iter_unpack('<i', raw)]
                # FFmpeg declares the ALAC surround pair as back channels.
                # Match the documented side-surround layouts in WAVE bit order.
                mapping = {7: [0, 1, 2, 3, 6, 4, 5], 8: [0, 1, 2, 3, 6, 7, 4, 5]}.get(channels, list(range(channels)))
                values = [values[frame * channels + channel] for frame in range(frames) for channel in mapping]
                other = struct.pack('<' + 'i' * len(values), *values)
                assert pcm == other, (name, 'Apple and FFmpeg disagree', list(struct.unpack_from('<' + 'i' * channels, pcm, channels * 4)), list(struct.unpack_from('<' + 'i' * channels, other, channels * 4)))
            encoded = struct.pack('<I', len(packets)) + b''.join(struct.pack('<I', len(p)) + p for p in packets)
            rows.append(f'    Vector {{ name: "{name}", rate: {rate}, channels: {channels}, depth: {depth}, frames: {frames}, configuration: "{pack(configuration)}", packets: "{pack(encoded)}", pcm: "{pack(pcm)}" }},\n')
            print(name, depth, channels, frames, len(packets), hashlib.sha256(pcm).hexdigest())
            if args.keep:
                args.keep.mkdir(parents=True, exist_ok=True)
                (args.keep / (name + '.caf')).write_bytes(source.read_bytes())
                (args.keep / (name + '.pcm')).write_bytes(pcm)

        layouts = {1: 'mono', 2: 'stereo', 3: '3.0', 4: '4.0', 5: '5.0(side)', 6: '5.1(side)', 7: '6.1', 8: '7.1(wide)'}
        cases = [(channels, depth, 44100 if depth == 16 else 48000, 'tone')
                 for channels in range(1, 9) for depth in [16, 24]]
        cases += [(1, 16, 8000, 'silence'), (2, 24, 96000, 'silence'),
                  (1, 24, 192000, 'impulse'), (2, 16, 32000, 'noise')]
        for channels, depth, rate, mode in cases:
            frames = 4103
            signal = bytearray()
            for i in range(frames):
                for c in range(channels):
                    value = int(math.sin(i * (c + 3) * 0.037) * (1 << (depth - 3)))
                    if i % 521 == 0:
                        value = (1 << (depth - 1)) - 1
                    if mode == 'silence':
                        value = 0
                    elif mode == 'impulse':
                        value = -(1 << (depth - 1)) if i == 0 else 0
                    elif mode == 'noise':
                        value = (((i * 747796405 + c * 2891336453 + 1234567) ^ (i * 13579 >> 3)) & ((1 << depth) - 1)) - (1 << (depth - 1))
                    signal += struct.pack('<i', value << (32 - depth))
            source = temp / 'input.s32'
            source.write_bytes(signal)
            encoded = temp / 'input.m4a'
            subprocess.run(['ffmpeg', '-v', 'error', '-y', '-f', 's32le', '-ar', str(rate), '-ac', str(channels), '-channel_layout', layouts[channels], '-i', str(source), '-c:a', 'alac', '-sample_fmt', 's16p' if depth == 16 else 's32p', str(encoded)], check=True)
            probe = json.loads(subprocess.check_output(['ffprobe', '-v', 'error', '-select_streams', 'a:0', '-show_streams', '-show_packets', '-show_data', '-of', 'json', str(encoded)]))
            configuration = extra_bytes(probe['streams'][0]['extradata'])[12:36]
            assert configuration[5] == depth
            data = encoded.read_bytes()
            packets = [data[int(p['pos']):int(p['pos']) + int(p['size'])] for p in probe['packets']]
            freeze(f'encoded-{channels}ch-{depth}bit' + ('' if mode == 'tone' else '-' + mode), configuration, packets, frames)
        for name, options in [
            ('raw-16', {'raw': True}), ('raw-20', {'raw': True, 'depth': 20}),
            ('raw-24-stereo', {'raw': True, 'depth': 24, 'paired': True}),
            ('raw-32-stereo', {'raw': True, 'depth': 32, 'paired': True}),
            ('no-predictor', {}), ('predictor-four', {'coefficients': (7, -2, 1, 0)}),
            ('predictor-eight', {'coefficients': (7, -1, 2, -1, 0, 1, 0, 0)}),
            ('delta-short', {'coefficients': (0,) * 31}),
            ('two-pass-zero-order', {'mode': 15}),
            ('two-pass-four', {'mode': 15, 'coefficients': (7, -2, 1, 0)}),
            ('two-pass-delta', {'mode': 15, 'coefficients': (0,) * 31}),
            ('low-bits', {'depth': 24, 'shift': 8}),
            ('mid-side-low-bits', {'depth': 24, 'shift': 16, 'paired': True}),
            ('data-and-fill', {'raw': True, 'ancillary': True}),
            ('coefficient-extremes', {'coefficients': (32767, -32768, 32767, -32768)}),
            ('compressed-20', {'depth': 20}),
            ('compressed-32-low-eight', {'depth': 32, 'shift': 8, 'paired': True}),
            ('compressed-32-low-sixteen', {'depth': 32, 'shift': 16, 'paired': True}),
        ]:
            freeze(name, *synthetic(**options))
    full = header + 'pub function vectors(): Vector[] {\n  return [\n' + ''.join(rows) + '  ];\n}\n'
    smoke_row = next(row for row in rows if 'name: "no-predictor"' in row)
    smoke = header + 'pub function vector(): Vector {\n  return ' + smoke_row.strip().removesuffix(',') + ';\n}\n'
    for name, content in [('alac_vectors.fern', full), ('alac_smoke_vectors.fern', smoke)]:
        target = ROOT / 'tests/stdlib' / name
        if args.check:
            if target.read_text() != content:
                parser.exit(1, name + ' is stale\n')
        else:
            target.write_text(content)


if __name__ == '__main__':
    main()
