#!/usr/bin/env python3
"""Freeze internal-rate SILK packet output from the pinned reference."""
import argparse
from pathlib import Path
import runpy
import subprocess

ROOT = Path(__file__).resolve().parent.parent
REFERENCE = runpy.run_path(str(Path(__file__).with_name('gen-silk-predict-vectors.py')))
DRIVER = r'''
package silk
import "fmt"

func FernPacketReference() {
 fmt.Println("// Generated by scripts/gen-silk-packet-vectors.py.")
 fmt.Println("// Pion Opus e7b8aa55508cfd30a968dbc695d4272a8e04f2f2, MIT and BSD-3-Clause.")
 fmt.Println("pub const PACKETS: i32[] = [")
 d:=NewDecoder();seed:=uint32(125365)
 for _,rate:=range []int{8,12,16} {
  bandwidth:=BandwidthNarrowband;if rate==12 {bandwidth=BandwidthMediumband};if rate==16 {bandwidth=BandwidthWideband}
  for frame:=0;frame<8;frame++ {
   duration:=[]int{10,20,40,60}[frame%4]
   streamChannels:=2;if frame%3==0 {streamChannels=1}
   outputChannels:=2;if frame%4==0 {outputChannels=1}
   packet:=make([]byte,1024);for i:=range packet {seed=seed*1664525+1013904223;packet[i]=byte(seed>>24)}
   codedChannels:=1;if streamChannels==2 && outputChannels==2 {codedChannels=2}
   out:=make([]float32,rate*duration*codedChannels)
   d.rangeDecoder.Init(packet)
   if err:=d.decodeWithInitializedRange(out,streamChannels==2,outputChannels==2,duration*1000000,bandwidth);err!=nil {panic(err)}
   fmt.Printf("  %d, %d, %d, %d, %d, %d, ",rate,duration,streamChannels,outputChannels,int32(d.rangeDecoder.FinalRange()),len(packet))
   for _,v:=range packet {fmt.Printf("%d, ",v)};fmt.Println()
   fmt.Printf("  %d, ",rate*duration*outputChannels)
   for _,v:=range out {fmt.Printf("%d, ",int32(v*32768));if streamChannels==1 && outputChannels==2 {fmt.Printf("%d, ",int32(v*32768))}};fmt.Println()
  }
 }
 fmt.Println("];")
}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-dir', type=Path, required=True)
    parser.add_argument('--output', type=Path, default=ROOT/'tests/stdlib/opus_silk_packet_vectors.fern')
    parser.add_argument('--fern', type=Path, default=ROOT/'bin/fern-selfhost')
    args = parser.parse_args()
    args.output.write_bytes(REFERENCE['reference'](args.source_dir, DRIVER, 'FernPacketReference'))
    subprocess.run([str(args.fern), '-fmt', '-w', str(args.output)], check=True)


if __name__ == '__main__':
    main()
