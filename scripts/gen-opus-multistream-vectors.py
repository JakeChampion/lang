#!/usr/bin/env python3
"""Freeze multistream packets and complete float PCM from pinned libopus."""
import argparse
import base64
import json
from pathlib import Path
import runpy
import struct
import subprocess
import zlib

ROOT = Path(__file__).resolve().parent.parent
REFERENCE = runpy.run_path(str(Path(__file__).with_name('gen-silk-loss-vectors.py')))


def encoded_case(rows):
    config = rows[0]
    data = bytearray(struct.pack('<IIIII', config['rate'], config['channels'], config['streams'], config['coupled'], len(rows)))
    data.extend(bytes(config['mapping']))
    for row in rows:
        if any(row[k] != config[k] for k in ['rate', 'channels', 'streams', 'coupled', 'mapping']):
            raise ValueError('configuration changed in a multistream case')
        packet = bytes.fromhex(row['packet'])
        pcm = row['pcm']
        if len(pcm) != row['frames']*row['channels']:
            raise ValueError('unexpected multistream PCM size')
        data.extend(struct.pack('<IIII', row['action'], row['frames'], row['range'], len(packet)))
        data.extend(packet)
        data.extend(struct.pack('<'+'I'*len(pcm), *pcm))
    return '  '+json.dumps(base64.b64encode(zlib.compress(data, 9)).decode('ascii'))+','


def generate(records):
    cases = {}
    for row in records:
        cases.setdefault(row['case'], []).append(row)
    if len(records) != 605 or set(cases) != set(range(55)):
        raise ValueError('unexpected multistream corpus size')
    lines = ['// Generated by scripts/gen-opus-multistream-vectors.py.',
             '// Unmodified libopus '+REFERENCE['PIN']+'.',
             '// Each zlib/base64 case contains configuration, packets, and complete float PCM.',
             '', 'pub const CASES: string[] = [']
    lines.extend(encoded_case(rows) for rows in cases.values())
    lines.extend(['];', '', '// Small, independent cases for the self-host interpreter gate.', 'pub const SMOKE: string[] = ['])
    lines.extend(encoded_case(cases[index][:3]) for index in [8, 10])
    return '\n'.join(lines+['];', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--archive', type=Path)
    parser.add_argument('--cmake', default='cmake')
    parser.add_argument('--fern', type=Path, default=ROOT/'bin/fern-selfhost')
    parser.add_argument('--output', type=Path, default=ROOT/'tests/stdlib/opus_multistream_vectors.fern')
    args = parser.parse_args()
    args.output.write_text(generate(REFERENCE['reference'](args.archive, args.cmake, 'opus_multistream.c')))
    subprocess.run([str(args.fern), '-fmt', '-w', str(args.output)], check=True)


if __name__ == '__main__':
    main()
