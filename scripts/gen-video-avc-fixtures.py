#!/usr/bin/env python3
"""Generate AVC SPS references with independent FFmpeg syntax traces."""
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent.parent
RATIOS = [(0, 0), (1, 1), (12, 11), (10, 11), (16, 11), (40, 33), (24, 11),
          (20, 11), (32, 11), (80, 33), (18, 11), (15, 11), (64, 33), (160, 99),
          (4, 3), (3, 2), (2, 1)]


def generate(directory):
    cases = [
        ("baseline-crop", "baseline", "yuv420p", "62x46", []),
        ("main", "main", "yuv420p", "64x48", []),
        ("high-crop-colour", "high", "yuv420p", "66x50",
         ["-vf", "setsar=41/33", "-color_primaries", "bt709", "-color_trc", "bt709", "-colorspace", "bt709", "-color_range", "pc"]),
        ("high10", "high10", "yuv420p10le", "64x48", []),
        ("high422", "high422", "yuv422p", "64x48", []),
        ("high444", "high444", "yuv444p", "64x48", []),
        ("interlaced", "high", "yuv420p", "64x52", ["-flags", "+ilme+ildct", "-x264-params", "interlaced=1:tff=1"]),
        ("hrd", "high", "yuv420p", "64x48", ["-b:v", "64k", "-minrate", "64k", "-maxrate", "64k", "-bufsize", "128k", "-x264-params", "nal-hrd=cbr:force-cfr=1"]),
    ]
    for name, profile, pixel_format, size, options in cases:
        path = directory / f"{name}.h264"
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-f", "lavfi", "-i", f"testsrc2=size={size}:rate=6",
                        "-frames:v", "1", "-c:v", "libx264", "-threads", "1", "-profile:v", profile,
                        "-pix_fmt", pixel_format, *options, "-f", "h264", str(path)], check=True)
        yield name, path


def trace_fields(log):
    fields = {}
    for key, value in re.findall(r"\[trace_headers[^\]]*\]\s+\d+\s+(\w+)\s+[01]+\s+=\s+(-?\d+)", log):
        fields.setdefault(key, int(value))
    return fields


def metadata(fields):
    only = fields["frame_mbs_only_flag"]
    chroma = fields.get("chroma_format_idc", 1)
    separate = fields.get("separate_colour_plane_flag", 0)
    array_type = 0 if separate else chroma
    x = 2 if array_type in (1, 2) else 1
    y = (2 if array_type == 1 else 1) * (2 - only)
    left, right, top, bottom = [fields.get("frame_crop_" + side + "_offset", 0) * scale
                                for side, scale in (("left", x), ("right", x), ("top", y), ("bottom", y))]
    width = (fields["pic_width_in_mbs_minus1"] + 1) * 16
    height = (fields["pic_height_in_map_units_minus1"] + 1) * 16 * (2 - only)
    ratio_id = fields.get("aspect_ratio_idc", 0)
    ratio = (fields["sar_width"], fields["sar_height"]) if ratio_id == 255 else RATIOS[ratio_id]
    values = [fields["profile_idc"], fields["level_idc"], fields["seq_parameter_set_id"], chroma, separate,
              fields.get("bit_depth_luma_minus8", 0) + 8, fields.get("bit_depth_chroma_minus8", 0) + 8,
              width, height, width - left - right, height - top - bottom, left, top, right, bottom,
              only, fields.get("mb_adaptive_frame_field_flag", 0), fields["max_num_ref_frames"], *ratio,
              fields.get("video_signal_type_present_flag", 0), fields.get("colour_description_present_flag", 0),
              fields.get("video_format", 5), fields.get("video_full_range_flag", 0), fields.get("colour_primaries", 2),
              fields.get("transfer_characteristics", 2), fields.get("matrix_coefficients", 2),
              fields.get("num_units_in_tick", 0), fields.get("time_scale", 0), fields.get("fixed_frame_rate_flag", 0)]
    assert len(values) == 30
    return values


def reference(path):
    process = subprocess.run(["ffmpeg", "-v", "trace", "-i", str(path), "-c:v", "copy", "-bsf:v", "trace_headers", "-f", "null", "-"],
                             check=True, capture_output=True, text=True)
    values = metadata(trace_fields(process.stderr))
    stream = json.loads(subprocess.check_output(["ffprobe", "-v", "error", "-show_streams", "-of", "json", str(path)]))["streams"][0]
    assert (values[9], values[10]) == (stream["width"], stream["height"])
    data = path.read_bytes()
    markers = list(re.finditer(b"\x00{2,}\x01", data))
    packets = [data[m.end():markers[i + 1].start() if i + 1 < len(markers) else len(data)].rstrip(b"\x00") for i, m in enumerate(markers)]
    return next(packet for packet in packets if packet[0] & 31 == 7), values


def main():
    lines = ["// Generated by scripts/gen-video-avc-fixtures.py with FFmpeg trace_headers and FFprobe.",
             "pub struct Vector { name: string, bytes: string, values: i64[] }", "pub function vectors(): Vector[] {", "  return ["]
    with tempfile.TemporaryDirectory() as temporary:
        for name, path in generate(Path(temporary)):
            sps, values = reference(path)
            lines.append(f'    Vector {{ name: "{name}", bytes: "{sps.hex()}", values: [' + ", ".join(f"{n}i64" for n in values) + "] },")
    lines += ["  ];", "}"]
    target = ROOT / "tests/stdlib/video_avc_vectors.fern"
    target.write_text("\n".join(lines) + "\n")
    compiler = os.environ.get("FERN") or subprocess.check_output([str(ROOT / "bootstrap/bootstrap.sh"), "stage0"], text=True).strip()
    subprocess.run([compiler, "-fmt", "-w", str(target)], check=True)
    print("Wrote", target.relative_to(ROOT))


if __name__ == "__main__":
    main()
