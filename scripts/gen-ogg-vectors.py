#!/usr/bin/env python3
"""Freeze Ogg pages and packet checksums from unmodified libogg 1.3.6."""
import argparse
import base64
import hashlib
import io
import json
from pathlib import Path
import struct
import subprocess
import tarfile
import tempfile
import urllib.request
import zlib

ROOT = Path(__file__).resolve().parent.parent
PIN = 'be05b13e98b048f0b5a0f5fa8ce514d56db5f822'
ARCHIVE_SHA = 'b2ff5c003e5697507169f7d614d64dc4e8bf030c85ad081bec75c164566f8246'


def reference(archive, cmake):
    data = archive.read_bytes() if archive else urllib.request.urlopen(
        f'https://codeload.github.com/xiph/ogg/tar.gz/{PIN}', timeout=60).read()
    if hashlib.sha256(data).hexdigest() != ARCHIVE_SHA:
        raise ValueError('libogg archive hash mismatch')
    with tempfile.TemporaryDirectory() as directory:
        root = Path(directory)
        with tarfile.open(fileobj=io.BytesIO(data)) as tar:
            tar.extractall(root, filter='data')
        source, build = root/('ogg-'+PIN), root/'build'
        subprocess.run([cmake, '-S', str(source), '-B', str(build), '-DCMAKE_BUILD_TYPE=Release',
                        '-DBUILD_SHARED_LIBS=OFF', '-DBUILD_TESTING=OFF'], check=True, stdout=subprocess.DEVNULL)
        subprocess.run([cmake, '--build', str(build), '-j', '2'], check=True, stdout=subprocess.DEVNULL)
        executable = root/'ogg-reference'
        subprocess.run(['cc', '-O2', '-Wall', '-Wextra', '-Werror', '-I'+str(source/'include'),
                        '-I'+str(build/'include'), str(ROOT/'scripts/audio-reference/ogg_pages.c'),
                        str(build/'libogg.a'), '-o', str(executable)], check=True)
        return [json.loads(line) for line in subprocess.check_output([str(executable)]).splitlines()]


def generate(records):
    if len(records) != 56 or sum(len(r['packets']) for r in records) != 48:
        raise ValueError('unexpected Ogg reference size')
    cases = {}
    for row in records:
        cases.setdefault(row['case'], []).append(row)
    if set(cases) != set(range(5)):
        raise ValueError('missing Ogg reference case')
    lines = ['// Generated by scripts/gen-ogg-vectors.py.',
             '// Unmodified libogg '+PIN+', BSD-3-Clause.',
             '// Each zlib/base64 case contains pages and independent libogg packet checksums.',
             '', 'pub const CASES: string[] = [']
    for rows in cases.values():
        data = bytearray(struct.pack('<I', len(rows)))
        for row in rows:
            raw = bytes.fromhex(row['bytes'])
            data.extend(struct.pack('<I', len(raw)))
            data.extend(raw)
            data.extend(struct.pack('<IIqIQI', row['serial'], row['sequence'], row['granule'], row['flags'],
                                    row['offset'], len(row['packets'])))
            for packet in row['packets']:
                payload = bytes.fromhex(packet['bytes'])
                data.extend(struct.pack('<IIQQ', len(payload), zlib.crc32(payload), packet['offset'], packet['page_offset']))
        encoded = base64.b64encode(zlib.compress(data, 9)).decode('ascii')
        lines.append('  '+json.dumps(encoded)+',')
    lines.append('];')
    return '\n'.join(lines)+'\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--archive', type=Path)
    parser.add_argument('--cmake', default='cmake')
    parser.add_argument('--output', type=Path, default=ROOT/'tests/stdlib/audio_ogg_vectors.fern')
    parser.add_argument('--fern', type=Path, default=ROOT/'bin/fern-selfhost')
    args = parser.parse_args()
    args.output.write_text(generate(reference(args.archive, args.cmake)))
    subprocess.run([str(args.fern), '-fmt', '-w', str(args.output)], check=True)


if __name__ == '__main__':
    main()
