#!/usr/bin/env python3
"""Generate MP3 tables from the pinned CC0 minimp3 reference."""
import hashlib
import argparse
from pathlib import Path
import re
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
REV = 'ea99364f61c14656440e8d77e9c233ccf3124633'
SHA = '57e437c5c1f0e8b243885d3929c8973b5e6c778451e0100ab4251d19915cb3ad'
NAMES = ['g_scf_long', 'g_scf_short', 'g_scf_partitions', 'g_scfc_decode', 'g_mod', 'g_preamp', 'g_expfrac', 'g_pow43', 'tabs', 'tab32', 'tab33', 'tabindex', 'g_linbits', 'g_pan', 'g_aa', 'g_twid9', 'g_twid3', 'g_mdct_window', 'g_sec', 'g_win']


def initializer(source, name):
    m = re.search(r'static const (float|u?int\d+_t)\s+' + name + r'\s*((?:\[[^]]*\])+)\s*=\s*\{', source, re.S)
    assert m, name
    start = m.end()
    depth = 1
    end = start
    while depth:
        depth += (source[end] == '{') - (source[end] == '}')
        end += 1
    body = re.sub(r'/\*.*?\*/', '', source[start:end-1], flags=re.S)
    pattern = r'-?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?f?'
    if '{' in body:
        width = int(re.findall(r'\[([^]]+)\]', m[2])[-1])
        tokens = []
        for row in re.findall(r'\{([^{}]+)\}', body):
            values = re.findall(pattern, row)
            assert len(values) <= width
            tokens.extend(values + ['0'] * (width - len(values)))
    else:
        tokens = re.findall(pattern, body)
    floating = m[1] == 'float'
    return floating, tokens


def generate(source):
    result = ['// Generated by scripts/gen-mp3-tables.py from minimp3 '+REV+'.',
              '// CC0: https://creativecommons.org/publicdomain/zero/1.0/', '']
    for name in NAMES:
        floating, tokens = initializer(source, name)
        values = []
        for t in tokens:
            if floating:
                t = t.removesuffix('f')
                if '.' not in t and 'e' not in t.lower():
                    t += '.0'
                t += 'f32'
            values.append(t)
        result.append('pub const '+name.upper()+': '+('f32' if floating else 'i32')+'[] = [')
        for i in range(0, len(values), 16):
            result.append('  '+', '.join(values[i:i+16])+',')
        result.append('];\n')
    return '\n'.join(result)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--source', type=Path, help='local pinned minimp3.h for offline verification')
    args = parser.parse_args()
    data = args.source.read_bytes() if args.source else urllib.request.urlopen(f'https://raw.githubusercontent.com/lieff/minimp3/{REV}/minimp3.h', timeout=30).read()
    assert hashlib.sha256(data).hexdigest() == SHA
    path = ROOT / 'internal/stdlib/std/audio/mp3/tables.fern'
    generated = generate(data.decode())
    if args.check:
        if path.read_text() != generated:
            raise SystemExit('MP3 tables differ from the pinned source')
    else:
        path.write_text(generated)
