#!/usr/bin/env python3
"""Generate independent QMF history and channel-transition controls."""
import hashlib
import importlib.util
import json
from pathlib import Path
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent.parent


def hash_bytes(data):
    value = 2166136261
    for byte in data:
        value = ((value ^ byte) * 16777619) & 0xffffffff
    return value


def main():
    spec = importlib.util.spec_from_file_location('vectors', ROOT / 'scripts/gen-mp3-vectors.py')
    vectors = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(vectors)
    source = ROOT / 'scripts/audio-reference/mp3_synthesis.c'
    channels = [1, 2, 1, 1, 2, 1, 2, 2, 1]
    with tempfile.TemporaryDirectory() as directory:
        work = Path(directory)
        vectors.reference(work)
        subprocess.run(['cc', '-O3', '-ffp-contract=off', '-I', str(work), str(source),
                        '-o', str(work / 'synthesis')], check=True)
        subprocess.run([str(work / 'synthesis'), str(work / 'samples.f32')], check=True)
        data = (work / 'samples.f32').read_bytes()
    assert all(abs(value) < 1000000 for value in struct.unpack('<' + 'f' * (len(data) // 4), data))
    pcm, history, at = [], [], 0
    for count in channels:
        size = 576 * count * 4
        pcm.append(hash_bytes(data[at:at + size]))
        at += size
        history.append(hash_bytes(data[at:at + 960 * 4]))
        at += 960 * 4
    assert at == len(data)
    text = ['// Generated by scripts/gen-mp3-synthesis-vectors.py.', '']
    for name, values, type_, suffix in [('CHANNELS', channels, 'i32', ''),
                                       ('PCM', pcm, 'u32', 'u32'), ('HISTORY', history, 'u32', 'u32')]:
        text += [f'pub const {name}: {type_}[] = [' + ', '.join(str(value) + suffix for value in values) + '];', '']
    (ROOT / 'tests/stdlib/mp3_synthesis_vectors.fern').write_text('\n'.join(text))
    report = {'reference_revision': vectors.tables.REV, 'reference_headers': vectors.tables.SHA,
              'c_source_sha256': hashlib.sha256(source.read_bytes()).hexdigest(),
              'output_sha256': hashlib.sha256(data).hexdigest(), 'channels': channels,
              'pcm_fnv1a': pcm, 'history_fnv1a': history, 'history_samples': 960,
              'samples_per_channel': 576, 'cc_flags': ['-O3', '-ffp-contract=off']}
    (ROOT / 'scripts/audio-reference/mp3-synthesis.json').write_text(json.dumps(report, indent=2) + '\n')


if __name__ == '__main__':
    main()
