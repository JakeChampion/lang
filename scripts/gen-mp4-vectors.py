#!/usr/bin/env python3
"""Freeze independent M4A packets, clocks, edit trimming, and FFmpeg PCM."""
import argparse
import base64
import hashlib
import json
from pathlib import Path
import runpy
import struct
import subprocess
import tempfile
import zlib

ROOT = Path(__file__).resolve().parent.parent
AAC = runpy.run_path(str(ROOT / 'scripts/gen-aac-vectors.py'))


def box(kind, data):
    return struct.pack('>I4s', len(data) + 8, kind) + data


def rewrite(data, change):
    out = b''
    at = 0
    while at < len(data):
        size, kind = struct.unpack_from('>I4s', data, at)
        assert size >= 8 and at + size <= len(data)
        body = data[at + 8:at + size]
        if kind in [b'moov', b'trak', b'mdia', b'minf', b'stbl']:
            body = rewrite(body, change)
        out += change(kind, body)
        at += size
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--keep', type=Path)
    args = parser.parse_args()
    version = subprocess.check_output(['ffmpeg', '-version'], text=True).splitlines()[0]
    text = '// Generated by scripts/gen-mp4-vectors.py.\n// Reference: ' + version + '\n'
    text += 'pub struct Vector { name: string, rate: i32, channels: i32, frames: i32, packets: i32, bytes: string, pcm: string }\n\n'
    smoke = text
    text += 'pub function vectors(): Vector[] {\n  return [\n'
    with tempfile.TemporaryDirectory() as directory:
        temp = Path(directory)
        def freeze(name, data):
            nonlocal text, smoke
            source = temp / 'reference.m4a'
            source.write_bytes(data)
            probe = json.loads(subprocess.check_output(['ffprobe', '-v', 'error', '-select_streams', 'a:0',
                '-show_streams', '-show_packets', '-of', 'json', str(source)]))
            stream = probe['streams'][0]
            raw_probe = json.loads(subprocess.check_output(['ffprobe', '-v', 'error', '-ignore_editlist', '1', '-select_streams', 'a:0', '-show_packets', '-of', 'json', str(source)]))
            rate, channels = int(stream['sample_rate']), int(stream['channels'])
            numerator, denominator = map(int, stream['time_base'].split('/'))
            frames = int(stream['duration_ts']) * numerator * rate // denominator
            AAC['run'](['-i', str(source), '-map', '0:a:0', '-c:a', 'pcm_f32le', '-f', 'f32le', str(temp / 'reference.f32')])
            reference = (temp / 'reference.f32').read_bytes()
            # FFmpeg can emit final codec padding beyond the container duration.
            # The independent track clock, rather than Fern output, bounds PCM.
            assert len(reference) >= frames * channels * 4, name
            reference = reference[:frames * channels * 4]
            packet = base64.b64encode(zlib.compress(data, 9)).decode()
            pcm = base64.b64encode(zlib.compress(reference, 9)).decode()
            row = f'    Vector {{ name: "{name}", rate: {rate}, channels: {channels}, frames: {frames}, packets: {len(raw_probe["packets"])}, bytes: "{packet}", pcm: "{pcm}" }}'
            text += row + ',\n'
            if name == 'silence':
                smoke += 'pub function vector(): Vector {\n  return ' + row.strip() + ';\n}\n'
            print(name, len(data), frames, len(raw_probe['packets']), hashlib.sha256(reference).hexdigest())
            if args.keep:
                args.keep.mkdir(parents=True, exist_ok=True)
                (args.keep / (name + '.m4a')).write_bytes(data)
                (args.keep / (name + '.f32')).write_bytes(reference)

        saved = {}
        for name, rate, channels, frames, mode, flags in [
            ('mono', 44100, 1, 2051, 'tone', []),
            ('stereo-faststart', 48000, 2, 4099, 'tone', ['-movflags', '+faststart']),
            ('surround', 48000, 6, 3077, 'tone', []),
            ('high-rate', 96000, 2, 3073, 'tone', []),
            ('no-edit-list', 44100, 2, 2051, 'tone', ['-use_editlist', '0']),
            ('movie-clock', 44100, 2, 2051, 'tone', ['-movie_timescale', '90000']),
            ('two-audio-tracks', 44100, 2, 2051, 'tone', ['-map', '0:a', '-map', '0:a']),
            ('silence', 44100, 1, 2048, 'silence', []),
        ]:
            (temp / 'input.f32').write_bytes(AAC['signal'](channels, frames, mode))
            AAC['run'](['-f', 'f32le', '-ar', str(rate), '-ac', str(channels), '-i', str(temp / 'input.f32'),
                '-c:a', 'aac', '-b:a', str(64000 * channels), '-aac_pns', '0', '-aac_tns', '0',
                '-map_metadata', '-1', '-fflags', '+bitexact', '-flags:a', '+bitexact', *flags, str(temp / 'encoded.m4a')])
            data = (temp / 'encoded.m4a').read_bytes()
            saved[name] = data
            freeze(name, data)

        AAC['run'](['-f', 'lavfi', '-i', 'color=c=black:size=32x32:rate=10:duration=0.15',
            '-f', 'f32le', '-ar', '44100', '-ac', '2', '-i', str(temp / 'input.f32'),
            '-c:v', 'mpeg4', '-c:a', 'aac', '-b:a', '96000', '-aac_pns', '0', '-shortest',
            '-map_metadata', '-1', '-fflags', '+bitexact', '-flags:a', '+bitexact', str(temp / 'video.mp4')])
        freeze('audio-with-video', (temp / 'video.mp4').read_bytes())

        def co64(kind, body):
            if kind == b'stco':
                count = struct.unpack_from('>I', body, 4)[0]
                values = struct.unpack_from(f'>{count}I', body, 8)
                return box(b'co64', body[:8] + struct.pack(f'>{count}Q', *values))
            return box(kind, body)
        freeze('co64', rewrite(saved['mono'], co64))

        for width in [4, 8, 16]:
            def compact(kind, body):
                if kind != b'stsz':
                    return box(kind, body)
                fixed, count = struct.unpack_from('>II', body, 4)
                values = [fixed] * count if fixed else list(struct.unpack_from(f'>{count}I', body, 12))
                assert all(0 < v < 1 << width for v in values)
                if width == 4:
                    values += [0] * (count % 2)
                    packed = bytes(values[i] << 4 | values[i+1] for i in range(0, len(values), 2))
                else:
                    packed = b''.join(v.to_bytes(width // 8, 'big') for v in values)
                return box(b'stz2', body[:4] + bytes([0, 0, 0, width]) + struct.pack('>I', count) + packed)
            freeze(f'compact-size-{width}', rewrite(saved['silence' if width < 16 else 'mono'], compact))

        def extended(kind, body):
            return struct.pack('>I4sQ', 1, kind, len(body) + 16) + body if kind == b'moov' else box(kind, body)
        freeze('extended-moov', rewrite(saved['mono'], extended))
        def to_end(kind, body):
            return bytes(4) + kind + body if kind == b'moov' else box(kind, body)
        freeze('zero-size-moov', rewrite(saved['mono'], to_end))
    text += '  ];\n}\n'
    target = ROOT / 'tests/stdlib/mp4_vectors.fern'
    if args.check:
        if not target.exists() or target.read_text() != text:
            parser.exit(1, 'MP4 vectors are stale; run scripts/gen-mp4-vectors.py\n')
    else:
        target.write_text(text)
    target = ROOT / 'tests/stdlib/mp4_smoke_vectors.fern'
    if args.check:
        if not target.exists() or target.read_text() != smoke:
            parser.exit(1, 'MP4 smoke vectors are stale; run scripts/gen-mp4-vectors.py\n')
    else:
        target.write_text(smoke)


if __name__ == '__main__':
    main()
