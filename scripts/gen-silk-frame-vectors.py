#!/usr/bin/env python3
"""Freeze SILK frame stages from pinned libopus and Pion reference results."""
import argparse
import json
from pathlib import Path
import runpy
import subprocess

ROOT = Path(__file__).resolve().parent.parent
REFERENCE = runpy.run_path(str(Path(__file__).with_name('gen-silk-predict-vectors.py')))
TABLES = runpy.run_path(str(Path(__file__).with_name('gen-silk-tables.py')))
DRIVER = r'''
package silk
import "fmt"

func fernRow(row []int32) {fmt.Printf("%d, ",len(row));for _,v:=range row {fmt.Printf("%d, ",v)};fmt.Println()}
func FernFrameReference() {
 fmt.Println("\npub const FRAMES: i32[] = [")
 seed:=uint32(1234567)
 for _,rate:=range []int{8,12,16} {
  d:=NewDecoder();bandwidth:=BandwidthNarrowband;if rate==12 {bandwidth=BandwidthMediumband};if rate==16 {bandwidth=BandwidthWideband}
  for frame:=0;frame<12;frame++ {
   duration:=10;if frame%3!=0 {duration=20}
   active:=frame%4!=0;independent:=frame%3==0;skip:=frame%5==0
   packet:=make([]byte,256);for i:=range packet {seed=seed*1664525+1013904223;packet[i]=byte(seed>>24)}
   d.rangeDecoder.Init(packet)
   out:=make([]float32,rate*duration)
   if err:=d.decodeFrame(out,active,duration*1000000,bandwidth,independent,skip);err!=nil {panic(err)}
   flag:=func(v bool) int {if v{return 1};return 0}
   fmt.Printf("  %d, %d, %d, %d, %d, %d, ",rate,duration,flag(active),flag(independent),flag(skip),int32(d.rangeDecoder.FinalRange()))
   p:=make([]int32,len(packet));for i,v:=range packet {p[i]=int32(v)};fernRow(p)
   fernRow(d.gainQ16Int[:duration/5])
   lsf:=make([]int32,len(d.n0Q15));for i,v:=range d.n0Q15 {lsf[i]=int32(v)};fernRow(lsf)
   first:=[]int32{};if len(d.aQ12Sets)>1 {for _,v:=range d.aQ12Int[0] {first=append(first,int32(v))}};fernRow(first)
   lpc:=[]int32{};for _,v:=range d.aQ12Int[len(d.aQ12Sets)-1] {lpc=append(lpc,int32(v))};fernRow(lpc)
   pitch:=[]int32{};if d.isPreviousFrameVoiced {for _,v:=range d.pitchLags[:duration/5] {pitch=append(pitch,int32(v))}};fernRow(pitch)
   ltp:=[]int32{};if d.isPreviousFrameVoiced {for _,row:=range d.bQ7[:duration/5] {for _,v:=range row {ltp=append(ltp,int32(v))}}};fernRow(ltp)
   padded:=(rate*duration+15)/16*16;fernRow(d.eRaw[:padded]);fernRow(d.eQ23[:padded])
   pcm:=[]int32{};for _,v:=range d.fixedPCM[:len(out)] {pcm=append(pcm,int32(v))};fernRow(pcm)
  }
 }
 fmt.Println("];")
}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-dir', type=Path, required=True)
    parser.add_argument('--output', type=Path, default=ROOT/'tests/stdlib/opus_silk_frame_vectors.fern')
    parser.add_argument('--fern', type=Path, default=ROOT/'bin/fern-selfhost')
    args = parser.parse_args()
    def fixture(name):
        data = subprocess.check_output(['git', '-C', str(args.source_dir), 'show',
                                        REFERENCE['REV']+':testdata/short-plc/'+name+'.json'])
        value = json.loads(data)
        if value['pin'] != '22244de5a79bd1d6d623c32e72bf1954b56235be':
            raise ValueError('libopus fixture pin mismatch')
        return value
    frame, stages = fixture('silk-first-frame'), fixture('silk-stage')
    lines = ['// Generated by scripts/gen-silk-frame-vectors.py.',
             '// libopus 22244de5a79bd1d6d623c32e72bf1954b56235be, BSD-3-Clause.',
             '// Pion Opus '+REFERENCE['REV']+', MIT and BSD-3-Clause.', '']
    declare = TABLES['declaration']
    lines += declare('LIBOPUS_PACKET', list(bytes.fromhex(frame['packet'])[3:-1]), 'u8')
    lines += [f'pub const LIBOPUS_RANGE: u32 = {frame["range"]}u32;', '']
    for key, values in stages.items():
        if isinstance(values, list):
            lines += declare('LIBOPUS_'+key.upper(), values, 'i32')
    random_frames = REFERENCE['reference'](args.source_dir, DRIVER, 'FernFrameReference').decode()
    args.output.write_text('\n'.join(lines)+random_frames)
    subprocess.run([str(args.fern), '-fmt', '-w', str(args.output)], check=True)


if __name__ == '__main__':
    main()
