#!/usr/bin/env python3
"""Regenerate the data behind f64 pow's non-integral path in std/f64.

    uv run --no-project scripts/gen_pow_table.py
    uv run --no-project scripts/gen_pow_table.py --check

The algorithm is the no-FMA pow of glibc (since 2.28) and ARM's
optimized-routines: log|x| as hi + lo to about 2^-68, the product y log|x| as
hi + lo, and an exp that takes the low part as a correction.

    x = 2^k z, z in [0x1.69555p-1, 0x1.69555p0), split into N subintervals by
    the top log2(N) bits of the integer (bits(x) - LOG_OFF)
    log(x) = k ln2 + log(c) + log1p(r),  r = z invc - 1

Unlike log's table, invc is a multiple of 1/N (or of 1/2N, above 1) close to
1/c, so it has at most 8 significant bits and z invc - 1 is exact once z is
split in two. Both rows around z = 1 have c = 1, so log(c) is zero there and
x near 1 keeps its relative accuracy: pow multiplies log's absolute error by y.
log(c) is a head on the 2^-43 grid plus a tail, which makes k ln2hi + logc
exact. log1p(r) - r + r^2/2 is a degree-5 polynomial in r times r^3, fitted on
error relative to log1p(r).

    exp(x) = 2^(k/N) exp(r),  k = rint(x N / ln2),  r = x - k ln2/N

2^(i/N) is a double plus a relative tail, and exp(r) - 1 - r is a cubic in r
times r^2 on |r| <= ln2/2N plus the reach of the low part pow hands it. ln2/N
is split so k ln2hi/N is exact for every k the range allows.

The polynomials are minimax, fitted with gen_log_table's Remez exchange in
60-digit decimal arithmetic, and the tables are computed at the same
precision. Nothing here is transcribed.
"""
import argparse
import decimal
import os
import sys
from decimal import Decimal as D

import gen_log_table as base
from gen_log_table import dec, f64, literal, log1p, tail

TARGET = base.TARGET
BEGIN = "// >>> generated by scripts/gen_pow_table.py — do not edit by hand"
END = "// <<< generated by scripts/gen_pow_table.py"

N = 128
TABLE_BITS = 7
LOG_OFF = 0x3FE6955500000000
SUB = 1 << (52 - TABLE_BITS)
LOGC_GRID = 43  # logc is a multiple of 2^-43
LN2HI_GRID = 42  # k * ln2hi is exact for |k| < 2^11
LOG_DEGREE = 5  # coefficients of r^3 .. r^8
EXP_DEGREE = 3  # coefficients of r^2 .. r^5
EXP_HI_BITS = 35  # k * ln2hi/N is exact for |k| < 2^18
EXP_TAIL_REACH = D(2) ** -14  # |r| beyond ln2/2N that pow's low part adds

LN2 = D(2).ln()


def on_grid(v, grid):
    units = (v * D(2) ** grid).to_integral_value(rounding=decimal.ROUND_HALF_EVEN)
    hi = float(units) / 2.0**grid
    assert dec(hi) * D(2) ** grid == units
    return hi


def round_bits(v, bits):
    """v rounded to the given number of significant bits."""
    e = v.adjusted()  # decimal exponent, only to pick a binary one near it
    b = int(e * 3.321928094887362)
    while D(2) ** (b + 1) <= abs(v):
        b += 1
    while D(2) ** b > abs(v):
        b -= 1
    return on_grid(v, bits - 1 - b)


def build_log_table():
    rows = []
    rmax = D(0)
    for i in range(N):
        zlo, zhi = dec(f64(LOG_OFF + i * SUB)), dec(f64(LOG_OFF + (i + 1) * SUB))
        center = (zlo + zhi) / 2
        if center < 1:
            invc = float((N / center).to_integral_value(rounding=decimal.ROUND_HALF_EVEN) / N)
        else:
            invc = float((2 * N / center).to_integral_value(rounding=decimal.ROUND_HALF_EVEN) / (2 * N))
        ic = dec(invc)
        rmax = max(rmax, abs(zlo * ic - 1), abs(zhi * ic - 1))
        logc = (1 / ic).ln() if invc != 1.0 else D(0)
        logc_hi = on_grid(logc, LOGC_GRID)
        logc_lo = float(logc - dec(logc_hi))
        rows.append((invc, logc_hi, logc_lo))
    return rows, rmax


def exp_tail(r):
    """(exp(r) - 1 - r) / r^2, by its series."""
    total = D(0)
    term = D(1) / 2
    n = 2
    eps = D(10) ** -(decimal.getcontext().prec + 2)
    while abs(term) >= eps:
        total += term
        n += 1
        term = term * r / n
    return total


def build_exp_table():
    rows = []
    for i in range(N):
        v = (LN2 * i / N).exp()
        scale = float(v)
        rows.append((scale, float(v / dec(scale) - 1)))
    return rows


def generate():
    rows, rmax = build_log_table()
    rfit = float(rmax * D("1.0001"))
    log_w = lambda r: abs(r**3 / log1p(r))
    log_cs, _ = base.remez(-rfit, rfit, LOG_DEGREE, log_w)
    log_poly = base.round_coeffs(log_cs)
    log_err = base.max_err(log_poly, -rfit, rfit, log_w)

    ln2n = LN2 / N
    efit = float(ln2n / 2 + EXP_TAIL_REACH)
    exp_w = lambda r: r * r
    exp_cs, _ = base.remez(-efit, efit, EXP_DEGREE, exp_w, f=exp_tail)
    exp_poly = base.round_coeffs(exp_cs)
    exp_err = base.max_err(exp_poly, -efit, efit, exp_w, f=exp_tail)

    ln2hi = on_grid(LN2, LN2HI_GRID)
    ln2n_hi = round_bits(ln2n, EXP_HI_BITS)
    return {
        "log_rows": rows,
        "rmax": rmax,
        "log_poly": log_poly,
        "log_err": log_err,
        "ln2hi": ln2hi,
        "ln2lo": float(LN2 - dec(ln2hi)),
        "exp_rows": build_exp_table(),
        "exp_poly": exp_poly,
        "exp_err": exp_err,
        "efit": efit,
        "invln2n": float(N / LN2),
        "ln2n_hi": ln2n_hi,
        "ln2n_lo": float(ln2n - dec(ln2n_hi)),
    }


def render_fern_region(g, indent):
    out = [indent + BEGIN]
    w = lambda ln="": out.append((indent + ln).rstrip())

    def array_fn(name, vals, per_line):
        w("function %s(): f64[] {" % name)
        w("  return [")
        for k in range(0, len(vals), per_line):
            w("    " + " ".join(literal(v) + "," for v in vals[k : k + per_line]))
        w("  ];")
        w("}")

    def const_fn(name, v):
        w("function %s(): f64 {" % name)
        w("  return %s;" % literal(v))
        w("}")
        w()

    w("// _pow_log_poly is log1p(r) - r + r^2/2 over r^3, coefficients of r^0 .. r^%d," % LOG_DEGREE)
    w("// minimax on error relative to log1p(r) over |r| <= %.6g. Max relative" % float(g["rmax"]))
    w("// error after rounding: 2^%.1f." % base.log2_of(g["log_err"]))
    array_fn("_pow_log_poly", g["log_poly"], 3)
    w()
    w("// _pow_invc, _pow_logc and _pow_logctail are the %d rows of the log table:" % N)
    w("// row i covers the z whose bits(z) - bits(0x1.69555p-1) has i in its top %d" % TABLE_BITS)
    w("// mantissa bits, invc is a multiple of 1/%d (1/%d above 1) near 1/c, and" % (N, 2 * N))
    w("// logc + logctail is log(c) with logc on the 2^-%d grid." % LOGC_GRID)
    for col, name in enumerate(["_pow_invc", "_pow_logc", "_pow_logctail"]):
        array_fn(name, [row[col] for row in g["log_rows"]], 4)
        w()
    w("// ln2 as a head on the 2^-%d grid and a tail." % LN2HI_GRID)
    const_fn("_pow_ln2hi", g["ln2hi"])
    const_fn("_pow_ln2lo", g["ln2lo"])
    w("// _pow_exp_poly is (exp(r) - 1 - r) / r^2, coefficients of r^0 .. r^%d, minimax" % EXP_DEGREE)
    w("// on absolute error of exp(r) over |r| <= %.6g. Max error after" % g["efit"])
    w("// rounding: 2^%.1f." % base.log2_of(g["exp_err"]))
    array_fn("_pow_exp_poly", g["exp_poly"], 4)
    w()
    w("// %d / ln2, and ln2 / %d as a %d-bit head and a tail." % (N, N, EXP_HI_BITS))
    const_fn("_pow_invln2n", g["invln2n"])
    const_fn("_pow_ln2n_hi", g["ln2n_hi"])
    const_fn("_pow_ln2n_lo", g["ln2n_lo"])
    w("// _pow_exp2 and _pow_exp2tail are 2^(i/%d) as a double and the relative tail" % N)
    w("// 2^(i/%d) / exp2 - 1." % N)
    for col, name in enumerate(["_pow_exp2", "_pow_exp2tail"]):
        array_fn(name, [row[col] for row in g["exp_rows"]], 4)
        w()
    out.append(indent + END)
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if the output is stale instead of writing it")
    args = ap.parse_args()
    g = generate()
    with open(TARGET, encoding="utf-8") as f:
        text = f.read()
    want = base.regenerated(text, lambda ind: render_fern_region(g, ind), BEGIN, END)
    if want is None:
        print("%s: expected exactly one %r ... %r region" % (os.path.relpath(TARGET, base.ROOT), BEGIN, END), file=sys.stderr)
        return 1
    return 0 if base.check_or_write(TARGET, want, args.check, "gen_pow_table.py") else 1


if __name__ == "__main__":
    sys.exit(main())
