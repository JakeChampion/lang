#!/usr/bin/env python3
"""Generate examples/markdown/entities.fern: the HTML5 named character
references and the Unicode punctuation ranges of CommonMark 0.31.2."""
import argparse
import html.entities
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'examples/markdown/entities.fern'


def literal(s):
    """A Fern string literal in the form that `fern -fmt` writes."""
    out = []
    for ch in s:
        if ch == '"' or ch == '\\':
            out.append('\\' + ch)
        elif ch in '\n\t':
            out.append({'\n': '\\n', '\t': '\\t'}[ch])
        elif unicodedata.category(ch) in ('Cc', 'Cf', 'Zl', 'Zp') or unicodedata.category(ch) == 'Zs' and ch != ' ':
            out.append('\\u{%04X}' % ord(ch))
        else:
            out.append(ch)
    return '"' + ''.join(out) + '"'


def rows(items, per):
    return ',\n  '.join(', '.join(items[i:i + per]) for i in range(0, len(items), per))


def punctuation_ranges():
    ranges = []
    for c in range(0x80, sys.maxunicode + 1):
        if unicodedata.category(chr(c))[0] in 'PS':
            if ranges and ranges[-1][1] == c - 1:
                ranges[-1][1] = c
            else:
                ranges.append([c, c])
    return ranges


def generate():
    names = sorted(k[:-1] for k in html.entities.html5 if k.endswith(';'))
    assert len(names) == 2125
    values = [html.entities.html5[n + ';'] for n in names]
    ranges = punctuation_ranges()
    flat = [str(v) for r in ranges for v in r]
    return f'''// Generated by scripts/gen-markdown-tables.py. DO NOT EDIT.
//
// The named character references of the HTML Standard (WHATWG), each name
// without its `;`, sorted by byte, and the characters that each one gives.
// See licenses/commonmark/NOTICE.txt.

pub const ENTITY_NAMES: string[] = [
  {rows([literal(n) for n in names], 8)},
];

pub const ENTITY_VALUES: string[] = [
  {rows([literal(v) for v in values], 8)},
];

// The characters above U+007F in the general categories P and S of Unicode
// {unicodedata.unidata_version}: the first and the last code point of each range.
pub const PUNCT_RANGES: i32[] = [
  {rows(flat, 12)},
];
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generate()
    if args.check:
        if OUT.read_text() != text:
            parser.exit(1, 'examples/markdown/entities.fern is stale; run scripts/gen-markdown-tables.py\n')
        return
    OUT.write_text(text)


if __name__ == '__main__':
    main()
