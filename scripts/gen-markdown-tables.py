#!/usr/bin/env python3
"""Generate internal/stdlib/std/markdown/entities.fern: the HTML5 named character
references, and the Unicode punctuation and symbol ranges of cmark 0.31.2.

The ranges come from cmark_utf8proc_is_punctuation_or_symbol in the
src/utf8.c of a cmark 0.31.2 source tree, which --cmark names. The Unicode
data of Python can be of a different version."""
import argparse
import html.entities
import re
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'internal/stdlib/std/markdown/entities.fern'


def literal(s):
    """A Fern string literal in the form that `fern -fmt` writes."""
    out = []
    for ch in s:
        if ch == '"' or ch == '\\':
            out.append('\\' + ch)
        elif ch in '\n\t':
            out.append({'\n': '\\n', '\t': '\\t'}[ch])
        elif unicodedata.category(ch) in ('Cc', 'Cf', 'Zl', 'Zp') or unicodedata.category(ch) == 'Zs' and ch != ' ':
            out.append('\\u{%04X}' % ord(ch))
        else:
            out.append(ch)
    return '"' + ''.join(out) + '"'


def rows(items, per):
    return ',\n  '.join(', '.join(items[i:i + per]) for i in range(0, len(items), per))


def punctuation_ranges(cmark):
    """The ranges of the test of cmark for a code point above U+007F."""
    src = (Path(cmark) / 'src/utf8.c').read_text()
    body = src[src.index('int cmark_utf8proc_is_punctuation_or_symbol'):]
    body = body[body.index('} else {'):body.index('\n}\n')]
    ranges = []
    for lo, hi, one in re.findall(r'\(uc >= (\d+) && uc <= (\d+)\)|\(uc == (\d+)\)', body):
        r = [int(one), int(one)] if one else [int(lo), int(hi)]
        if ranges and ranges[-1][1] == r[0] - 1:
            ranges[-1][1] = r[1]
        else:
            ranges.append(r)
    assert all(a[1] < b[0] for a, b in zip(ranges, ranges[1:]))
    return ranges


def generate(cmark):
    names = sorted(k[:-1] for k in html.entities.html5 if k.endswith(';'))
    assert len(names) == 2125
    values = [html.entities.html5[n + ';'] for n in names]
    ranges = punctuation_ranges(cmark)
    flat = [str(v) for r in ranges for v in r]
    return f'''// Generated by scripts/gen-markdown-tables.py. DO NOT EDIT.
//
// The named character references of the HTML Standard (WHATWG), each name
// without its `;`, sorted by byte, and the characters that each one gives.
// See licenses/commonmark/NOTICE.txt.

pub const ENTITY_NAMES: string[] = [
  {rows([literal(n) for n in names], 8)},
];

pub const ENTITY_VALUES: string[] = [
  {rows([literal(v) for v in values], 8)},
];

// The characters above U+007F that cmark 0.31.2 takes as punctuation or as a
// symbol: the first and the last code point of each range.
pub const PUNCT_RANGES: i32[] = [
  {rows(flat, 12)},
];
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--cmark', required=True, help='a cmark 0.31.2 source tree')
    args = parser.parse_args()
    text = generate(args.cmark)
    if args.check:
        if OUT.read_text() != text:
            parser.exit(1, 'internal/stdlib/std/markdown/entities.fern is stale; run scripts/gen-markdown-tables.py\n')
        return
    OUT.write_text(text)


if __name__ == '__main__':
    main()
