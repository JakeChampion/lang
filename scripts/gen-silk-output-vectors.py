#!/usr/bin/env python3
"""Freeze SILK output checksums from the pinned libopus review corpus."""
import argparse
import gzip
import json
from pathlib import Path
import runpy
import struct
import subprocess
import zlib

ROOT = Path(__file__).resolve().parent.parent
REFERENCE = runpy.run_path(str(Path(__file__).with_name('gen-silk-predict-vectors.py')))
TABLES = runpy.run_path(str(Path(__file__).with_name('gen-silk-tables.py')))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-dir', type=Path, required=True)
    parser.add_argument('--output', type=Path)
    parser.add_argument('--loss', action='store_true', help='include complete SILK cases with loss and recovery')
    parser.add_argument('--fern', type=Path, default=ROOT/'bin/fern-selfhost')
    args = parser.parse_args()
    if args.output is None:
        args.output = ROOT/('tests/stdlib/opus_silk_recovery_vectors.fern' if args.loss else 'tests/stdlib/opus_silk_output_vectors.fern')
    data = subprocess.check_output(['git', '-C', str(args.source_dir), 'show',
                                    REFERENCE['REV']+':testdata/short-plc/review-corpus.json.gz'])
    corpus = json.loads(gzip.decompress(data))
    if corpus['pin'] != '22244de5a79bd1d6d623c32e72bf1954b56235be':
        raise ValueError('libopus reference pin mismatch')
    rows, cases, packets = [], 0, 0
    for case in corpus['cases']:
        prefix = []
        if args.loss:
            if any(int(step['packet'][:2], 16) >= 96 for step in case['steps'] if step.get('packet')):
                continue
            prefix = case['steps']
        for step in case['steps']:
            if args.loss:
                break
            if not step.get('packet') or int(step['packet'][:2], 16) >= 96:
                break
            prefix.append(step)
        if not prefix:
            continue
        cases += 1
        rows.extend([case['rate'], case['channels'], len(prefix)])
        for step in prefix:
            packet = bytes.fromhex(step.get('packet') or '')
            samples = step['pcm']
            checksum = zlib.crc32(struct.pack('<'+'h'*len(samples), *samples))
            signed = lambda value: value if value < 2147483648 else value - 4294967296
            rows.extend([len(packet), *packet, len(samples), signed(checksum), signed(step['range']), *samples[:8], *samples[-8:]])
            packets += 1
    if (cases, packets) != (50, 600 if args.loss else 150):
        raise ValueError('unexpected SILK prefix coverage')
    lines = ['// Generated by scripts/gen-silk-output-vectors.py.',
             '// libopus 22244de5a79bd1d6d623c32e72bf1954b56235be, BSD-3-Clause.',
             '// Corpus from Pion Opus '+REFERENCE['REV']+', MIT.', '']
    lines += TABLES['declaration']('PACKETS', rows, 'i32')
    args.output.write_text('\n'.join(lines))
    subprocess.run([str(args.fern), '-fmt', '-w', str(args.output)], check=True)


if __name__ == '__main__':
    main()
