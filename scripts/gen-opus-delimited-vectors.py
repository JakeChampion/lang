#!/usr/bin/env python3
"""Freeze self-delimited packet boundaries from pinned, unmodified libopus."""
import argparse
import base64
import json
from pathlib import Path
import runpy
import struct
import subprocess
import zlib

ROOT = Path(__file__).resolve().parent.parent
REFERENCE = runpy.run_path(str(Path(__file__).with_name('gen-silk-loss-vectors.py')))


def generate(records):
    if len(records) != 1896:
        raise ValueError('unexpected delimited packet count')
    lines = ['// Generated by scripts/gen-opus-delimited-vectors.py.',
             '// Unmodified libopus '+REFERENCE['PIN']+'.',
             '// Each zlib/base64 group contains input and complete packet boundaries.',
             '', 'pub const CASES: string[] = [']
    for start in range(0, len(records), 32):
        rows = records[start:start+32]
        data = bytearray(struct.pack('<I', len(rows)))
        for row in rows:
            raw = bytes.fromhex(row['bytes'])
            data.extend(struct.pack('<I', len(raw)))
            data.extend(raw)
            data.extend(struct.pack('<i', row['count']))
            if row['count'] >= 0:
                data.extend(struct.pack('<IIIII', row['consumed'], row['offset'], row['padding'], row['toc'], row['crc']))
                data.extend(struct.pack('<'+'I'*row['count'], *row['sizes']))
        lines.append('  '+json.dumps(base64.b64encode(zlib.compress(data, 9)).decode('ascii'))+',')
    return '\n'.join(lines+['];', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--archive', type=Path)
    parser.add_argument('--cmake', default='cmake')
    parser.add_argument('--fern', type=Path, default=ROOT/'bin/fern-selfhost')
    parser.add_argument('--output', type=Path, default=ROOT/'tests/stdlib/opus_delimited_vectors.fern')
    args = parser.parse_args()
    records = REFERENCE['reference'](args.archive, args.cmake, 'opus_delimited.c')
    args.output.write_text(generate(records))
    subprocess.run([str(args.fern), '-fmt', '-w', str(args.output)], check=True)


if __name__ == '__main__':
    main()
