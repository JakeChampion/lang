#!/usr/bin/env python3
"""Freeze raw AAC codewords and an independent C double-precision transform oracle."""
import argparse
import base64
import hashlib
from pathlib import Path
import runpy
import struct
import subprocess
import tempfile
import zlib

ROOT = Path(__file__).resolve().parent.parent
TABLES = runpy.run_path(str(ROOT / 'scripts/gen-aac-tables.py'))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-dir', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = TABLES['reference']('codebooks.rs', args.source_dir)
    words = []
    for book in range(12):
        prefix = 'SCF_CODEBOOK' if book == 0 else f'SPECTRUM_CODEBOOK{book}'
        lengths = TABLES['array'](source, prefix + '_LENS')
        codes = TABLES['array'](source, prefix + '_CODES')
        words.extend((book, symbol, code, width) for symbol, (code, width) in enumerate(zip(codes, lengths)))
    raw = struct.pack('<I', len(words)) + b''.join(struct.pack('<4I', *word) for word in words)
    oracle = ROOT / 'scripts/audio-reference/aac-kernels.c'
    with tempfile.TemporaryDirectory() as directory:
        executable = Path(directory) / 'oracle'
        subprocess.run(['cc', '-O2', '-ffp-contract=off', str(oracle), '-lm', '-o', str(executable)], check=True)
        raw += subprocess.check_output([str(executable)])
    encoded = base64.b64encode(zlib.compress(raw, 9)).decode()
    text = ('// Generated by scripts/gen-aac-kernel-vectors.py.\n'
            '// Raw codewords: Symphonia ' + TABLES['PIN'] + ' (MPL-2.0).\n'
            '// Copyright (c) 2019-2023 The Project Symphonia Developers.\n'
            '// See licenses/aac/MPL-2.0.txt and licenses/aac/NOTICE.txt.\n'
            '// Transform oracle SHA-256: ' + hashlib.sha256(oracle.read_bytes()).hexdigest() + '\n'
            '// Uncompressed vector SHA-256: ' + hashlib.sha256(raw).hexdigest() + '\n'
            'pub const DATA: string = "' + encoded + '";\n')
    target = ROOT / 'tests/stdlib/aac_kernel_vectors.fern'
    if args.check:
        if not target.exists() or target.read_text() != text:
            parser.exit(1, 'AAC kernel vectors are stale; run scripts/gen-aac-kernel-vectors.py\n')
    else:
        target.write_text(text)
    print(f'{len(words)} codewords, {len(raw)} reference bytes, {len(encoded)} encoded bytes')


if __name__ == '__main__':
    main()
