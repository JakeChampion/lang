#!/usr/bin/env python3
"""Write internal/stdlib/std/shape/presentation.fern: the Arabic presentation forms
from which the Arabic fallback of HarfBuzz makes its lookups.

Run:  python3 -I scripts/gen-arabic-table.py UCDDIR

UCDDIR holds UnicodeData.txt of the Unicode Character Database
(https://www.unicode.org/Public/UCD/latest/ucd/). The script follows the
shaping table of src/gen-arabic-table.py of HarfBuzz 15: the same
ligatures, the same three ligatures of the private use area, and the same
order of the ligatures.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "internal" / "stdlib" / "std" / "shape" / "presentation.fern"

# The ligatures that HarfBuzz makes.
LIGATURES = (
    0xF2EE, 0xFC08, 0xFC0E, 0xFC12, 0xFC32, 0xFC3F, 0xFC40, 0xFC41, 0xFC42,
    0xFC43, 0xFC44, 0xFC4E, 0xFC5E, 0xFC60, 0xFC61, 0xFC62, 0xFC6A, 0xFC6D,
    0xFC6F, 0xFC70, 0xFC73, 0xFC75, 0xFC86, 0xFC8F, 0xFC91, 0xFC94, 0xFC9C,
    0xFC9D, 0xFC9E, 0xFC9F, 0xFCA1, 0xFCA2, 0xFCA3, 0xFCA4, 0xFCA8, 0xFCAA,
    0xFCAC, 0xFCB0, 0xFCC9, 0xFCCA, 0xFCCB, 0xFCCC, 0xFCCD, 0xFCCE, 0xFCCF,
    0xFCD0, 0xFCD1, 0xFCD2, 0xFCD3, 0xFCD5, 0xFCDA, 0xFCDB, 0xFCDC, 0xFCDD,
    0xFD30, 0xFD88, 0xFEF5, 0xFEF6, 0xFEF7, 0xFEF8, 0xFEF9, 0xFEFA, 0xFEFB,
    0xFEFC, 0xF201, 0xF211, 0xF2EE,
)

# The ligatures of the private use area that HarfBuzz adds.
PUA = [
    "F201;PUA ARABIC LIGATURE LELLAH ISOLATED FORM;Lo;0;AL;<isolated> 0644 0644 0647;;;;N;;;;;",
    "F211;PUA ARABIC LIGATURE LAM WITH MEEM WITH JEEM INITIAL FORM;Lo;0;AL;<initial> 0644 0645 062C;;;;N;;;;;",
    "F2EE;PUA ARABIC LIGATURE SHADDA WITH FATHATAN ISOLATED FORM;Lo;0;AL;<isolated> 0020 064B 0651;;;;N;;;;;",
]

SHAPES = ["initial", "medial", "final", "isolated"]


def shaping_table(lines):
    """The forms of each letter, and the ligatures of two letters, of a
    letter and a mark, and of three letters, as HarfBuzz reads them."""
    shapes, ligatures = {}, {}
    for line in lines:
        fields = [x.strip() for x in line.split(";")]
        if fields[5][0:1] != "<":
            continue
        items = fields[5].split(" ")
        shape, items = items[0][1:-1], tuple(int(x, 16) for x in items[1:])
        c = int(fields[0], 16)
        if shape not in SHAPES:
            continue
        if len(items) != 1:
            # A mark ligature starts with a space and is in visual order.
            if items[0] == 0x0020:
                items = items[:0:-1]
                shape = None
            if c not in LIGATURES:
                continue
            ligatures.setdefault(items, {})[shape] = c
        else:
            shapes.setdefault(items[0], {})[shape] = c
    ligas_2, ligas_3, ligas_mark_2 = {}, {}, {}
    for key, by_shape in ligatures.items():
        for shape, c in by_shape.items():
            if len(key) == 3:
                first, second, third = ({"isolated": ("initial", "medial", "final"), "final": ("medial", "medial", "final"),
                                         "initial": ("initial", "medial", "medial")}[shape])
                liga = (shapes[key[0]][first], shapes[key[1]][second], shapes[key[2]][third])
                ligas_3.setdefault(liga[0], []).append((liga[1], liga[2], c))
            elif shape is None:
                ligas_mark_2.setdefault(key[0], []).append((key[1], c))
            else:
                first, second = {"isolated": ("initial", "final"), "final": ("medial", "final"), "initial": ("initial", "medial")}[shape]
                liga = (shapes[key[0]][first], shapes[key[1]][second])
                ligas_2.setdefault(liga[0], []).append((liga[1], c))
    return shapes, ligas_2, ligas_mark_2, ligas_3


def array(name, comment, values, per_line):
    lines = comment + ["const %s: i32[] = [" % name]
    for k in range(0, len(values), per_line):
        lines.append("  " + ", ".join("0x%04X" % v for v in values[k:k + per_line]) + ",")
    return lines + ["];", ""]


def flat(table):
    out = []
    for first in sorted(table):
        for liga in table[first]:
            out += [first, *liga]
    return out


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    path = Path(sys.argv[1]) / "UnicodeData.txt"
    shapes, ligas_2, ligas_mark_2, ligas_3 = shaping_table(path.read_text(encoding="utf-8").splitlines() + PUA)
    first, last = min(shapes), max(shapes)
    forms = []
    for u in range(first, last + 1):
        forms += [shapes.get(u, {}).get(shape, 0) for shape in SHAPES]
    lines = [
        "// Generated by scripts/gen-arabic-table.py from the Unicode Character",
        "// Database -- do not edit by hand.",
        "//",
        "// The Arabic presentation forms from which the Arabic fallback of HarfBuzz",
        "// makes its lookups, in the order of HarfBuzz.",
        "",
        "// The first letter of FORMS.",
        "const FIRST: i32 = 0x%04X;" % first,
        "",
    ]
    lines += array("FORMS", ["// The initial, the medial, the final and the isolated form of each letter",
                             "// from FIRST, or 0."], forms, 8)
    lines += array("LIGATURES_3", ["// The ligatures of three letters: the forms of the letters, then the",
                                   "// ligature."], flat(ligas_3), 8)
    lines += array("LIGATURES_2", ["// The ligatures of two letters: the forms of the letters, then the",
                                   "// ligature."], flat(ligas_2), 9)
    lines += array("MARK_LIGATURES", ["// The ligatures of two marks: the marks, then the ligature."], flat(ligas_mark_2), 9)
    lines += [
        "// The form of the letter `u` for the feature `feature`: 0 for init, 1 for",
        "// medi, 2 for fina and 3 for isol. It is 0 when the letter has no such",
        "// form.",
        "pub function form(u: i32, feature: i32): i32 {",
        "  let k = 4 * (u - FIRST) + feature;",
        "  return if (u < FIRST || k >= FORMS.len()) { 0 } else { FORMS[k] };",
        "}",
        "",
        "// The letters of FORMS: the first and the last.",
        "pub function letters(): (i32, i32) {",
        "  return (FIRST, FIRST + FORMS.len() / 4 - 1);",
        "}",
        "",
        "// The ligatures of three letters, of two letters or of two marks for `kind`",
        "// 0, 1 or 2, as LIGATURES_3, LIGATURES_2 and MARK_LIGATURES hold them.",
        "pub function ligatures(kind: i32): i32[] {",
        "  return if (kind == 0) { LIGATURES_3 } else if (kind == 1) { LIGATURES_2 } else { MARK_LIGATURES };",
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
