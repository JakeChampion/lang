#!/usr/bin/env python3
"""Freeze SILK redundant frames and subsequent packets from pinned libopus."""
import argparse
from pathlib import Path
import runpy
import struct
import subprocess
import zlib

ROOT = Path(__file__).resolve().parent.parent
REFERENCE = runpy.run_path(str(Path(__file__).with_name('gen-silk-loss-vectors.py')))
TABLES = runpy.run_path(str(Path(__file__).with_name('gen-silk-tables.py')))


def generate(records):
    if len(records) != 240 or {r['case'] for r in records} != set(range(30)):
        raise ValueError('unexpected FEC corpus size')
    pairs = {(r['rate'], r['output_rate']) for r in records}
    if len(pairs) != 15 or {r['duration'] for r in records} != {10, 20, 40, 60}:
        raise ValueError('incomplete FEC rate or duration coverage')
    flags = {(r['duration'], mask) for r in records for mask in r['flags']}
    for duration, count in [(10, 1), (20, 1), (40, 2), (60, 3)]:
        if not all((duration, mask) in flags for mask in range(1 << count)):
            raise ValueError('incomplete redundant frame flag coverage')
    rows = []
    signed = lambda value: value if value < 2147483648 else value - 4294967296
    for row in records:
        packet = bytes.fromhex(row['packet']) if row['fec'] else b''
        samples = row['pcm']
        checksum = zlib.crc32(struct.pack('<'+'h'*len(samples), *samples))
        rows.extend([row['case'], row['rate'], row['output_rate'], row['channels'], row['duration'],
                     row['stream'], row['fec'], len(packet), *packet, len(samples), signed(checksum),
                     signed(row['range']), row['losses'], *samples[:8], *samples[-8:]])
    return '\n'.join(['// Generated by scripts/gen-silk-fec-vectors.py.',
                      '// Unmodified libopus '+REFERENCE['PIN']+', BSD-3-Clause.', '']+
                     TABLES['declaration']('PACKETS', rows, 'i32'))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--archive', type=Path)
    parser.add_argument('--cmake', default='cmake')
    parser.add_argument('--output', type=Path, default=ROOT/'tests/stdlib/opus_silk_fec_vectors.fern')
    parser.add_argument('--fern', type=Path, default=ROOT/'bin/fern-selfhost')
    args = parser.parse_args()
    records = REFERENCE['reference'](args.archive, args.cmake, 'silk_fec.c')
    args.output.write_text(generate(records))
    subprocess.run([str(args.fern), '-fmt', '-w', str(args.output)], check=True)


if __name__ == '__main__':
    main()
