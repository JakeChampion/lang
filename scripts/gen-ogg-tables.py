#!/usr/bin/env python3
"""Generate the unreflected Ogg CRC-32 table with polynomial 0x04C11DB7."""
import argparse
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent.parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--fern', type=Path, default=ROOT/'bin/fern-selfhost')
    parser.add_argument('--output', type=Path, default=ROOT/'internal/stdlib/std/audio/ogg/tables.fern')
    args = parser.parse_args()
    values = []
    for byte in range(256):
        crc = byte << 24
        for _ in range(8):
            crc = ((crc << 1) ^ (0x04C11DB7 if crc & 0x80000000 else 0)) & 0xffffffff
        values.append(crc)
    lines = ['// Ogg CRC-32 table. Generated by scripts/gen-ogg-tables.py.',
             '// The unreflected polynomial is 0x04C11DB7. The initial checksum is zero.',
             '', 'pub const CRC: u32[] = [']
    for at in range(0, 256, 8):
        lines.append('  '+', '.join(str(v)+'u32' for v in values[at:at+8])+',')
    lines.append('];')
    target = args.output
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text('\n'.join(lines)+'\n')
    subprocess.run([str(args.fern), '-fmt', '-w', str(target)], check=True)


if __name__ == '__main__':
    main()
