#!/usr/bin/env python3
"""Generate SILK tables from a pinned Pion Opus source tree."""
import argparse
import ast
import hashlib
from pathlib import Path
import re
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
REV = 'e7b8aa55508cfd30a968dbc695d4272a8e04f2f2'
HASHES = {'codebook.go': '4e427114f0da27d06cd6b4618243b5bbb87b993ad2f037bae447de61b8919444', 'icdf.go': 'ea7054f47bf8f4aa03e729b89957b2eae18398f050715355fb89b66dd89d65c9'}

def extract(source):
    source = re.sub(r'//[^\n]*', '', source)
    result = {}
    pattern = r'(\w+)\s*=\s*((?:\[[^\]]*\])+)(u?int(?:8|16|32|64)?|float(?:32|64))\s*\{'
    for match in re.finditer(pattern, source):
        dimensions = re.findall(r'\[([^\]]*)\]', match[2])
        if any(dim for dim in dimensions):
            raise ValueError('fixed array dimensions need explicit padding')
        start, end, depth = match.end() - 1, match.end() - 1, 0
        while end < len(source):
            depth += (source[end] == '{') - (source[end] == '}')
            if depth == 0:
                break
            end += 1
        values = ast.literal_eval(source[start:end+1].replace('{', '[').replace('}', ']'))
        result[match[1]] = (len(dimensions), values)
    return result

def inverse_cdf(row):
    if len(row) < 2 or row[0] != 256 or row[-1] != 256:
        raise ValueError('SILK CDF total must be 256')
    if any(type(x) is not int or x < 0 or x > 256 for x in row):
        raise ValueError('invalid SILK CDF entry')
    if row[1:] != sorted(row[1:]):
        raise ValueError('SILK CDF must be monotonic')
    bias = 0
    while row[bias+1] == 0:
        bias += 1
    return [256-x for x in row[bias+1:]], bias

def name_of(name):
    name = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', name)
    return re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', name).upper()

def declaration(name, values, kind):
    if any(type(x) is not int for x in values):
        raise ValueError('table entries must be integers')
    lines = [f'pub const {name}: {kind}[] = [']
    for at in range(0, len(values), 24):
        lines.append('  '+', '.join(str(x) for x in values[at:at+24])+',')
    return lines + ['];', '']

def generate(tables):
    lines = ['// Code generated by scripts/gen-silk-tables.py. DO NOT EDIT.',
             '// Pion Opus '+REV+'. Copyright 2026 The Pion community.',
             '// SPDX-License-Identifier: MIT. See licenses/opus/PION-MIT.txt.', '']
    for original, (depth, values) in tables.items():
        name = name_of(original)
        rows = values if depth == 2 else [values]
        if depth not in (1, 2):
            raise ValueError('unsupported table depth')
        offsets, flat, biases = [0], [], []
        for row in rows:
            data, bias = inverse_cdf(row) if original.startswith('icdf') else (row, 0)
            flat.extend(data)
            offsets.append(len(flat))
            biases.append(bias)
        kind = 'u8' if all(0 <= x <= 255 for x in flat) else 'i32'
        lines += declaration(name, flat, kind)
        if depth == 2:
            lines += declaration(name+'_OFFSETS', offsets, 'i32')
        if any(biases):
            lines += declaration(name+'_BIASES', biases, 'i32')
    return '\n'.join(lines)

def sign_tables(tables):
    signs = []
    for signal in ['Inactive', 'Unvoiced', 'Voiced']:
        for level in ['Low', 'High']:
            for pulse in ['0', '1', '2', '3', '4', '5', '6Plus']:
                key = f'icdfExcitationSign{signal}Signal{level}Quantization{pulse}Pulse'
                inverse, bias = inverse_cdf(tables[key][1])
                if bias or len(inverse) != 2:
                    raise ValueError('unexpected excitation sign distribution')
                signs.extend(inverse)
    return '\n'.join(declaration('EXCITATION_SIGN_ICDFS', signs, 'u8'))

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-dir', type=Path)
    parser.add_argument('--output', type=Path, default=ROOT/'internal/stdlib/std/opus/silk/tables.fern')
    args = parser.parse_args()
    tables = {}
    for file in ['codebook.go', 'icdf.go']:
        data = (args.source_dir/file).read_bytes() if args.source_dir else urllib.request.urlopen(
            f'https://raw.githubusercontent.com/pion/opus/{REV}/internal/silk/{file}', timeout=30).read()
        if hashlib.sha256(data).hexdigest() != HASHES[file]:
            raise ValueError('source hash mismatch: '+file)
        tables.update(extract(data.decode()))
    if len(tables) != 105:
        raise ValueError('unexpected table count')
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generate(tables)+'\n'+sign_tables(tables))

if __name__ == '__main__':
    main()
