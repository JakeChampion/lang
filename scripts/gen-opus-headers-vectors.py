#!/usr/bin/env python3
"""Freeze Opus headers and comments from pinned, unmodified libopusfile."""
import argparse
import base64
import hashlib
import io
import json
from pathlib import Path
import struct
import subprocess
import tarfile
import tempfile
import urllib.request
import zlib

ROOT = Path(__file__).resolve().parent.parent
PINS = {
    'opusfile': ('6dfd29e7adb87f2e193575fc3fa88cbf1a0b27df', '7dcaea4385d9020dc3c02a8d01bce6ba17576bbda4b126434a90d74ba6bec29d'),
    'opus': ('22244de5a79bd1d6d623c32e72bf1954b56235be', '3267aa969b2b26542417f57819a5bc25d5079355300307dd2dddc7c704aed418'),
    'ogg': ('be05b13e98b048f0b5a0f5fa8ce514d56db5f822', 'b2ff5c003e5697507169f7d614d64dc4e8bf030c85ad081bec75c164566f8246'),
}


def head(channels=2, version=1, family=0, streams=1, coupled=1, mapping=None):
    raw = b'OpusHead'+struct.pack('<BBHIhB', version, channels, 312, 44100, -1280, family)
    if family:
        raw += bytes([streams, coupled]) + bytes(mapping if mapping is not None else range(channels))
    return raw


def tags(vendor, comments, suffix=b''):
    return b'OpusTags'+blob(vendor)+struct.pack('<I', len(comments))+b''.join(blob(c) for c in comments)+suffix


def blob(raw):
    return struct.pack('<I', len(raw))+raw


def cases():
    rows = []
    for version in [0, 1, 2, 15, 16, 255]:
        for channels in [0, 1, 2, 3, 8, 9, 255]:
            for family in [0, 1, 2]:
                raw = head(channels, version, family)
                rows.extend([(0, raw), (0, raw+b'future fields')])
    for channels in range(1, 9):
        for streams, coupled in [(0, 0), (1, 0), (1, 1), (2, 1), (4, 4), (8, 0), (1, 2), (255, 0)]:
            for mapped in [0, streams+coupled, 255]:
                rows.append((0, head(channels, family=1, streams=streams, coupled=coupled, mapping=[mapped]*channels)))
    for raw in [head(), head(1), head(8, family=1, streams=5, coupled=3)]:
        rows.extend((0, raw[:at]) for at in range(len(raw)))
        rows.append((0, b'X'+raw[1:]))
    for vendor in [b'', b'libopus 1.6', b'a\x00b\xff\xc0\x80']:
        for comments in [[], [b'TITLE=one'], [b'TITLE=one', b'title=two', b'ARTIST=three'], [b'', b'=empty', b'no equals', b'KEY=\x00\xff'], [b'COMMENT='+b'long'*128]]:
            for suffix in [b'', b'\x00padding', b'\x01\x00\xffbinary', b'\xffprivate']:
                raw = tags(vendor, comments, suffix)
                rows.append((1, raw))
                rows.extend((1, raw[:at]) for at in range(min(len(raw), 40)))
    for raw in [b'OpusTags'+b'\xff'*8, b'OpusTags'+blob(b'x')+b'\xff'*4, tags(b'v', [b'x'])[:-1], b'not opus'+b'\x00'*8]:
        rows.append((1, raw))
    return rows


def reference(args):
    inputs = b''.join(bytes([kind])+blob(raw) for kind, raw in cases())
    with tempfile.TemporaryDirectory() as directory:
        root = Path(directory)
        sources = {}
        for name, (pin, digest) in PINS.items():
            archive = getattr(args, name+'_archive')
            raw = archive.read_bytes() if archive else urllib.request.urlopen(
                f'https://codeload.github.com/xiph/{name}/tar.gz/{pin}', timeout=60).read()
            if hashlib.sha256(raw).hexdigest() != digest:
                raise ValueError(name+' archive hash mismatch')
            with tarfile.open(fileobj=io.BytesIO(raw)) as tar:
                tar.extractall(root, filter='data')
            sources[name] = root/(name+'-'+pin)
        build = root/'ogg-build'
        subprocess.run([args.cmake, '-S', str(sources['ogg']), '-B', str(build), '-DBUILD_TESTING=OFF'],
                       check=True, stdout=subprocess.DEVNULL)
        source = sources['opusfile']
        includes = [source/'include', source/'src', sources['opus']/'include', sources['ogg']/'include', build/'include']
        executable = root/'opus-headers'
        subprocess.run(['cc', '-O2', '-Wall', '-Wextra', '-Wno-parentheses', *['-I'+str(p) for p in includes],
                        str(ROOT/'scripts/audio-reference/opus_headers.c'), str(source/'src/info.c'),
                        str(source/'src/internal.c'), '-o', str(executable)], check=True)
        return [json.loads(line) for line in subprocess.check_output([str(executable)], input=inputs).splitlines()]


def generate(records):
    if len(records) != len(cases()):
        raise ValueError('unexpected Opus header corpus size')
    lines = ['// Generated by scripts/gen-opus-headers-vectors.py.',
             '// Unmodified libopusfile '+PINS['opusfile'][0]+'.',
             '// Each zlib/base64 group contains inputs and complete parsed header fields.',
             '', 'pub const CASES: string[] = [']
    for start in range(0, len(records), 32):
        rows = records[start:start+32]
        data = bytearray(struct.pack('<I', len(rows)))
        for row in rows:
            data.extend(struct.pack('<II', row['kind'], int(row['code'] == 0)))
            data.extend(blob(bytes.fromhex(row['bytes'])))
            if row['code'] == 0:
                if row['kind'] == 0:
                    data.extend(struct.pack('<8q', *row['fields']))
                    data.extend(blob(bytes.fromhex(row['mapping'])))
                else:
                    data.extend(blob(bytes.fromhex(row['vendor'])))
                    data.extend(struct.pack('<I', len(row['comments'])))
                    for comment in row['comments']:
                        data.extend(blob(bytes.fromhex(comment)))
                    data.extend(blob(bytes.fromhex(row['suffix'])))
        lines.append('  '+json.dumps(base64.b64encode(zlib.compress(data, 9)).decode('ascii'))+',')
    return '\n'.join(lines+['];', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in PINS:
        parser.add_argument('--'+name+'-archive', type=Path)
    parser.add_argument('--cmake', default='cmake')
    parser.add_argument('--fern', type=Path, default=ROOT/'bin/fern-selfhost')
    parser.add_argument('--output', type=Path, default=ROOT/'tests/stdlib/opus_headers_vectors.fern')
    args = parser.parse_args()
    args.output.write_text(generate(reference(args)))
    subprocess.run([str(args.fern), '-fmt', '-w', str(args.output)], check=True)


if __name__ == '__main__':
    main()
