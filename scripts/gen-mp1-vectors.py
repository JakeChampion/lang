#!/usr/bin/env python3
"""Freeze three-frame Layer I streams with nonzero subbands and independent scalar PCM."""
import argparse
import hashlib
from pathlib import Path
import runpy
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent.parent
MP2 = runpy.run_path(str(ROOT / "scripts/gen-mp2-vectors.py"))


def frame(version, rate_index, mode, ext, seq, dense=False, bitrate_index=14, free_slots=0):
    protected = seq != 1
    rate = [44100, 48000, 32000][rate_index] // version
    bitrate = (32 * bitrate_index if version == 1 else
               [0, 32, 48, 56, 64, 80, 96, 112, 128, 144, 160, 176, 192, 224, 256][bitrate_index])
    padding = seq % 2
    header = bytes([255, (254 if version == 1 else 246) | (not protected),
                    (bitrate_index << 4) | (rate_index << 2) | (padding << 1),
                    (mode << 6) | (ext << 4) | [0, 1, 3][seq]])
    fields = []

    def put(value, width):
        fields.append(format(value, f"0{width}b"))

    channels = 1 if mode == 3 else 2
    bound = 4 * (ext + 1) if mode == 1 else 32
    widths = {}
    for band in range(32):
        for ch in range(channels):
            if ch == 0 or band < bound:
                allocation = 1 + (band + seq + ch) % 14 if band in (1, 16, 31) else 0
                if dense:
                    allocation = 1 + (band + seq + ch) % 4
                put(allocation, 4)
            widths[band, ch] = allocation + 1 if allocation else 0

    crc = 65535
    for bit in "".join(format(v, "08b") for v in header[2:]) + "".join(fields):
        feedback = (crc >> 15) ^ int(bit)
        crc = ((crc << 1) & 65535) ^ (0x8005 if feedback else 0)
    for (band, ch), width in widths.items():
        if width:
            put((band + seq + ch * 3) % 64, 6)
    for slot in range(12):
        for (band, ch), width in widths.items():
            if width and (ch == 0 or band < bound):
                put((slot * 173 + seq * 325 + band * 93 + ch) % (1 << width), width)
    bits = "".join(fields)
    bits += "0" * (-len(bits) % 8)
    payload = int(bits, 2).to_bytes(len(bits) // 8, "big")
    data = header + (struct.pack(">H", crc) if protected else b"") + payload
    size = 4 * ((12000 * bitrate // rate if bitrate_index else free_slots) + padding)
    assert len(data) <= size
    return data.ljust(size, bytes(1))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--minimp3", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    header = args.minimp3.read_bytes()
    assert hashlib.sha256(header).hexdigest() == MP2["HEADER_SHA"]
    rows = []
    with tempfile.TemporaryDirectory() as directory:
        work = Path(directory)
        (work / "minimp3.h").write_bytes(header)
        oracle = work / "oracle"
        subprocess.run(["cc", "-O2", "-ffp-contract=off", "-I", work,
                        ROOT / "scripts/audio-reference/mp2.c", "-o", oracle], check=True)
        cases = [(1, 0, 3, 0), (1, 1, 0, 0), (1, 2, 2, 0), (2, 0, 1, 0),
                 (2, 1, 1, 1), (2, 2, 1, 2), (1, 1, 1, 3)]
        streams = [(version, rate, [(mode, ext)] * 3, (False,) * 3, (14,) * 3)
                   for version, rate, mode, ext in cases]
        for version, rate, mode, ext in [(1, 0, 3, 0), (1, 1, 0, 0), (2, 0, 1, 0)]:
            streams.append((version, rate, [(mode, ext)] * 3, (True,) * 3, (14,) * 3))
        # The middle frame disables bands whose scratch held prior synthesis results.
        streams.append((1, 2, [(1, 1)] * 3, (True, False, True), (14,) * 3))
        # Keep synthesis history while bitrate, padding, protection and frame length change.
        streams.extend([(1, 0, [(3, 0)] * 3, (False,) * 3, (3, 5, 4)),
                        (2, 1, [(0, 0)] * 3, (False,) * 3, (6, 9, 7))])
        # Two-channel mode and joint-stereo bound may change without resetting synthesis.
        streams.extend([(1, 1, [(0, 0), (1, 0), (2, 0)], (True,) * 3, (14,) * 3),
                        (2, 0, [(1, 3), (1, 0), (1, 2)], (True,) * 3, (14,) * 3)])
        for version, rate, modes, density, bitrates in streams:
            data = b"".join(frame(version, rate, mode, ext, seq, density[seq], bitrates[seq])
                            for seq, (mode, ext) in enumerate(modes))
            stream = work / "input.mp1"
            stream.write_bytes(data)
            pcm = work / "out.pcm"
            subprocess.run([oracle, stream, pcm, "layer1"], check=True)
            channels = 1 if modes[0][0] == 3 else 2
            assert pcm.stat().st_size == 3 * 384 * channels * 4
            sample_rate = [44100, 48000, 32000][rate] // version
            rows.append(f'    Vector {{ rate: {sample_rate}, channels: {channels}, '
                        f'encoded: "{MP2["packed"](data)}", pcm: "{MP2["packed"](pcm.read_bytes())}" }}')
    text = ("// Generated by scripts/gen-mp1-vectors.py using pinned scalar minimp3.\n"
            "pub struct Vector { rate: i32, channels: i32, encoded: string, pcm: string }\n\n"
            "pub function vectors(): Vector[] {\n  return [\n" + ",\n".join(rows) + ",\n  ];\n}\n")
    output = ROOT / "tests/stdlib/mp1_vectors.fern"
    if args.check:
        if text != output.read_text():
            raise SystemExit("Layer I references differ")
    else:
        output.write_text(text)


if __name__ == "__main__":
    main()
