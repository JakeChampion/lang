#!/usr/bin/env python3
"""Generate bounded AAC-LC decode tables from a hash-pinned MPL-2.0 reference."""
import argparse
import hashlib
import math
from pathlib import Path
import re
import struct
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
PIN = '6d533f26150953a882a6a111ebd13f0abf7129d5'
HASHES = {
    'codebooks.rs': 'c42aa790154d9085be8cc11213322e9ea87127e4c0e1de3c91664039d2a02e7b',
    'common.rs': '23402e0a4e20595f3f9d55bf07f2cee4959b2fb6faab38105b15017a40124fea',
}
MISSING = 2147483647


def reference(name, source):
    path = f'symphonia-codec-aac/src/aac/{name}'
    raw = (source / path).read_bytes() if source else urllib.request.urlopen(
        f'https://raw.githubusercontent.com/pdeljanov/Symphonia/{PIN}/{path}', timeout=60).read()
    if hashlib.sha256(raw).hexdigest() != HASHES[name]:
        raise ValueError(f'reference digest mismatch: {path}')
    return raw.decode()


def array(source, name):
    match = re.search(rf'const {name}:\s*\[[^;]+;[^\]]+\]\s*=\s*\[(.*?)\];', source, re.S)
    if not match:
        raise ValueError(f'missing reference table: {name}')
    values = re.sub(r'//[^\n]*', '', match[1])
    return [int(x.strip(), 0) for x in values.split(',') if x.strip()]


def huffman(source):
    nodes = []
    fast = []
    for book in range(12):
        prefix = 'SCF_CODEBOOK' if book == 0 else f'SPECTRUM_CODEBOOK{book}'
        lengths, codes = array(source, prefix + '_LENS'), array(source, prefix + '_CODES')
        if len(lengths) != len(codes):
            raise ValueError('Huffman table length mismatch')
        root = len(nodes)
        nodes.append([MISSING, MISSING])
        for symbol, (length, code) in enumerate(zip(lengths, codes)):
            if not 1 <= length <= 19 or code >= 1 << length:
                raise ValueError('invalid Huffman code')
            node = root
            for shift in range(length - 1, -1, -1):
                bit = (code >> shift) & 1
                child = nodes[node][bit]
                if shift == 0:
                    if child != MISSING:
                        raise ValueError('duplicate Huffman code')
                    nodes[node][bit] = -symbol - 1
                else:
                    if child == MISSING:
                        child = len(nodes)
                        nodes[node][bit] = child
                        nodes.append([MISSING, MISSING])
                    if child < 0:
                        raise ValueError('non-prefix-free Huffman table')
                    node = child
        for prefix_bits in range(512):
            node = root
            entry = MISSING
            for shift in range(8, -1, -1):
                child = nodes[node][(prefix_bits >> shift) & 1]
                if child == MISSING:
                    break
                if child < 0:
                    entry = ((9 - shift) << 16) | (-child - 1)
                    break
                node = child
            else:
                entry = -node - 1
            fast.append(entry)
    return fast, [child for node in nodes for child in node]


def f32(value):
    return struct.unpack('<f', struct.pack('<f', value))[0]


def float_literal(value):
    value = format(f32(value), '.9g')
    if '.' not in value and 'e' not in value:
        value += '.0'
    return value + 'f32'


def declaration(name, values, floats=False):
    values = [float_literal(v) if floats else str(v) for v in values]
    rows = [', '.join(values[i:i + 12]) for i in range(0, len(values), 12)]
    return f'pub const {name}: {"f32" if floats else "i32"}[] = [\n  ' + ',\n  '.join(rows) + ',\n];\n'


def bessel_i0(value):
    result = 1.0
    for n in range(63, 0, -1):
        result = result * value / (n * n) + 1.0
    return result


def kbd(size, alpha):
    factor = (alpha * math.pi / size) ** 2
    total = 0.0
    sums = []
    for n in range(size):
        total += bessel_i0(n * (size - n) * factor)
        sums.append(total)
    return [math.sqrt(value / (total + 1.0)) for value in sums]


def generate(codebooks, common):
    fast, children = huffman(codebooks)
    text = '''# AAC-LC tables

These fixed tables support AAC-LC spectral decoding and inverse transforms.
The codebooks and band boundaries follow Symphonia v0.5.5 at `6d533f26150953a882a6a111ebd13f0abf7129d5`.
Generated prefix tables preserve every codeword in the pinned reference.
Window and transform coefficients use binary32 values generated from their mathematical definitions.

This module is available under MPL-2.0. See `licenses/aac/MPL-2.0.txt` and `licenses/aac/NOTICE.txt`.
Regenerate with `scripts/gen-aac-tables.py`; use `--check` for a byte-exact check.

```fern
<<*>>=
// Generated by scripts/gen-aac-tables.py. DO NOT EDIT.
// Copyright (c) 2019-2023 The Project Symphonia Developers.
// Previous author: Kostya Shishkov <kostya.shiskov@gmail.com>.
// This Source Code Form is subject to the Mozilla Public License, v. 2.0.
// See licenses/aac/MPL-2.0.txt or https://mozilla.org/MPL/2.0/.

'''
    text += declaration('HUFF_FAST', fast) + '\n' + declaration('HUFF_CHILDREN', children) + '\n'
    text += declaration('POW43', [math.pow(i, 4.0 / 3.0) for i in range(8192)], True) + '\n'
    text += declaration('NORMAL_SCF', [math.pow(2.0, (i - 156) * .25) for i in range(256)], True) + '\n'
    text += declaration('INTENSITY_SCF', [math.pow(.5, (i - 155) * .25) for i in range(256)], True) + '\n'
    for size, name, alpha in [(1024, 'LONG', 4.0), (128, 'SHORT', 6.0)]:
        text += declaration('SINE_' + name, [math.sin((i + .5) * math.pi / (2 * size)) for i in range(size)], True) + '\n'
        text += declaration('KBD_' + name, kbd(size, alpha), True) + '\n'
        scale = math.sqrt(1.0 / (2 * size))
        twiddle = [v for k in range(size // 2) for v in (scale * math.cos(math.pi * (k + .125) / size), scale * math.sin(math.pi * (k + .125) / size))]
        text += declaration('MDCT_' + name, twiddle, True) + '\n'
    text += declaration('FFT', [v for k in range(256) for v in (math.cos(-2 * math.pi * k / 512), math.sin(-2 * math.pi * k / 512))], True) + '\n'
    long = ['96', '96', '64', '48', '48', '32', '24', '24', '16', '16', '16', '8', '8']
    short = ['64', '64', '64', '48', '48', '48', '24', '24', '16', '16', '16', '8', '8']
    bands, starts, lengths = [], [], []
    for suffix, rates in [('LONG', long), ('SHORT', short)]:
        for rate in rates:
            values = array(common, f'SWB_OFFSET_{rate}K_{suffix}')
            starts.append(len(bands))
            lengths.append(len(values))
            bands.extend(values)
    text += declaration('BANDS', bands) + '\n' + declaration('BAND_START', starts) + '\n' + declaration('BAND_LENGTH', lengths) + '\n'
    text += declaration('TNS_LONG_BANDS', [31, 31, 34, 40, 42, 51, 46, 46, 42, 42, 42, 39, 39]) + '\n'
    text += declaration('TNS_SHORT_BANDS', [9, 9, 10, 14, 14, 14, 14, 14, 14, 14, 14, 14, 14]) + '\n'
    tns = []
    for resolution in [3, 4]:
        for compressed in [False, True]:
            width = resolution - int(compressed)
            base = 1 << (resolution - 1)
            for value in range(1 << width):
                signed = value if value < 1 << (width - 1) else value - (1 << width)
                tns.append(math.sin(signed * (math.pi / 2) / (base - .5 if signed >= 0 else base + .5)))
    text += declaration('TNS_COEFFICIENTS', tns, True)
    text += '''
pub struct Bands { start: i32, count: i32 }

pub function bands(rate: i32, short: boolean): Bands {
  let index = rate + (if (short) { 13 } else { 0 });
  let start = BAND_START[index];
  return Bands { start: start, count: BAND_LENGTH[index] };
}
```
'''
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-dir', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generate(reference('codebooks.rs', args.source_dir), reference('common.rs', args.source_dir))
    target = ROOT / 'internal/stdlib/std/audio/aac/tables.fern.md'
    if args.check:
        if not target.exists() or target.read_text() != text:
            parser.exit(1, 'AAC tables are stale; run scripts/gen-aac-tables.py\n')
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)


if __name__ == '__main__':
    main()
