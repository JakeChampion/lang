#!/usr/bin/env python3
"""Freeze complete float PCM for Opus playback from pinned libopus."""
import argparse
import base64
import json
from pathlib import Path
import runpy
import struct
import subprocess
import zlib

ROOT = Path(__file__).resolve().parent.parent
REFERENCE = runpy.run_path(str(Path(__file__).with_name('gen-silk-loss-vectors.py')))


def generate(records):
    cases = {}
    for row in records:
        cases.setdefault(row['case'], []).append(row)
    if len(records) != 290 or set(cases) != set(range(10)):
        raise ValueError('unexpected playback corpus size')
    if {r['action'] for r in records} != {0, 1, 2, 3}:
        raise ValueError('incomplete playback operation coverage')
    lines = ['// Generated by scripts/gen-opus-playback-vectors.py.',
             '// Unmodified libopus '+REFERENCE['PIN']+', BSD-3-Clause.',
             '// Each zlib/base64 case contains packet bytes and complete little-endian float PCM.',
             '', 'pub const CASES: string[] = [']
    for rows in cases.values():
        data = bytearray(struct.pack('<III', rows[0]['rate'], rows[0]['channels'], len(rows)))
        for row in rows:
            packet = bytes.fromhex(row['packet'])
            pcm = row['pcm']
            if len(pcm) != row['frames'] * row['channels']:
                raise ValueError('unexpected PCM length')
            data.extend(struct.pack('<IIII', row['action'], row['frames'], row['range'], len(packet)))
            data.extend(packet)
            data.extend(struct.pack('<'+'I'*len(pcm), *pcm))
        encoded = base64.b64encode(zlib.compress(data, 9)).decode('ascii')
        lines.append('  '+json.dumps(encoded)+',')
    lines.append('];')
    return '\n'.join(lines)+'\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--archive', type=Path)
    parser.add_argument('--cmake', default='cmake')
    parser.add_argument('--output', type=Path, default=ROOT/'tests/stdlib/opus_playback_vectors.fern')
    parser.add_argument('--fern', type=Path, default=ROOT/'bin/fern-selfhost')
    args = parser.parse_args()
    records = REFERENCE['reference'](args.archive, args.cmake, 'opus_playback.c')
    args.output.write_text(generate(records))
    subprocess.run([str(args.fern), '-fmt', '-w', str(args.output)], check=True)


if __name__ == '__main__':
    main()
