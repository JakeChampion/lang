#!/usr/bin/env python3
"""Freeze CAF transport cases around independent ALAC packet and PCM references."""
import argparse
import base64
import hashlib
from pathlib import Path
import re
import runpy
import struct
import subprocess
import tempfile
import zlib

ROOT = Path(__file__).resolve().parent.parent
ALAC = runpy.run_path(str(ROOT / 'scripts/gen-alac-vectors.py'))


def unpack(value):
    return zlib.decompress(base64.b64decode(value))


def packed(value):
    return base64.b64encode(zlib.compress(value, 9)).decode()


def chunks(data):
    at = 8
    output = []
    while at < len(data):
        tag, size = struct.unpack_from('>4sq', data, at)
        assert size >= 0 and at + 12 + size <= len(data)
        output.append((tag, data[at + 12:at + 12 + size]))
        at += 12 + size
    assert at == len(data)
    return output


def file(rows):
    return b'caff' + struct.pack('>HH', 1, 0) + b''.join(tag + struct.pack('>q', len(body)) + body for tag, body in rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = (ROOT / 'tests/stdlib/alac_vectors.fern').read_text()
    references = []
    pattern = r'Vector \{ name: "([^"]+)"[^\n]*?configuration: "([^"]+)"[^\n]*?packets: "([^"]+)"[^\n]*?pcm: "([^"]+)" \}'
    for name, configuration, bundle, pcm in re.findall(pattern, source):
        configuration, bundle, pcm = map(unpack, (configuration, bundle, pcm))
        count = struct.unpack_from('<I', bundle)[0]
        at, packets = 4, []
        for _ in range(count):
            size = struct.unpack_from('<I', bundle, at)[0]
            at += 4
            packets.append(bundle[at:at + size])
            at += size
        assert at == len(bundle)
        channels = configuration[9]
        references.append((name, configuration, packets, pcm, len(pcm) // (4 * channels)))
    assert len(references) == 38
    version = subprocess.check_output(['ffmpeg', '-version'], text=True).splitlines()[0]
    header = '// Generated by scripts/gen-caf-vectors.py.\n// PCM: independent alac_vectors corpus. Remux reference: ' + version + '\n'
    header += 'pub struct Vector { name: string, source: i32, trim: i32, frames: i32, mask: u32, order: i32[], encoded: string }\n\n'
    rows, smoke = [], None
    side = [0, 4, 3, 7, 263, 1543, 1551, 1807, 1743]
    back = [0, 4, 3, 7, 263, 55, 63, 319, 255]
    with tempfile.TemporaryDirectory() as directory:
        temp = Path(directory)
        def freeze(name, index, data, trim=0, frames=None, remux=False):
            nonlocal smoke
            _, configuration, _, pcm, total = references[index]
            channels = configuration[9]
            frames = total - trim if frames is None else frames
            assert trim >= 0 and frames >= 0 and trim + frames <= total
            order = list(range(channels))
            if remux:
                order = {7: [0, 1, 2, 3, 5, 6, 4], 8: [0, 1, 2, 3, 6, 7, 4, 5]}.get(channels, order)
            mask = (back if remux else side)[channels]
            samples = [v[0] for v in struct.iter_unpack('<i', pcm)]
            expected = [samples[(trim + frame) * channels + channel] for frame in range(frames) for channel in order]
            if remux:
                path = temp / 'verify.caf'
                path.write_bytes(data)
                raw = subprocess.check_output(['ffmpeg', '-v', 'error', '-i', str(path), '-f', 's32le', '-'])
                actual = [v[0] >> (32 - configuration[5]) for v in struct.iter_unpack('<i', raw)]
                assert actual == expected, name
            digest = hashlib.sha256(struct.pack('<' + 'i' * len(expected), *expected)).hexdigest()
            row = f'    Vector {{ name: "{name}", source: {index}, trim: {trim}, frames: {frames}, mask: {mask}u32, order: [{", ".join(map(str, order))}], encoded: "{packed(data)}" }},\n'
            rows.append(row)
            if name == 'initial-and-final-trim':
                smoke = row
            print(name, len(data), frames, digest)

        for index, (name, configuration, packets, _, frames) in enumerate(references):
            data = ALAC['caf'](configuration, packets, frames)
            freeze('direct-' + name, index, data)
            if name.startswith('encoded-') and name.count('-') == 2:
                path, remux = temp / 'input.caf', temp / 'remux.caf'
                path.write_bytes(data)
                subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', str(path), '-c:a', 'copy', str(remux)], check=True)
                freeze('remux-' + name, index, remux.read_bytes(), remux=True)
        small = next(i for i, value in enumerate(references) if value[0] == 'no-predictor')
        _, configuration, packets, _, frames = references[small]
        base = chunks(ALAC['caf'](configuration, packets, frames))
        modified = [(tag, struct.pack('>qqii', 1, 11, 5, 3) + body[24:] if tag == b'pakt' else body) for tag, body in base]
        freeze('initial-and-final-trim', small, file(modified), trim=5, frames=11)
        modified = [(tag, struct.pack('>qqii', 1, 0, 19, 0) + body[24:] if tag == b'pakt' else body) for tag, body in base]
        freeze('empty-presentation', small, file(modified), trim=19, frames=0)
        empty = ALAC['caf'](configuration, [], 0)
        freeze('empty-file', small, empty, frames=0)
        unknown = file(base)
        data_at = next(at for at in range(8, len(unknown) - 12) if unknown[at:at + 4] == b'data')
        unknown = unknown[:data_at + 4] + struct.pack('>q', -1) + unknown[data_at + 12:]
        freeze('unknown-data-size', small, unknown)
        modified = [(tag, body[:20] + struct.pack('>I', 0) + body[24:] if tag == b'desc' else body + ALAC['varint'](frames) if tag == b'pakt' else body) for tag, body in base]
        freeze('variable-packet-frames', small, file(modified))
        modified = [(tag, body[:16] + struct.pack('>I', len(packets[0])) + body[20:] if tag == b'desc' else body[:24] if tag == b'pakt' else body) for tag, body in base]
        freeze('constant-packet-bytes', small, file(modified))
        freeze('constant-bytes-without-table', small, file([(tag, body) for tag, body in modified if tag != b'pakt']))
        freeze('unknown-chunks', small, file([base[0], (b'free', b''), (b'uuid', b'opaque'), *base[1:]]))
        _, configuration, packets, _, frames = references[0]
        base = chunks(ALAC['caf'](configuration, packets, frames))
        modified = [(tag, struct.pack('>qqii', len(packets), 5, 4098, 0) + body[24:] if tag == b'pakt' else body) for tag, body in base]
        freeze('whole-initial-packet-trim', 0, file(modified), trim=4098, frames=5)
        modified = [(tag, struct.pack('>qqii', len(packets), 4094, 0, 9) + body[24:] if tag == b'pakt' else body) for tag, body in base]
        freeze('whole-final-packet-trim', 0, file(modified), frames=4094)
    assert smoke is not None
    text = header + 'pub function vectors(): Vector[] {\n  return [\n' + ''.join(rows) + '  ];\n}\n'
    smoke_text = header + 'pub function vector(): Vector {\n  return ' + smoke.strip().removesuffix(',') + ';\n}\n'
    for name, value in [('caf_vectors.fern', text), ('caf_smoke_vectors.fern', smoke_text)]:
        target = ROOT / 'tests/stdlib' / name
        if args.check:
            if target.read_text() != value:
                parser.exit(1, name + ' is stale\n')
        else:
            target.write_text(value)


if __name__ == '__main__':
    main()
