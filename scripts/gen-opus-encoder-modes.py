#!/usr/bin/env python3
"""Preserve the pinned CELT encoder's transform tables independently of decoder tables."""
import argparse
import hashlib
import io
from pathlib import Path
import re
import runpy
import struct
import subprocess
import tarfile
import tempfile
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
PIN = '82ac57d9f1aaf575800cf17373348e45b7ce6c0d'
ARCHIVE_SHA = 'ccb8c3bcde07ac72ce9bb0297834c028de9097f95b62e55dca36464e3c59336d'
MODES = runpy.run_path(str(ROOT/'scripts/gen-opus-modes.py'))


def generate(source):
    table = source/'celt/static_modes_float.h'
    text = table.read_text()
    mdct = MODES['values'](text, 'mdct_twiddles960')
    fft = MODES['values'](text, 'fft_twiddles48000_960')
    if len(mdct) != 1800 or len(fft) != 960:
        raise ValueError('unexpected encoder transform sizes')
    current = (ROOT/'internal/stdlib/std/opus/modes.fern').read_text()
    body = re.search(r'pub const FFT_TWIDDLES: f32\[\] = \[(.*?)\];', current, re.S)[1]
    current_values = [v.strip().removesuffix('f32') for v in body.split(',') if v.strip()]
    def packed(value):
        return struct.pack('<f', float(value.removesuffix('f')))
    indices = [i for i, (a, b) in enumerate(zip(fft, current_values, strict=True)) if packed(a) != packed(b)]
    if indices != [240, 481, 720]:
        raise ValueError('unexpected differences from the decoder FFT table')
    states = '\n'.join(MODES['fft_states'](table))
    scales = re.search(r'pub const FFT_SCALE: f32\[\] = \[(.*?)\];', states, re.S)[0]
    lines = ['// Generated by scripts/gen-opus-encoder-modes.py.',
             '// CELT encoder tables from unmodified libopus '+PIN+'.',
             '// Preserve libopus 1.4 quantization decisions while decoder tables follow the current reference.',
             *MODES['notice'](source), '']
    lines += MODES['table']('MDCT_TWIDDLES', 'f32', mdct)
    lines += ['', scales]
    lines += MODES['table']('FFT_PATCH_INDICES', 'i32', [str(i) for i in indices])
    lines += MODES['table']('FFT_PATCH_VALUES', 'f32', [fft[i] for i in indices])
    return '\n'.join(lines)+'\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--archive', type=Path)
    parser.add_argument('--fern', type=Path, default=ROOT/'bin/fern-selfhost')
    parser.add_argument('--output', type=Path, default=ROOT/'internal/stdlib/std/opus/encoder_modes.fern')
    args = parser.parse_args()
    raw = args.archive.read_bytes() if args.archive else urllib.request.urlopen(
        f'https://codeload.github.com/xiph/opus/tar.gz/{PIN}', timeout=60).read()
    if hashlib.sha256(raw).hexdigest() != ARCHIVE_SHA:
        raise ValueError('libopus encoder archive hash mismatch')
    with tempfile.TemporaryDirectory() as directory:
        with tarfile.open(fileobj=io.BytesIO(raw)) as archive:
            archive.extractall(directory, filter='data')
        args.output.write_text(generate(Path(directory)/('opus-'+PIN)))
    subprocess.run([str(args.fern), '-fmt', '-w', str(args.output)], check=True)


if __name__ == '__main__':
    main()
