  values(a,b,smulbb(a,b),smulwb(a,b),smulww(a,b),smulwt(a,b),smmul(a,b),addSat32(a,b),saturatingSubInt32(a,b),smlabb(a,b,1234567),smlawb(a,b,1234567),smlawt(a,b,1234567),smlaWW(a,b,1234567))
