#!/usr/bin/env python3
"""Freeze Ogg Opus files and complete PCM from pinned libopusfile."""
import argparse
import base64
import hashlib
import io
import json
from pathlib import Path
import runpy
import struct
import subprocess
import tarfile
import tempfile
import urllib.request
import zlib

ROOT = Path(__file__).resolve().parent.parent
PINS = runpy.run_path(str(Path(__file__).with_name('gen-opus-headers-vectors.py')))['PINS']


def reference(args, helper='opus_file.c'):
    with tempfile.TemporaryDirectory() as directory:
        root = Path(directory)
        sources = {}
        for name, (pin, digest) in PINS.items():
            archive = getattr(args, name+'_archive')
            raw = archive.read_bytes() if archive else urllib.request.urlopen(
                f'https://codeload.github.com/xiph/{name}/tar.gz/{pin}', timeout=60).read()
            if hashlib.sha256(raw).hexdigest() != digest:
                raise ValueError(name+' archive hash mismatch')
            with tarfile.open(fileobj=io.BytesIO(raw)) as tar:
                tar.extractall(root, filter='data')
            sources[name] = root/(name+'-'+pin)
        opus, ogg = root/'opus-build', root/'ogg-build'
        subprocess.run([args.cmake, '-S', str(sources['opus']), '-B', str(opus), '-DCMAKE_BUILD_TYPE=Release',
                        '-DOPUS_DISABLE_INTRINSICS=ON', '-DOPUS_ASSERTIONS=ON', '-DOPUS_BUILD_TESTING=OFF',
                        '-DOPUS_BUILD_PROGRAMS=OFF', '-DOPUS_DRED=OFF', '-DOPUS_OSCE=OFF'],
                       check=True, stdout=subprocess.DEVNULL)
        subprocess.run([args.cmake, '--build', str(opus), '-j', '2'], check=True, stdout=subprocess.DEVNULL)
        subprocess.run([args.cmake, '-S', str(sources['ogg']), '-B', str(ogg), '-DCMAKE_BUILD_TYPE=Release',
                        '-DBUILD_SHARED_LIBS=OFF', '-DBUILD_TESTING=OFF'], check=True, stdout=subprocess.DEVNULL)
        subprocess.run([args.cmake, '--build', str(ogg), '-j', '2'], check=True, stdout=subprocess.DEVNULL)
        source = sources['opusfile']
        includes = [source/'include', source/'src', sources['opus']/'include', sources['ogg']/'include', ogg/'include']
        executable = root/'opus-file-reference'
        subprocess.run(['cc', '-O2', '-DOP_DISABLE_HTTP', '-DOP_HAVE_LRINTF',
                        *['-I'+str(p) for p in includes], str(ROOT/'scripts/audio-reference'/helper),
                        *[str(source/('src/'+name+'.c')) for name in ['info', 'internal', 'stream', 'opusfile']],
                        str(opus/'libopus.a'), str(ogg/'libogg.a'), '-lm', '-o', str(executable)], check=True)
        return [json.loads(line) for line in subprocess.check_output([str(executable)]).splitlines()]


def blob(raw):
    return struct.pack('<I', len(raw))+raw


def encoded_case(row):
    data = bytearray(blob(bytes.fromhex(row['bytes'])))
    data.extend(struct.pack('<I', len(row['links'])))
    for link in row['links']:
        data.extend(struct.pack('<Iqq8q', link['serial'], link['initial'], link['frames'], *link['fields']))
        data.extend(blob(bytes.fromhex(link['mapping'])))
        data.extend(blob(bytes.fromhex(link['vendor'])))
        data.extend(struct.pack('<I', len(link['comments'])))
        for comment in link['comments']:
            data.extend(blob(bytes.fromhex(comment)))
        data.extend(blob(bytes.fromhex(link['suffix'])))
        if len(link['pcm']) != link['frames']*link['fields'][1]:
            raise ValueError('unexpected Opus file PCM count')
        data.extend(blob(struct.pack('<'+'I'*len(link['pcm']), *link['pcm'])))
    return json.dumps(base64.b64encode(zlib.compress(data, 9)).decode('ascii'))


def generate(records):
    if len(records) != 11 or {row['case'] for row in records} != set(range(11)):
        raise ValueError('unexpected Opus file corpus size')
    lines = ['// Generated by scripts/gen-opus-file-vectors.py.',
             '// Unmodified libopusfile '+PINS['opusfile'][0]+'.',
             '// Each zlib/base64 case contains an Ogg file, headers, tags, and complete float PCM.',
             '', 'pub const CASES: string[] = [']
    lines.extend('  '+encoded_case(row)+',' for row in records if row['case'] != 9)
    lines.extend(['];', '', '// One complete file for the self-host interpreter gate.',
                  'pub const SMOKE: string = '+encoded_case(records[9])+';', ''])
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in PINS:
        parser.add_argument('--'+name+'-archive', type=Path)
    parser.add_argument('--cmake', default='cmake')
    parser.add_argument('--fern', type=Path, default=ROOT/'bin/fern-selfhost')
    parser.add_argument('--output', type=Path, default=ROOT/'tests/stdlib/opus_file_vectors.fern')
    args = parser.parse_args()
    args.output.write_text(generate(reference(args)))
    subprocess.run([str(args.fern), '-fmt', '-w', str(args.output)], check=True)


if __name__ == '__main__':
    main()
