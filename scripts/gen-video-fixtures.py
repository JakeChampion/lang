#!/usr/bin/env python3
"""Generate QTRLE packet vectors with FFmpeg and verify every source pixel."""
import json
import os
from pathlib import Path
import struct
import subprocess
import tempfile
import zlib

ROOT = Path(__file__).resolve().parent.parent


def frames(width, height, depth):
    state = 42
    first = bytearray()
    for y in range(height):
        for x in range(width):
            state = (state * 1664525 + 1013904223) & 0xffffffff
            p = bytes((255 if depth == 24 else (x * 7 + y * 31) % 256,
                       state >> 24, (state >> 16) & 255, (state >> 8) & 255))
            if x % 260 < 130:
                p = bytes((255 if depth == 24 else 37, 71, 81, 91))
            first.extend(p)
    second = bytearray(first)
    at = ((height // 2) * width + width // 2) * 4
    second[at:at + 4] = bytes((255 if depth == 24 else 19, 250, 1, 2))
    fourth = bytearray(second)
    fourth[:4] = bytes((255 if depth == 24 else 0, 20, 30, 40))
    return [bytes(first), bytes(second), bytes(second), bytes(fourth)]


def run(*args):
    return subprocess.check_output(args)


def main():
    out = ['// Generated by scripts/gen-video-fixtures.py with independent FFmpeg packets.',
           'pub struct Vector { width: i32, height: i32, depth: i32, packets: string[], crcs: u32[] }',
           'pub function vectors(): Vector[] {', '  return [']
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        for width, height in [(1, 1), (129, 2), (521, 3)]:
            for depth in (24, 32):
                originals = frames(width, height, depth)
                raw = b''.join(originals)
                source = tmp / 'input.argb'
                source.write_bytes(raw)
                mov = tmp / 'encoded.mov'
                run('ffmpeg', '-v', 'error', '-y', '-f', 'rawvideo', '-pixel_format', 'argb',
                    '-video_size', f'{width}x{height}', '-framerate', '25', '-i', str(source),
                    '-c:v', 'qtrle', '-pix_fmt', 'rgb24' if depth == 24 else 'argb', '-g', '30', str(mov))
                decoded = run('ffmpeg', '-v', 'error', '-i', str(mov), '-f', 'rawvideo', '-pix_fmt', 'argb', '-')
                assert decoded == raw, (width, height, depth)
                packet_info = json.loads(run('ffprobe', '-v', 'error', '-show_packets',
                                             '-show_entries', 'packet=pos,size', '-of', 'json', str(mov)))
                data = mov.read_bytes()
                packets = [data[int(p['pos']):int(p['pos']) + int(p['size'])] for p in packet_info['packets']]
                assert len(packets) == len(originals)
                out.append(f'    Vector {{ width: {width}, height: {height}, depth: {depth},')
                out.append('      packets: [' + ', '.join('"' + p.hex() + '"' for p in packets) + '],')
                out.append('      crcs: [' + ', '.join(str(zlib.crc32(f)) + 'u32' for f in originals) + '] },')
        out.extend(['  ];', '}', ''])
    (ROOT / 'tests/stdlib/video_vectors.fern').write_text('\n'.join(out))
    configs = ['// Generated from FFmpeg AVC and HEVC records.',
               'pub struct Vector { hevc: boolean, config: string, packet: string, argb: string }',
               'pub function vectors(): Vector[] { return [']
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        source = tmp / 'source.argb'
        source.write_bytes(frames(16, 16, 24)[0])
        for hevc in (False, True):
            output = tmp / 'encoded.mp4'
            options = ['-c:v', 'libx265', '-x265-params', 'lossless=1:pools=none:wpp=0:log-level=error'] if hevc else ['-c:v', 'libx264', '-qp', '0']
            run('ffmpeg', '-v', 'error', '-y', '-f', 'rawvideo', '-pixel_format', 'argb',
                '-video_size', '16x16', '-i', str(source), *options, '-pix_fmt', 'yuv444p', str(output))
            data = output.read_bytes()
            tag = b'hvcC' if hevc else b'avcC'
            assert data.count(tag) == 1
            at = data.index(tag)
            size = struct.unpack_from('>I', data, at - 4)[0]
            config = data[at + 4:at - 4 + size]
            info = json.loads(run('ffprobe', '-v', 'error', '-show_packets', '-show_entries', 'packet=pos,size', '-of', 'json', str(output)))
            assert len(info['packets']) == 1
            p = info['packets'][0]
            packet = data[int(p['pos']):int(p['pos']) + int(p['size'])]
            argb = run('ffmpeg', '-v', 'error', '-i', str(output), '-f', 'rawvideo', '-pix_fmt', 'argb', '-')
            assert len(argb) == 16 * 16 * 4
            configs.append(f'  Vector {{ hevc: {str(hevc).lower()}, config: "{config.hex()}", packet: "{packet.hex()}", argb: "{argb.hex()}" }},')
    configs.extend([' ]; }', ''])
    (ROOT / 'tests/stdlib/video_nal_vectors.fern').write_text('\n'.join(configs))
    compiler = os.environ.get('FERN') or run(str(ROOT / 'bootstrap/bootstrap.sh'), 'stage0').decode().strip()
    subprocess.run([compiler, '-fmt', '-w', str(ROOT / 'tests/stdlib/video_vectors.fern'),
                    str(ROOT / 'tests/stdlib/video_nal_vectors.fern')], check=True)
    print(run('ffmpeg', '-version').decode().splitlines()[0])
    print('24 QTRLE packets verified against source ARGB pixels')
    print('AVC and HEVC configuration records and packets generated')


if __name__ == '__main__':
    main()
