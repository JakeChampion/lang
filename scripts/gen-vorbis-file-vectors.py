#!/usr/bin/env python3
"""Freeze independent libvorbisfile PCM for Ogg Vorbis transport cases."""
import argparse
import base64
import re
from pathlib import Path
import runpy
import struct
import subprocess
import tempfile
import zlib

ROOT = Path(__file__).resolve().parent.parent
PACKET = runpy.run_path(str(ROOT / 'scripts/gen-vorbis-vectors.py'))


def pack(data):
    return base64.b64encode(zlib.compress(data, 9)).decode()


def checksum(data):
    crc = 0
    for byte in data:
        crc ^= byte << 24
        for _ in range(8):
            crc = ((crc << 1) ^ (0x04c11db7 if crc & 0x80000000 else 0)) & 0xffffffff
    return crc


def page(serial, sequence, granule, flags, payload, lacing):
    assert len(lacing) <= 255 and sum(lacing) == len(payload)
    data = bytearray(b'OggS' + bytes([0, flags]) + struct.pack('<qII', granule, serial, sequence) + bytes(4) + bytes([len(lacing)]) + bytes(lacing) + payload)
    data[22:26] = struct.pack('<I', checksum(data))
    return bytes(data)


def complete(serial, sequence, granule, flags, packets):
    lacing = []
    for packet in packets:
        lacing += [255] * (len(packet) // 255) + [len(packet) % 255]
    return page(serial, sequence, granule, flags, b''.join(packets), lacing)


def repage(values, counts, trim=0, offset=0, separate=False, long_comment=False):
    ident, comment, setup = values[:3]
    result = complete(42, 0, 0, 2, [ident])
    sequence = 1
    if long_comment:
        vendor = b'x' * 70000
        comment = b'\x03vorbis' + struct.pack('<I', len(vendor)) + vendor + struct.pack('<I', 0) + b'\x01'
        first = 255 * 255
        result += page(42, sequence, -1, 0, comment[:first], [255] * 255)
        sequence += 1
        result += complete(42, sequence, 0, 1, [comment[first:], setup])
        sequence += 1
    elif separate:
        for packet in [comment, setup]:
            result += complete(42, sequence, 0, 0, [packet])
            sequence += 1
    else:
        result += complete(42, sequence, 0, 0, [comment, setup])
        sequence += 1
    rendered = 0
    audio = values[3:]
    first = 0
    while first < len(audio):
        # Nonzero origins require the second audio packet to flush its page.
        end = min(first + (2 if first == 0 and (trim or offset) else 3), len(audio))
        rendered += sum(counts[first:end])
        granule = rendered - trim + offset
        assert granule >= 0
        result += complete(42, sequence, granule, 4 if end == len(audio) else 0, audio[first:end])
        sequence += 1
        first = end
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--reference', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = (ROOT / 'tests/stdlib/vorbis_vectors.fern').read_text()
    rows = re.findall(r'Vector \{ name: "([^"]+)"[^\n]*?counts: "([^"]+)"[^\n]*?ogg: "([^"]+)"', source)
    fixtures = [(name, zlib.decompress(base64.b64decode(encoded))) for name, _, encoded in rows if not name.startswith('floor0-')]
    mono = fixtures[0][1]
    values = PACKET['packets'](mono)
    counts = struct.unpack('<' + 'I' * (len(values) - 3), zlib.decompress(base64.b64decode(rows[0][1])))
    fixtures += [('repage', repage(values, counts)), ('separate-headers', repage(values, counts, separate=True)),
                 ('continued-comment', repage(values, counts, long_comment=True)),
                 ('initial-trim', repage(values, counts, trim=128)),
                 ('initial-offset', repage(values, counts, offset=12345)),
                 ('chain-rate-channels', repage(values, counts) + fixtures[1][1])]
    synthetic = PACKET['floor0_packets'](8, 1, 1, 0)
    small = complete(73, 0, 0, 2, synthetic[:1])
    small += complete(73, 1, 0, 0, synthetic[1:3])
    small += complete(73, 2, 95, 4, synthetic[3:])
    fixtures += [('floor0-smoke', small)]
    fixtures += [('initial-trim-one-packet', repage(synthetic, [0, 32, 32, 32], trim=32))]
    ending = complete(74, 0, 0, 2, synthetic[:1]) + complete(74, 1, 0, 0, synthetic[1:3])
    fixtures += [('final-trim-one-packet', ending + complete(74, 2, 64, 4, synthetic[3:]))]
    text = '// Generated by scripts/gen-vorbis-file-vectors.py.\n// Reference: Xiph libvorbisfile 1.3.7, public float API, seekable input.\n'
    text += 'pub struct Vector { name: string, encoded: string, formats: string, pcm: string }\n\n'
    text += 'pub function vectors(): Vector[] {\n  return [\n'
    smoke = text[:text.index('pub function vectors')]
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory) / 'input.ogg'
        for name, encoded in fixtures:
            path.write_bytes(encoded)
            output = subprocess.check_output([str(args.reference), 'seek', str(path)])
            at, links = 0, []
            while at < len(output):
                link, rate, channels, frames = struct.unpack_from('<IIII', output, at)
                at += 16
                if link == len(links):
                    links.append([rate, channels, 0, bytearray()])
                assert 0 <= link < len(links) and links[link][:2] == [rate, channels]
                size = frames * channels * 4
                links[link][2] += frames
                links[link][3] += output[at:at + size]
                at += size
            assert at == len(output)
            formats = b''.join(struct.pack('<III', *link[:3]) for link in links)
            pcm = b''.join(link[3] for link in links)
            row = f'Vector {{ name: "{name}", encoded: "{pack(encoded)}", formats: "{pack(formats)}", pcm: "{pack(pcm)}" }}'
            text += '    ' + row + ',\n'
            if name == 'floor0-smoke':
                smoke += 'pub function vector(): Vector {\n  return ' + row + ';\n}\n'
            print(name, len(encoded), [link[:3] for link in links])
    text += '  ];\n}\n'
    for name, content in [('vorbis_file_vectors.fern', text), ('vorbis_file_smoke_vectors.fern', smoke)]:
        target = ROOT / 'tests/stdlib' / name
        if args.check:
            if target.read_text() != content:
                parser.exit(1, f'{name} is stale\n')
        else:
            target.write_text(content)


if __name__ == '__main__':
    main()
