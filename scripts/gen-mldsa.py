#!/usr/bin/env python3
# gen-mldsa.py: writes the ML-DSA-65 vector suites under tests/stdlib.
#
#   gen-mldsa.py ACVP-DIR WYCHEPROOF-DIR
#
# ACVP-DIR holds internalProjection.json of the ACVP-Server directories
# gen-val/json-files/ML-DSA-keyGen-FIPS204, ML-DSA-sigGen-FIPS204 and
# ML-DSA-sigVer-FIPS204 (https://github.com/usnistgov/ACVP-Server) as
# keyGen.json, sigGen.json and sigVer.json. WYCHEPROOF-DIR holds the
# testvectors_v1 files mldsa_65_sign_seed_test.json,
# mldsa_65_sign_noseed_test.json and mldsa_65_verify_test.json of
# https://github.com/C2SP/wycheproof.
#
# The suites take each ML-DSA-65 group of the pure external interface. They
# leave out the groups of HashML-DSA and of the internal interface, and each
# Wycheproof vector that gives mu and no message. A suite compares the
# SHA3-256 digest of a key or a signature that the module makes with the
# digest of the expected bytes.
import hashlib
import json
import os
import sys

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "stdlib")

HEADER = """// Generated by scripts/gen-mldsa.py from {src}. Do not edit by hand.
// {note}
"""

HELPERS = """
import "std/test";
import "std/hex";
import "std/crypto" as crypto;
import "std/crypto/mldsa";

function bytes(h: string): u8[] {
  match (hex.decode(h)) {
    Ok(b) => {
      return b;
    },
    Err(e) => {
      return [];
    }
  }
  return [];
}

function digest(b: [u8]): string {
  return hex.encode(crypto.sha3_256(b));
}

// Signs msg with k. An empty rnd selects the deterministic variant. want is
// the digest of the signature, or "" when signing must refuse.
function sign_with(k: mldsa.PrivateKey, msg: string, ctx: string, rnd: string, want: string, tc: string): string {
  let r = if (rnd == "") { k.sign_deterministic(bytes(msg), bytes(ctx)) } else { k.sign_derand(bytes(msg), bytes(ctx), bytes(rnd)) };
  match (r) {
    Ok(sig) => {
      if (want == "") {
        return tc + "signing accepted an invalid input";
      }
      if (digest(sig) != want) {
        return tc + "signature differs";
      }
      match (k.public_key().verify(bytes(msg), sig, bytes(ctx))) {
        Ok(_) => {},
        Err(e) => {
          return tc + "own signature refused: " + e.message();
        }
      }
    },
    Err(e) => {
      if (want != "") {
        return tc + "signing refused: " + e.message();
      }
    }
  }
  return "";
}

// KeyGen from a seed. An empty pk means that the seed must be refused.
function keygen(seed: string, pk: string, sk: string, tc: string): string {
  match (mldsa.private_key(bytes(seed))) {
    Ok(k) => {
      if (pk == "") {
        return tc + "seed accepted";
      }
      if (digest(k.public_key().bytes()) != pk) {
        return tc + "public key differs";
      }
      if (sk != "" && digest(k.bytes()) != sk) {
        return tc + "private key differs";
      }
    },
    Err(e) => {
      if (pk != "") {
        return tc + "seed refused: " + e.message();
      }
    }
  }
  return "";
}

// Signing with a key from a seed (sign_seed) or from its expanded encoding.
function sign(seeded: boolean, key: string, pk: string, msg: string, ctx: string, rnd: string, want: string, id: i32): string {
  let tc = "tc " + id.to_string() + ": ";
  let parsed = if (seeded) { mldsa.private_key(bytes(key)) } else { mldsa.expanded_private_key(bytes(key)) };
  match (parsed) {
    Ok(k) => {
      if (pk == "") {
        return tc + "invalid private key accepted";
      }
      if (digest(k.public_key().bytes()) != pk) {
        return tc + "public key differs";
      }
      return sign_with(k, msg, ctx, rnd, want, tc);
    },
    Err(e) => {
      if (pk != "" && want != "") {
        return tc + "private key refused: " + e.message();
      }
    }
  }
  return "";
}

function verify(pk: string, msg: string, ctx: string, sig: string, valid: boolean, id: i32): string {
  let tc = "tc " + id.to_string() + ": ";
  match (mldsa.public_key(bytes(pk))) {
    Ok(k) => {
      match (k.verify(bytes(msg), bytes(sig), bytes(ctx))) {
        Ok(_) => {
          if (!valid) {
            return tc + "invalid signature accepted";
          }
        },
        Err(e) => {
          if (valid) {
            return tc + "valid signature refused: " + e.message();
          }
        }
      }
    },
    Err(e) => {
      if (valid) {
        return tc + "public key refused: " + e.message();
      }
    }
  }
  return "";
}
"""


def s(x):
    return '"' + x.lower() + '"'


def digest(h):
    return hashlib.sha3_256(bytes.fromhex(h)).hexdigest()


def load(d, name):
    with open(os.path.join(d, name)) as f:
        return json.load(f)


def write(name, src, note, title, groups):
    lines = [HEADER.format(src=src, note=note).rstrip("\n"), HELPERS.rstrip("\n"), ""]
    its = []
    for gi, (label, key, body) in enumerate(groups):
        fn = "test_group_" + str(gi + 1)
        lines.append("function " + fn + "(): test.TestOutcome {")
        if key is not None:
            lines.append("  let key = " + s(key) + ";")
        lines.append("  let r = \"\";")
        for stmt in body:
            lines.append("  r = " + stmt + ";")
            lines.append("  if (r != \"\") {")
            lines.append("    return test.fail(r);")
            lines.append("  }")
        lines.append("  return test.pass();")
        lines.append("}")
        lines.append("")
        its.append((label, fn))
    lines.append("function main(): i32 {")
    lines.append("  let r = test.new(" + s(title) + ");")
    for label, fn in its:
        lines.append("  r = r.it(\"" + label + "\", " + fn + ");")
    lines.append("  return r.finish();")
    lines.append("}")
    path = os.path.join(OUT, name)
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(path, sum(len(b) for _, _, b in groups), "vectors in", len(groups), "groups")


def pure65(g):
    return g["parameterSet"] == "ML-DSA-65" and g.get("signatureInterface", "external") == "external" and g.get("preHash", "pure") == "pure"


def acvp(d):
    groups = []
    for g in load(d, "keyGen.json")["testGroups"]:
        if g["parameterSet"] != "ML-DSA-65":
            continue
        body = ["keygen(%s, %s, %s, \"tc %d: \")" % (s(t["seed"]), s(digest(t["pk"])), s(digest(t["sk"])), t["tcId"]) for t in g["tests"]]
        groups.append(("keyGen tgId %d" % g["tgId"], None, body))
    for g in load(d, "sigGen.json")["testGroups"]:
        if not pure65(g):
            continue
        body = []
        for t in g["tests"]:
            rnd = "" if g["deterministic"] else t["rnd"]
            body.append("sign(false, %s, %s, %s, %s, %s, %s, %d)" % (s(t["sk"]), s(digest(t["pk"])), s(t["message"]), s(t["context"]), s(rnd), s(digest(t["signature"])), t["tcId"]))
        kind = "deterministic" if g["deterministic"] else "hedged"
        groups.append(("sigGen tgId %d, %s" % (g["tgId"], kind), None, body))
    for g in load(d, "sigVer.json")["testGroups"]:
        if not pure65(g):
            continue
        body = ["verify(%s, %s, %s, %s, %s, %d)" % (s(t["pk"]), s(t["message"]), s(t["context"]), s(t["signature"]), "true" if t["testPassed"] else "false", t["tcId"]) for t in g["tests"]]
        groups.append(("sigVer tgId %d" % g["tgId"], None, body))
    note = "ML-DSA-65, pure external interface: keyGen, sigGen and sigVer."
    write("acvp_mldsa65_test.fern", "ACVP-Server gen-val/json-files/ML-DSA-*-FIPS204/internalProjection.json", note, "acvp ml-dsa-65", groups)


def wycheproof(d):
    groups = []
    for name, seeded in (("mldsa_65_sign_seed_test.json", True), ("mldsa_65_sign_noseed_test.json", False)):
        data = load(d, name)
        for gi, g in enumerate(data["testGroups"]):
            key = g["privateSeed"] if seeded else g["privateKey"]
            pk = "" if g.get("publicKey") is None else digest(g["publicKey"])
            body = []
            for t in g["tests"]:
                if "msg" not in t:
                    continue
                want = digest(t["sig"]) if t["result"] == "valid" else ""
                body.append("sign(%s, key, %s, %s, %s, %s, %s, %d)" % ("true" if seeded else "false", s(pk), s(t["msg"]), s(t.get("ctx", "")), s(t.get("rnd", "")), s(want), t["tcId"]))
            if body:
                groups.append(("%s group %d" % (name[:-5], gi + 1), key, body))
    data = load(d, "mldsa_65_verify_test.json")
    for gi, g in enumerate(data["testGroups"]):
        body = ["verify(key, %s, %s, %s, %s, %d)" % (s(t["msg"]), s(t.get("ctx", "")), s(t["sig"]), "true" if t["result"] == "valid" else "false", t["tcId"]) for t in g["tests"]]
        groups.append(("mldsa_65_verify_test group %d" % (gi + 1), g["publicKey"], body))
    note = "ML-DSA-65: sign with a seed, sign with an expanded key, and verify."
    write("wycheproof_mldsa65_test.fern", "Wycheproof testvectors_v1/mldsa_65_*_test.json", note, "wycheproof ml-dsa-65", groups)


def main():
    if len(sys.argv) != 3:
        print("usage: gen-mldsa.py ACVP-DIR WYCHEPROOF-DIR", file=sys.stderr)
        sys.exit(2)
    acvp(sys.argv[1])
    wycheproof(sys.argv[2])


if __name__ == "__main__":
    main()
