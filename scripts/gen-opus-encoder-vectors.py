#!/usr/bin/env python3
"""Freeze encoder analysis and complete-frame CRCs from hash-pinned libopus 1.4."""
import argparse
from pathlib import Path
import runpy
import subprocess
import zlib

ROOT = Path(__file__).resolve().parent.parent
TABLES = runpy.run_path(str(ROOT/'scripts/gen-opus-encoder-modes.py'))
REFERENCE = runpy.run_path(str(ROOT/'scripts/gen-silk-loss-vectors.py'))
CASES = [
    ('ANALYSIS_SHORT', ['analysis', '2', '12', '1', '21']),
    ('ANALYSIS_LONG', ['analysis', '41', '900', '1', '21']),
    ('ANALYSIS_LIMIT', ['analysis', '5', '900', '1', '21']),
    ('ENCODE_SHORT', ['encode', '1', '6', '1', '21']),
    ('ENCODE_LONG', ['encode', '7', '120', '1', '21']),
    ('ENCODE_WIDEBAND', ['encode', '11', '120', '3', '17']),
]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--archive', type=Path)
    parser.add_argument('--cmake', default='cmake')
    parser.add_argument('--fern', type=Path, default=ROOT/'bin/fern-selfhost')
    parser.add_argument('--output', type=Path, default=ROOT/'tests/stdlib/opus_encoder_vectors.fern')
    args = parser.parse_args()
    outputs = REFERENCE['reference'](args.archive, args.cmake, 'celt_encoder_trace.c',
                                     [row[1] for row in CASES], pin=TABLES['PIN'], archive_sha=TABLES['ARCHIVE_SHA'])
    lines = ['// Generated by scripts/gen-opus-encoder-vectors.py.',
             '// Unmodified scalar libopus '+TABLES['PIN']+' (1.4), BSD-3-Clause.', '']
    for (name, _), output in zip(CASES, outputs, strict=True):
        lines.append(f'pub const {name}: u32 = {zlib.crc32(output)}u32;')
    args.output.write_text('\n'.join(lines)+'\n')
    subprocess.run([str(args.fern), '-fmt', '-w', str(args.output)], check=True)


if __name__ == '__main__':
    main()
