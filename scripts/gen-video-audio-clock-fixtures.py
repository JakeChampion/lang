#!/usr/bin/env python3
"""Create exact rational controls for audio-derived video clocks."""
from fractions import Fraction
import os
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent.parent
MAXIMUM = (1 << 63) - 1


def controls():
    rows = []
    for rate in (1, 8000, 11025, 16000, 22050, 44100, 48000, 96000, 192000, 2147483647):
        for frames in (0, 1, rate - 1, rate, rate + 1, rate * 123 + rate // 3, 1099511627776):
            elapsed = Fraction(frames * 1000000, rate).__floor__()
            if elapsed + 7000000 <= MAXIMUM:
                rows.append((123456, 7000000, frames + 123456, rate, 9000000000000000000, elapsed + 7000000))
    rows += [(0, 0, MAXIMUM, 2147483647, MAXIMUM, (MAXIMUM * 1000000) // 2147483647),
             (MAXIMUM, MAXIMUM, MAXIMUM, 48000, MAXIMUM, MAXIMUM)]
    return rows


def main():
    lines = ['// Generated by scripts/gen-video-audio-clock-fixtures.py with Python fractions.Fraction.',
             'pub struct Vector { first_frame: i64, first_us: i64, position: i64, rate: i32, ns: i64, media_us: i64 }',
             'pub function vectors(): Vector[] {', '  return [']
    rows = controls()
    for a, b, c, d, e, f in rows:
        lines.append(f'    Vector {{ first_frame: {a}i64, first_us: {b}i64, position: {c}i64, rate: {d}, ns: {e}i64, media_us: {f}i64 }},')
    lines += ['  ];', '}']
    target = ROOT / 'tests/stdlib/video_audio_clock_vectors.fern'
    target.write_text('\n'.join(lines) + '\n')
    compiler = os.environ.get('FERN') or subprocess.check_output([str(ROOT / 'bootstrap/bootstrap.sh'), 'stage0'], text=True).strip()
    subprocess.run([compiler, '-fmt', '-w', str(target)], check=True)
    print(len(rows), 'independent audio frame-to-time controls')


if __name__ == '__main__':
    main()
