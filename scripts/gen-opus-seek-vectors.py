#!/usr/bin/env python3
"""Freeze independent cold-seek PCM as XOR deltas from the complete-file corpus."""
import argparse
import base64
import json
from pathlib import Path
import re
import runpy
import struct
import subprocess
import zlib

ROOT = Path(__file__).resolve().parent.parent
FILES = runpy.run_path(str(ROOT/'scripts/gen-opus-file-vectors.py'))


class Reader:
    def __init__(self, data):
        self.data, self.at = data, 0

    def fields(self, pattern):
        result = struct.unpack_from(pattern, self.data, self.at)
        self.at += struct.calcsize(pattern)
        return result

    def blob(self):
        size, = self.fields('<I')
        result = self.data[self.at:self.at+size]
        if len(result) != size:
            raise ValueError('truncated complete-file corpus')
        self.at += size
        return result


def complete_cases():
    text = (ROOT/'tests/stdlib/opus_file_vectors.fern').read_text()
    body = re.search(r'pub const CASES: string\[\] = \[(.*?)\];', text, re.S)[1]
    cases = []
    for encoded in re.findall(r'"([A-Za-z0-9+/=]+)"', body):
        reader = Reader(zlib.decompress(base64.b64decode(encoded)))
        raw = reader.blob()
        count, = reader.fields('<I')
        links = []
        for _ in range(count):
            serial, initial, frames, *fields = reader.fields('<Iqq8q')
            reader.blob()  # Channel map.
            reader.blob()  # Vendor.
            comments, = reader.fields('<I')
            for _ in range(comments):
                reader.blob()
            reader.blob()  # Binary suffix.
            links.append({'serial': serial, 'initial': initial, 'frames': frames,
                          'channels': fields[1], 'pcm': reader.blob()})
        if reader.at != len(reader.data):
            raise ValueError('trailing complete-file fixture data')
        cases.append((raw, links))
    return cases


def generate(records):
    cases = complete_cases()
    if len(records) != 10 or [r['case'] for r in records] != [*range(9), 10] or len(cases) != 10:
        raise ValueError('unexpected seek corpus')
    lines = ['// Generated by scripts/gen-opus-seek-vectors.py.',
             '// Cold seeks through unmodified libopusfile '+FILES['PINS']['opusfile'][0]+'.',
             '// PCM XOR deltas use the independent complete-file corpus as their baseline.',
             'pub const CASES: string[] = [']
    for row, (raw, links) in zip(records, cases, strict=True):
        if len(raw) != row['file_bytes'] or zlib.crc32(raw) != row['file_crc']:
            raise ValueError('reference input differs from the frozen complete-file corpus')
        if [zlib.crc32(link['pcm']) for link in links] != row['pcm_crc']:
            raise ValueError('reference full decode differs from the frozen corpus')
        data = bytearray(struct.pack('<I', len(row['points'])))
        for point in row['points']:
            full = bytearray()
            for li in range(point['link'], len(links)):
                start = point['position'] if li == point['link'] else 0
                full.extend(links[li]['pcm'][start*links[li]['channels']*4:])
            samples = point['pcm']
            if len(samples)*4 != len(full):
                raise ValueError('seek sample count differs from the remaining playable frames')
            delta = bytearray()
            for (baseline,), bits in zip(struct.iter_unpack('<I', full), samples, strict=True):
                delta.extend(struct.pack('<I', baseline ^ bits))
            data.extend(struct.pack('<IqI', point['link'], point['position'], len(delta)))
            data.extend(delta)
        packed = base64.b64encode(zlib.compress(data, 9)).decode('ascii')
        lines.append('  '+json.dumps(packed)+',')
    lines += ['];', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in FILES['PINS']:
        parser.add_argument('--'+name+'-archive', type=Path)
    parser.add_argument('--cmake', default='cmake')
    parser.add_argument('--fern', type=Path, default=ROOT/'bin/fern-selfhost')
    parser.add_argument('--output', type=Path, default=ROOT/'tests/stdlib/opus_seek_vectors.fern')
    args = parser.parse_args()
    args.output.write_text(generate(FILES['reference'](args, 'opus_seek.c')))
    subprocess.run([str(args.fern), '-fmt', '-w', str(args.output)], check=True)


if __name__ == '__main__':
    main()
