#!/usr/bin/env python3
"""Generate QTRLE MOV files and independent packet and pixel references."""
import json
import os
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent.parent
WIDTH, HEIGHT, COUNT = 17, 5, 6


def run(*args):
    return subprocess.check_output(args)


def pixels(depth):
    base = bytearray()
    for y in range(HEIGHT):
        for x in range(WIDTH):
            base += bytes((255 if depth == 24 else (37 * x + 19 * y) % 256,
                           x * 11, y * 43, (x + y) * 9))
    frames = [bytes(base)]
    base[4:8] = bytes((255 if depth == 24 else 0, 17, 29, 41))
    frames += [bytes(base), bytes(base)]
    for x in range(WIDTH):
        base[(2 * WIDTH + x) * 4:(2 * WIDTH + x + 1) * 4] = bytes((255, 31, 47, 63))
    frames.append(bytes(base))
    base[-8:] = bytes((255, 12, 24, 36, 255 if depth == 24 else 128, 48, 60, 72))
    frames += [bytes(base), bytes(base)]
    return frames


def metadata(path):
    return json.loads(run("ffprobe", "-v", "error", "-ignore_editlist", "1", "-select_streams", "v",
                          "-show_packets", "-show_streams", "-of", "json", str(path)))


def generate(directory):
    cases = []
    for depth in (24, 32):
        raw = directory / f"source-{depth}.argb"
        raw.write_bytes(b"".join(pixels(depth)))
        path = directory / f"qtrle-{depth}.mov"
        options = ["-movflags", "+faststart"] if depth == 32 else []
        run("ffmpeg", "-v", "error", "-y", "-f", "rawvideo", "-pixel_format", "argb",
            "-video_size", f"{WIDTH}x{HEIGHT}", "-framerate", "6", "-i", str(raw),
            "-c:v", "qtrle", "-pix_fmt", "rgb24" if depth == 24 else "argb", "-g", "3",
            "-threads", "1", *options, str(path))
        cases.append((f"qtrle-{depth}", path, [depth]))
    multiple = directory / "qtrle-two-tracks.mov"
    run("ffmpeg", "-v", "error", "-y", "-i", str(cases[0][1]), "-i", str(cases[1][1]),
        "-map", "0:v:0", "-map", "1:v:0", "-c", "copy", str(multiple))
    cases.append(("qtrle-two-tracks", multiple, [24, 32]))
    audio = directory / "qtrle-audio.mov"
    run("ffmpeg", "-v", "error", "-y", "-i", str(cases[1][1]), "-f", "lavfi", "-i",
        "sine=frequency=440:sample_rate=48000", "-t", "1", "-c:v", "copy", "-c:a", "aac", str(audio))
    cases.append(("qtrle-audio", audio, [32]))
    legacy = directory / "qtrle-legacy.mov"
    data = bytearray(cases[0][1].read_bytes())
    assert data[4:8] == b"ftyp"
    data[4:8] = b"free"
    legacy.write_bytes(data)
    cases.append(("qtrle-legacy", legacy, [24]))
    for name, path, depths in cases:
        reference = metadata(path)
        assert len(reference["streams"]) == len(depths)
        for i, depth in enumerate(depths):
            stream = reference["streams"][i]
            assert stream["codec_name"] == "qtrle"
            assert stream["pix_fmt"] == ("rgb24" if depth == 24 else "argb")
            packets = [p for p in reference["packets"] if p["stream_index"] == stream["index"]]
            assert len(packets) == COUNT and "K" in packets[0]["flags"]
            assert sum("K" in p["flags"] for p in packets) >= 2
            assert any(int(p["size"]) <= 7 and "K" not in p["flags"] for p in packets)
            decoded = run("ffmpeg", "-v", "error", "-ignore_editlist", "1", "-i", str(path),
                          "-map", f"0:v:{i}", "-vsync", "0", "-pix_fmt", "argb", "-f", "rawvideo", "-")
            assert decoded == b"".join(pixels(depth)), (name, i, "reference pixels")
    return cases


def main():
    lines = ["// Generated by scripts/gen-video-qtrle-mov-fixtures.py with FFmpeg and FFprobe.",
             "pub struct Packet { offset: i64, bytes: i32, dts: i64, pts: i64, duration: u32, sync: boolean }",
             "pub struct Track { depth: i32, scale: u32, packets: Packet[], frames: string[] }",
             "pub struct Vector { name: string, bytes: string, tracks: Track[] }",
             "pub function vectors(): Vector[] {", "  return ["]
    with tempfile.TemporaryDirectory() as temporary:
        for name, path, depths in generate(Path(temporary)):
            reference = metadata(path)
            lines.append(f'    Vector {{ name: "{name}", bytes: "{path.read_bytes().hex()}", tracks: [')
            for stream, depth in zip(reference["streams"], depths):
                numerator, scale = map(int, stream["time_base"].split("/"))
                assert numerator == 1
                packets = [p for p in reference["packets"] if p["stream_index"] == stream["index"]]
                assert len(packets) == COUNT
                lines.append(f"      Track {{ depth: {depth}, scale: {scale}u32, packets: [")
                for p in packets:
                    lines.append(f'        Packet {{ offset: {p["pos"]}i64, bytes: {p["size"]}, dts: {p["dts"]}i64, pts: {p["pts"]}i64, duration: {p["duration"]}u32, sync: {str("K" in p["flags"]).lower()} }},')
                lines.append("      ], frames: [" + ", ".join('"' + p.hex() + '"' for p in pixels(depth)) + "] },")
            lines.append("    ] },")
    lines += ["  ];", "}"]
    target = ROOT / "tests/stdlib/video_qtrle_mov_vectors.fern"
    target.write_text("\n".join(lines) + "\n")
    compiler = os.environ.get("FERN") or run(str(ROOT / "bootstrap/bootstrap.sh"), "stage0").decode().strip()
    subprocess.run([compiler, "-fmt", "-w", str(target)], check=True)
    print("Wrote", target.relative_to(ROOT))


if __name__ == "__main__":
    main()
