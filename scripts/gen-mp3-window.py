#!/usr/bin/env python3
"""Generate the MPEG audio synthesis window from the pinned public-domain PDMP3 decoder."""
import argparse
import hashlib
from pathlib import Path
import re
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
REV = '2a206a3ada78ec4d13434847f05f50097c60c36a'
SHA = '3fa7df3b90d47696e656cb0d277296f19048832432c4b2a0584b64c71bfc1ff7'
URL = f'https://raw.githubusercontent.com/technosaurus/PDMP3/{REV}/pdmp3.c'
OUT = ROOT / 'internal/stdlib/std/audio/mp3/window.fern'


def generate(source):
    start = source.index('g_synth_dtbl[512] = {')
    end = source.index('}', start)
    values = [float(v) for v in re.findall(r'-?\d+\.\d+', source[start:end])]
    assert len(values) == 512
    scaled = [round(v * 65536) for v in values]
    # The ISO table holds exact multiples of 1/65536 at nine decimals.
    assert all(abs(v * 65536 - s) < 0.001 for v, s in zip(values, scaled))
    lines = ['// Generated by scripts/gen-mp3-window.py from PDMP3 ' + REV + '.',
             '// Public domain (Unlicense): https://unlicense.org/',
             '// Each entry is the ISO 11172-3 synthesis window coefficient D[i] times 65536.', '',
             'pub const SYNTHESIS_WINDOW: i32[] = [']
    for i in range(0, 512, 16):
        lines.append('  ' + ', '.join(str(v) for v in scaled[i:i + 16]) + ',')
    lines.append('];')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--source', type=Path, help='local pinned pdmp3.c for offline verification')
    args = parser.parse_args()
    data = args.source.read_bytes() if args.source else urllib.request.urlopen(URL, timeout=30).read()
    assert hashlib.sha256(data).hexdigest() == SHA
    generated = generate(data.decode())
    if args.check:
        if OUT.read_text() != generated:
            raise SystemExit('MP3 window differs from the pinned source')
    else:
        OUT.write_text(generated)
