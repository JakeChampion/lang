#!/usr/bin/env python3
"""Freeze libvorbisfile seek edge cases, including empty links and split packets."""
import argparse
import base64
from pathlib import Path
import runpy
import struct
import subprocess
import tempfile
import zlib

ROOT = Path(__file__).resolve().parent.parent
FILE = runpy.run_path(str(ROOT / 'scripts/gen-vorbis-file-vectors.py'))
PACKET = FILE['PACKET']


def pack(data):
    return base64.b64encode(zlib.compress(data, 9)).decode()


def stream(serial, empty=False, setup_pad=False, audio_pad=False, interleaved=False):
    packets = PACKET['floor0_packets'](8, 1, 1, 0)
    ident, comment, setup = packets[:3]
    complete, page = FILE['complete'], FILE['page']
    encoded = complete(serial, 0, 0, 2, [ident])
    if interleaved:
        encoded += complete(serial + 1000, 0, 0, 2, [b'unknown-stream'])
    sequence = 1
    if setup_pad:
        setup += bytes(70000)
        encoded += complete(serial, sequence, 0, 0, [comment])
        sequence += 1
        encoded += page(serial, sequence, -1, 0, setup[:65025], [255] * 255)
        sequence += 1
        encoded += complete(serial, sequence, 0, 1, [setup[65025:]])
        sequence += 1
    else:
        encoded += complete(serial, sequence, 0, 0, [comment, setup])
        sequence += 1
    audio = packets[3:4] if empty else packets[3:]
    if audio_pad:
        first = audio[0] + bytes(70000)
        encoded += page(serial, sequence, -1, 0, first[:65025], [255] * 255)
        sequence += 1
        if interleaved:
            encoded += complete(serial + 1000, 1, 0, 0, [b'middle'])
        encoded += complete(serial, sequence, 95, 5, [first[65025:], *audio[1:]])
        if interleaved:
            encoded += complete(serial + 1000, 2, 0, 4, [b'end'])
    else:
        encoded += complete(serial, sequence, 0 if empty else 95, 4, audio)
    return encoded


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--reference', required=True, type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    fixtures = [('empty-link', stream(200, empty=True)),
        ('leading-empty-link', stream(201, empty=True) + stream(202)),
        ('trailing-empty-link', stream(203) + stream(204, empty=True)),
        ('adjacent-empty-links', stream(205, empty=True) + stream(206, empty=True) + stream(207)),
        ('continued-setup', stream(208, setup_pad=True)),
        ('continued-audio', stream(209, audio_pad=True)),
        ('interleaved-audio', stream(210, audio_pad=True, interleaved=True))]
    text = '// Generated by scripts/gen-vorbis-seek-vectors.py.\n// Reference: Xiph libvorbisfile 1.3.7, public float and track APIs.\n'
    text += '// PCM starts with ov_pcm_seek(0); interleaved input uses the streaming API.\n'
    text += 'pub struct Vector { name: string, encoded: string, formats: string, pcm: string }\n\n'
    text += 'pub function vectors(): Vector[] {\n  return [\n'
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory) / 'input.ogg'
        for name, encoded in fixtures:
            path.write_bytes(encoded)
            tracks = subprocess.check_output([str(args.reference), 'tracks', str(path)])
            count = struct.unpack_from('<I', tracks)[0]
            assert len(tracks) == 4 + 16 * count
            formats, pcms = b'', []
            for i in range(count):
                rate, channels, frames = struct.unpack_from('<IIQ', tracks, 4 + 16 * i)
                assert frames < 2**31
                formats += struct.pack('<III', rate, channels, frames)
                pcms.append(bytearray())
            mode = 'stream' if name == 'interleaved-audio' else 'seek_from_start'
            raw = subprocess.check_output([str(args.reference), mode, str(path)])
            at = 0
            while at < len(raw):
                link, rate, channels, frames = struct.unpack_from('<IIII', raw, at)
                at += 16
                assert struct.unpack_from('<II', formats, 12 * link) == (rate, channels)
                size = frames * channels * 4
                pcms[link] += raw[at:at + size]
                at += size
            assert at == len(raw)
            for i, pcm in enumerate(pcms):
                _, channels, frames = struct.unpack_from('<III', formats, 12 * i)
                assert len(pcm) == frames * channels * 4, (name, i, len(pcm), frames)
            pcm = b''.join(pcms)
            text += f'    Vector {{ name: "{name}", encoded: "{pack(encoded)}", formats: "{pack(formats)}", pcm: "{pack(pcm)}" }},\n'
            print(name, len(encoded), count, len(pcm) // 4)
    text += '  ];\n}\n'
    target = ROOT / 'tests/stdlib/vorbis_seek_vectors.fern'
    if args.check:
        if target.read_text() != text:
            parser.exit(1, 'Vorbis seek fixtures are stale\n')
    else:
        target.write_text(text)


if __name__ == '__main__':
    main()
