#!/usr/bin/env python3
"""Freeze SILK loss and recovery PCM from unmodified, pinned libopus."""
import argparse
import hashlib
import io
import json
from pathlib import Path
import runpy
import struct
import subprocess
import tarfile
import tempfile
import urllib.request
import zlib

ROOT = Path(__file__).resolve().parent.parent
PIN = '22244de5a79bd1d6d623c32e72bf1954b56235be'
ARCHIVE_SHA = '3267aa969b2b26542417f57819a5bc25d5079355300307dd2dddc7c704aed418'
TABLES = runpy.run_path(str(Path(__file__).with_name('gen-silk-tables.py')))


def reference(archive, cmake, helper='silk_loss.c'):
    data = archive.read_bytes() if archive else urllib.request.urlopen(
        f'https://codeload.github.com/xiph/opus/tar.gz/{PIN}', timeout=60).read()
    if hashlib.sha256(data).hexdigest() != ARCHIVE_SHA:
        raise ValueError('libopus archive hash mismatch')
    with tempfile.TemporaryDirectory() as directory:
        root = Path(directory)
        with tarfile.open(fileobj=io.BytesIO(data)) as tar:
            tar.extractall(root, filter='data')
        source, build = root/('opus-'+PIN), root/'build'
        subprocess.run([cmake, '-S', str(source), '-B', str(build), '-DCMAKE_BUILD_TYPE=Release',
                        '-DOPUS_DISABLE_INTRINSICS=ON', '-DOPUS_ASSERTIONS=ON',
                        '-DOPUS_BUILD_TESTING=OFF', '-DOPUS_BUILD_PROGRAMS=OFF',
                        '-DOPUS_DRED=OFF', '-DOPUS_OSCE=OFF'], check=True, stdout=subprocess.DEVNULL)
        subprocess.run([cmake, '--build', str(build), '-j', '2'], check=True, stdout=subprocess.DEVNULL)
        command = ['cc', '-O2', '-DHAVE_CONFIG_H']
        for include in [build, source, source/'include', source/'celt', source/'silk']:
            command.extend(['-I', str(include)])
        executable = root/'silk-loss-reference'
        command.extend([str(ROOT/'scripts/audio-reference'/helper), str(build/'libopus.a')])
        if helper == 'silk_loss.c':
            command.append('-Wl,--wrap=silk_resampler')
        command.extend(['-lm', '-o', str(executable)])
        subprocess.run(command, check=True)
        return [json.loads(line) for line in subprocess.check_output([str(executable)]).splitlines()]


def generate(records):
    if len(records) != 54:
        raise ValueError('unexpected loss corpus size')
    rows = []
    for row in records:
        packet = bytes.fromhex(row['packet'])
        samples = row['pcm']
        checksum = zlib.crc32(struct.pack('<'+'h'*len(samples), *samples))
        if checksum >= 2147483648:
            checksum -= 4294967296
        rows.extend([row['rate'], row['channels'], row['duration'], row['stream'], row['lost'], len(packet), *packet,
                     len(samples), checksum, row['losses'], *samples[:8], *samples[-8:]])
    return '\n'.join(['// Generated by scripts/gen-silk-loss-vectors.py.',
                      '// Unmodified libopus '+PIN+', BSD-3-Clause.', '']+
                     TABLES['declaration']('PACKETS', rows, 'i32'))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--archive', type=Path, help='local pinned libopus archive for offline generation')
    parser.add_argument('--cmake', default='cmake')
    parser.add_argument('--output', type=Path, default=ROOT/'tests/stdlib/opus_silk_loss_vectors.fern')
    parser.add_argument('--fern', type=Path, default=ROOT/'bin/fern-selfhost')
    args = parser.parse_args()
    args.output.write_text(generate(reference(args.archive, args.cmake)))
    subprocess.run([str(args.fern), '-fmt', '-w', str(args.output)], check=True)


if __name__ == '__main__':
    main()
