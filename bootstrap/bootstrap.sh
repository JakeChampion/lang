#!/usr/bin/env bash
#
# bootstrap/bootstrap.sh — build the self-host compiler from a checkout with
# NO Go toolchain and NO native backend on the path.
#
#   bootstrap.sh build       (make bootstrap)  stage0 -> stage1, install it
#   bootstrap.sh distcheck   (make distcheck)  stage1 -> stage2 -> stage3, stage2 == stage3
#   bootstrap.sh stage0      print the verified stage0's path and nothing else,
#                            for a caller that compiles with the pin itself
#                            (the self-host test harness builds its drivers
#                            with it)
#
#   stage0   a pinned earlier compiler (bootstrap/stage0.lock), or the binary
#            named by STAGE0=<path>
#   stage1   stage0 compiles compiler/fern.fern for this host; it
#            must then compile and run a one-line program and coreutils/tr
#            (the smoke test), and
#            is installed as bin/fern-selfhost — the same compiler `make
#            selfhost-cli` builds with the native toolchain
#   stage2   stage1 compiles the same source: the current compiler, built by
#            a compiler that is itself the current source
#   stage3   stage2 compiles the same source once more. stage2 and stage3 must
#            be byte-identical: a compiler that reproduces itself through its
#            own output is the reproducibility gate, and a difference is
#            either nondeterminism or a miscompile that changed the compiler's
#            own behaviour. stage1 is not part of the comparison: its code was
#            generated by stage0, so it differs from stage2 whenever the code
#            generator changed after the pin was built.
#
# The pinned stage0 is downloaded once into build/bootstrap/ and verified
# against the lock's sha256 of the UNCOMPRESSED binary before it runs.
# docs/BOOTSTRAP.md is the runbook: refreshing the pin, debugging a
# stage2 != stage3 divergence, what the pin does and does not prove.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LOCK="$ROOT/bootstrap/stage0.lock"
OUT="$ROOT/build/bootstrap"
ENTRY="$ROOT/compiler/fern.fern"
STDLIB="$ROOT/internal/stdlib"

die() { echo "bootstrap: $*" >&2; exit 1; }

mode="${1:-build}"
case "$mode" in build|distcheck|stage0) ;; *) die "usage: bootstrap.sh [build|distcheck|stage0]" ;; esac

case "$(uname -s)/$(uname -m)" in
  Linux/x86_64)  HOST=x86-64-linux ;;
  Linux/aarch64) HOST=arm64-linux ;;
  Darwin/arm64)  HOST=arm64-darwin ;;
  *) die "unsupported bootstrap host $(uname -s)/$(uname -m) (x86-64 Linux, arm64 Linux, arm64 macOS)" ;;
esac

sha256() {
  if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1" | cut -d' ' -f1
  else shasum -a 256 "$1" | cut -d' ' -f1; fi
}

size() { wc -c < "$1" | tr -d ' '; }

# stage1_key: what stage1 is built from, so a distcheck rebuilds a stage1
# that an earlier build left behind for different sources or another stage0.
stage1_key() {
  local sum="sha256sum"
  command -v sha256sum >/dev/null 2>&1 || sum="shasum -a 256"
  {
    echo "stage0 $(sha256 "$stage0")"
    (cd "$ROOT" && find compiler internal/stdlib -type f -print0 | LC_ALL=C sort -z | xargs -0 $sum)
  } | $sum | cut -d' ' -f1
}

# lock_field KEY prints the value of the lock's `KEY value` line.
lock_field() {
  local v
  v="$(awk -v k="$1" '$1 == k { print $2; exit }' "$LOCK")"
  [ -n "$v" ] || die "$LOCK has no '$1' line"
  echo "$v"
}

# resolve_stage0 sets $stage0 to an executable: STAGE0=<path> if given, else
# the lock's pin for this host, fetched into the cache on first use. Its
# progress lines go to stderr so `bootstrap.sh stage0` can print the path alone.
resolve_stage0() {
  if [ -n "${STAGE0:-}" ]; then
    [ -x "$STAGE0" ] || die "STAGE0=$STAGE0 is not an executable file"
    stage0="$(cd "$(dirname "$STAGE0")" && pwd)/$(basename "$STAGE0")"
    echo "stage0: $stage0 (local, sha256 $(sha256 "$stage0"))" >&2
    return
  fi
  [ -f "$LOCK" ] || die "no $LOCK and no STAGE0=<path> given"
  local url want tag asset got
  url="$(lock_field url)"
  want="$(lock_field "$HOST")"
  tag="${url##*/}"
  stage0="$OUT/stage0/$tag/fern-selfhost-$HOST"
  if [ ! -x "$stage0" ]; then
    # Per-process scratch names, published by one rename: the two worker
    # processes of a CI shard resolve the pin at the same moment, and a
    # shared scratch name let one rename the file the other was still
    # checking. Both end up with the same verified bytes either way.
    local gz tmp
    gz="$stage0.$$.gz"
    tmp="$stage0.$$.tmp"
    asset="$url/fern-selfhost-$HOST.gz"
    echo "stage0: downloading $asset" >&2
    mkdir -p "$(dirname "$stage0")"
    curl -fsSL --retry 3 --retry-delay 2 -o "$gz" "$asset" \
      || { rm -f "$gz"; die "download failed: $asset"; }
    gzip -dc "$gz" > "$tmp" || { rm -f "$gz" "$tmp"; die "$asset is not gzip data"; }
    rm -f "$gz"
    got="$(sha256 "$tmp")"
    if [ "$got" != "$want" ]; then
      rm -f "$tmp"
      die "sha256 mismatch for $asset: lock pins $want, downloaded $got"
    fi
    chmod +x "$tmp"
    mv -f "$tmp" "$stage0"
  fi
  got="$(sha256 "$stage0")"
  [ "$got" = "$want" ] || die "cached $stage0 has sha256 $got, lock pins $want — delete it and re-run"
  echo "stage0: $tag for $HOST (sha256 $got)" >&2
}

# stage0 prints the resolved pin's path on stdout and nothing else.
stage0() {
  resolve_stage0
  echo "$stage0"
}

# measured FILE CMD...: CMD, with its wall seconds and peak resident set in
# kB written to FILE. python3's getrusage is the one reading of a child's
# peak that every host has (GNU time is not on the Linux runners, and
# macOS's reports bytes); without python3 the wall is read alone.
measured() {
  local file="$1" t0
  shift
  if command -v python3 >/dev/null 2>&1; then
    python3 - "$file" "$@" <<'PY'
import resource, subprocess, sys, time
t0 = time.monotonic()
code = subprocess.run(sys.argv[2:]).returncode
wall = time.monotonic() - t0
peak = resource.getrusage(resource.RUSAGE_CHILDREN).ru_maxrss
if sys.platform == "darwin":
    peak //= 1024
with open(sys.argv[1], "w") as f:
    f.write(f"{wall:.0f} {peak}\n")
sys.exit(code)
PY
  else
    t0=$(date +%s)
    "$@" || return $?
    echo "$(( $(date +%s) - t0 ))" > "$file"
  fi
}

# stage NAME COMPILER: compile the compiler's own source with COMPILER into
# $OUT/NAME, for this host, and report the cost.
stage() {
  local out wall peak
  out="$OUT/$1"
  rm -f "$out" "$out.measure"
  measured "$out.measure" "$2" -target "$HOST" -o "$out" "$ENTRY" "$STDLIB" \
    || die "$1 failed: $2 could not compile $ENTRY (an old stage0 meeting a construct it does not know? see docs/BOOTSTRAP.md on refreshing the pin)"
  chmod +x "$out"
  read -r wall peak < "$out.measure"
  echo "$1: $wall s, ${peak:+$((peak / 1024)) MB peak RSS, }$(size "$out") bytes"
}

# report: the stages' costs as `metric<TAB>value` rows in
# $OUT/distcheck-report.txt, the format scripts/perf-history records, so the
# self-compile's wall and peak memory per host are a trend over main.
report() {
  local name wall peak
  {
    echo "# bootstrap/bootstrap.sh report — host $HOST"
    for name in stage1 stage2 stage3; do
      [ -s "$OUT/$name.measure" ] || continue
      read -r wall peak < "$OUT/$name.measure"
      printf 'bootstrap/%s/%s.wall_s\t%s\n' "$HOST" "$name" "$wall"
      [ -n "$peak" ] && printf 'bootstrap/%s/%s.peak_rss_mb\t%s\n' "$HOST" "$name" "$((peak / 1024))"
      printf 'bootstrap/%s/%s.size_bytes\t%s\n' "$HOST" "$name" "$(size "$OUT/$name")"
    done
  } > "$OUT/distcheck-report.txt"
}

# smoke COMPILER: the compiler must compile a one-line program and
# coreutils/tr, and both results must run — a binary that links but cannot
# execute is not a compiler, and one that only handles a one-liner is not
# one either.
smoke() {
  local src bin code
  src="$OUT/smoke.fern"
  bin="$OUT/smoke"
  echo 'function main(): i32 { return 42; }' > "$src"
  rm -f "$bin"
  "$1" -target "$HOST" -o "$bin" "$src" "$STDLIB" || die "smoke: $1 could not compile $src"
  chmod +x "$bin"
  code=0
  "$bin" || code=$?
  [ "$code" = 42 ] || die "smoke: program compiled by $1 exited $code, want 42"
  # A one-line program never reaches the lowering of records, matches and
  # imported modules, where a stage1 built through the AST lowering aborts
  # (#9763). coreutils/tr is a real multi-module program that does.
  bin="$OUT/smoke-tr"
  rm -f "$bin"
  "$1" -O -target "$HOST" -o "$bin" "$ROOT/coreutils/tr.fern" "$STDLIB" \
    || die "smoke: $1 could not compile coreutils/tr.fern"
  chmod +x "$bin"
  local got
  # A here-string rather than a pipe: under pipefail, a tr that exits
  # without reading would fail the writer with SIGPIPE instead.
  got="$("$bin" a-c x-z <<<'abc')" || die "smoke: tr compiled by $1 failed"
  [ "$got" = xyz ] || die "smoke: tr compiled by $1 printed '$got', want 'xyz'"
  echo "smoke: $1 compiles a program and coreutils/tr, and both run"
}

build() {
  resolve_stage0
  rm -f "$OUT/stage1.key"
  stage stage1 "$stage0"
  smoke "$OUT/stage1"
  stage1_key > "$OUT/stage1.key"
  mkdir -p "$ROOT/bin"
  # A fresh file, never a write into the old one: macOS refuses to run an
  # executable that was overwritten in place after it last ran (SIGKILL).
  rm -f "$ROOT/bin/fern-selfhost"
  cp "$OUT/stage1" "$ROOT/bin/fern-selfhost"
  echo "installed bin/fern-selfhost ($HOST, sha256 $(sha256 "$OUT/stage1"))"
  # bin/fern compiles with this only when the key beside it names the sources
  # bin/fern embeds (internal/tools/launcher). Computing the key takes Go and
  # cmd/fern; without them the old key goes, so no bin/fern uses this.
  local key
  if key="$(cd "$ROOT" && go run ./cmd/fern -selfhost-key 2>/dev/null)"; then
    echo "$key" > "$ROOT/bin/fern-selfhost.key"
  else
    rm -f "$ROOT/bin/fern-selfhost.key"
  fi
}

distcheck() {
  resolve_stage0
  if [ ! -x "$OUT/stage1" ] || [ "$(cat "$OUT/stage1.key" 2>/dev/null)" != "$(stage1_key)" ]; then
    build
  else
    echo "stage1: reused, built from these sources by this stage0"
  fi
  stage stage2 "$OUT/stage1"
  stage stage3 "$OUT/stage2"
  if ! cmp -s "$OUT/stage2" "$OUT/stage3"; then
    echo "bootstrap: stage2 != stage3 — the compiler does not reproduce itself" >&2
    cmp "$OUT/stage2" "$OUT/stage3" >&2 || true
    echo "  stage2: $(size "$OUT/stage2") bytes  $OUT/stage2" >&2
    echo "  stage3: $(size "$OUT/stage3") bytes  $OUT/stage3" >&2
    die "both binaries are kept; docs/BOOTSTRAP.md has the bisection recipe"
  fi
  if cmp -s "$OUT/stage1" "$OUT/stage2"; then
    echo "stage1 == stage2: stage0 generates the same code as the current source"
  else
    echo "stage1 != stage2: stage0 generates different code from the current source (its pin predates a code generator change)"
  fi
  echo "stage2 == stage3: fixed point reached (sha256 $(sha256 "$OUT/stage3"))"
  report
}

mkdir -p "$OUT"
"$mode"
