func TestWasmP3StreamExportImport(t *testing.T) {
	skipIfPreview2Missing(t)

	comp := component.BuildStreamExportImportComponent(p3StreamProducerCore, p3StreamConsumerCore, p3PendMemCore, component.CValtypeU8, component.CValtypeU32)
	dir := t.TempDir()
	p := filepath.Join(dir, "streamimp.wasm")
	if err := os.WriteFile(p, comp, 0o644); err != nil {
		t.Fatal(err)
	}
	out, err := exec.Command("wasmtime", "run",
		"-W", "component-model-async,component-model-async-stackful",
		"--invoke", "run()", p).CombinedOutput()
	if err != nil {
		t.Fatalf("wasmtime run (stream export/import): %v\n%s", err, out)
	}
	if !bytes.Contains(out, []byte("42")) {
		t.Errorf("stream export/import: got %q, want 42 (10+20+12)", bytes.TrimSpace(out))
	}
}
