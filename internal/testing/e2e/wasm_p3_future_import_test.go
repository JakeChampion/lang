func TestWasmP3FutureExportImport(t *testing.T) {
	skipIfPreview2Missing(t)

	comp := component.BuildFutureExportImportComponent(p3FutureProducerCore, p3FutureConsumerCore, p3PendMemCore, component.CValtypeU32)
	dir := t.TempDir()
	p := filepath.Join(dir, "futureimp.wasm")
	if err := os.WriteFile(p, comp, 0o644); err != nil {
		t.Fatal(err)
	}
	out, err := exec.Command("wasmtime", "run",
		"-W", "component-model-async,component-model-async-stackful",
		"--invoke", "run()", p).CombinedOutput()
	if err != nil {
		t.Fatalf("wasmtime run (future export/import): %v\n%s", err, out)
	}
	if !bytes.Contains(out, []byte("42")) {
		t.Errorf("future export/import: got %q, want 42", bytes.TrimSpace(out))
	}
}
