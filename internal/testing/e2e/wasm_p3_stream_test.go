func TestWasmP3StreamRoundtrip(t *testing.T) {
	skipIfPreview2Missing(t)

	comp := component.BuildStreamRoundtripComponent(p3StreamRoundtripCore, p3PendMemCore, component.CValtypeU8, component.CValtypeU32)
	dir := t.TempDir()
	p := filepath.Join(dir, "stream.wasm")
	if err := os.WriteFile(p, comp, 0o644); err != nil {
		t.Fatal(err)
	}
	out, err := exec.Command("wasmtime", "run",
		"-W", "component-model-async,component-model-async-stackful",
		"--invoke", "run()", p).CombinedOutput()
	if err != nil {
		t.Fatalf("wasmtime run (stream roundtrip): %v\n%s", err, out)
	}
	if !bytes.Contains(out, []byte("42")) {
		t.Errorf("stream roundtrip: got %q, want 42 (10+20+12)", bytes.TrimSpace(out))
	}
}
