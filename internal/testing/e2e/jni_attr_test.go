func jniBuild(t *testing.T, src string, args ...string) (string, string, error) {
	t.Helper()
	dir := t.TempDir()
	path := filepath.Join(dir, "lib.fern")
	if err := os.WriteFile(path, []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	java := filepath.Join(dir, "java")
	full := []string{"-target", "arm64-android", "-o", filepath.Join(dir, "libdemo.so")}
	// -jni-java takes effect only with -shared, and the CLI refuses it alone
	// before the build sees the program.
	if slices.Contains(args, "-shared") {
		full = append(full, "-jni-java", java)
	}
	full = append(full, args...)
	cmd := exec.Command(e2eharness.SelfHostCLI(t), append(full, path, e2eharness.SelfHostStdlibRoot(t))...)
	cmd.Env = e2eharness.ChildEnv()
	out, err := cmd.CombinedOutput()
	return java, string(out), err
}

// The Java class that -jni-java writes: a final class with a private
// constructor when each method is static, the library of -o, and a native
// declaration for each @jni function.
func TestJNIJavaClass(t *testing.T) {
	const src = `@jni("dev.fern.demo.Native", "static long add(long, int)")
pub function add(env: usize, cls: usize, a: i64, b: i32): i64 {
  return a + b as i64;
}

@jni("dev.fern.demo.Native", "static void reset()")
pub function reset(env: usize, cls: usize): void {
}

@jni("dev.fern.demo.View", "boolean visible(Object)")
pub function visible(env: usize, thiz: usize, other: usize): u8 {
  return 1;
}
`
	java, out, err := jniBuild(t, src, "-shared")
	if err != nil {
		t.Fatalf("build: %v\n%s", err, out)
	}
	for _, tc := range []struct{ file, want string }{
		{"Native.java", "// Generated by fern -jni-java from the @jni functions. Do not edit.\npackage dev.fern.demo;\n\nfinal class Native {\n    static {\n        System.loadLibrary(\"demo\");\n    }\n\n    // The state of the native library, for its callbacks.\n    public static long fern;\n\n    private Native() {}\n\n    static native long add(long a, int b);\n    static native void reset();\n}\n"},
		{"View.java", "// Generated by fern -jni-java from the @jni functions. Do not edit.\npackage dev.fern.demo;\n\nclass View {\n    static {\n        System.loadLibrary(\"demo\");\n    }\n\n    // The state of the native library, for its callbacks.\n    public static long fern;\n\n    native boolean visible(Object other);\n}\n"},
	} {
		got, err := os.ReadFile(filepath.Join(java, "dev", "fern", "demo", tc.file))
		if err != nil {
			t.Fatal(err)
		}
		if string(got) != tc.want {
			t.Errorf("%s =\n%s\nwant\n%s", tc.file, got, tc.want)
		}
	}
}

// A class head names the superclass and the interfaces: the Java class is
// public, and so are its native methods. The other method of the class can
// name the class alone.
func TestJNIJavaClassHead(t *testing.T) {
	const src = `@jni("dev.fern.demo.Tick extends java.lang.Thread implements java.lang.Runnable, java.io.Closeable", "void run()")
pub function run(env: usize, thiz: usize): void {
}

@jni("dev.fern.demo.Tick", "void close()")
pub function close(env: usize, thiz: usize): void {
}
`
	java, out, err := jniBuild(t, src, "-shared")
	if err != nil {
		t.Fatalf("build: %v\n%s", err, out)
	}
	got, err := os.ReadFile(filepath.Join(java, "dev", "fern", "demo", "Tick.java"))
	if err != nil {
		t.Fatal(err)
	}
	want := "// Generated by fern -jni-java from the @jni functions. Do not edit.\npackage dev.fern.demo;\n\npublic class Tick extends java.lang.Thread implements java.lang.Runnable, java.io.Closeable {\n    static {\n        System.loadLibrary(\"demo\");\n    }\n\n    // The state of the native library, for its callbacks.\n    public static long fern;\n\n    public native void run();\n    public native void close();\n}\n"
	if string(got) != want {
		t.Errorf("Tick.java =\n%s\nwant\n%s", got, want)
	}
	if javac, err := exec.LookPath("javac"); err == nil {
		if o, err := exec.Command(javac, "-d", t.TempDir(), filepath.Join(java, "dev", "fern", "demo", "Tick.java")).CombinedOutput(); err != nil {
			t.Errorf("javac: %v\n%s", err, o)
		}
	}
}

// A nested interface is "Outer$Inner" in the head, as in a DEX descriptor.
// The Java source writes it as "Outer.Inner".
func TestJNIJavaClassHeadNestedInterface(t *testing.T) {
	const src = `@jni("dev.fern.demo.Catch implements java.lang.Thread$UncaughtExceptionHandler", "void uncaughtException(java.lang.Thread, java.lang.Throwable)")
pub function caught(env: usize, thiz: usize, thread: usize, e: usize): void {
}
`
	java, out, err := jniBuild(t, src, "-shared")
	if err != nil {
		t.Fatalf("build: %v\n%s", err, out)
	}
	got, err := os.ReadFile(filepath.Join(java, "dev", "fern", "demo", "Catch.java"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(got), "public class Catch implements java.lang.Thread.UncaughtExceptionHandler {") {
		t.Errorf("Catch.java =\n%s\nwant the nested interface with a dot", got)
	}
	if javac, err := exec.LookPath("javac"); err == nil {
		if o, err := exec.Command(javac, "-d", t.TempDir(), filepath.Join(java, "dev", "fern", "demo", "Catch.java")).CombinedOutput(); err != nil {
			t.Errorf("javac: %v\n%s", err, o)
		}
	}
}

func TestJNIAttributeRefusals(t *testing.T) {
	cases := []struct {
		name, src string
		shared    bool
		want      string
	}{
		{"width", `@jni("a.B", "static int f(int)") pub function f(env: usize, cls: usize, n: i64): i32 { return 0; }`, true, "parameter n is i64, but the Java int needs i32"},
		{"two heads", "@jni(\"a.B implements java.lang.Runnable\", \"void run()\") pub function f(env: usize, o: usize): void { }\n@jni(\"a.B extends java.lang.Thread\", \"void go()\") pub function g(env: usize, o: usize): void { }", true, "class a.B is declared as implements java.lang.Runnable and as extends java.lang.Thread"},
		{"bad head", `@jni("a.B implements", "void run()") pub function f(env: usize, o: usize): void { }`, true, "is not \"name [extends class] [implements interface, ...]\""},
		{"nested own class", `@jni("a.B$C implements java.lang.Runnable", "void run()") pub function f(env: usize, o: usize): void { }`, true, "is not \"name [extends class] [implements interface, ...]\""},
		{"char", `@jni("a.B", "static int f(char)") pub function f(env: usize, cls: usize, c: u8): i32 { return 0; }`, true, "parameter c is u8, but the Java char needs i32"},
		{"result", `@jni("a.B", "static boolean f()") pub function f(env: usize, cls: usize): i32 { return 0; }`, true, "the result is i32, but the Java boolean needs u8"},
		{"arity", `@jni("a.B", "static int f(int, int)") pub function f(env: usize, cls: usize, n: i32): i32 { return 0; }`, true, "so it needs 4 parameters (it has 3)"},
		{"env", `@jni("a.B", "static int f()") pub function f(env: i32, cls: usize): i32 { return 0; }`, true, "the JNIEnv* and the jobject or jclass come first, each as usize"},
		{"declaration", `@jni("a.B", "static f") pub function f(env: usize, cls: usize): i32 { return 0; }`, true, "is not \"[static] result name(type, ...)\""},
		{"twice", `@jni("a.B", "static int f()") pub function f(env: usize, cls: usize): i32 { return 0; }
@jni("a.B", "static int f()") pub function g(env: usize, cls: usize): i32 { return 0; }`, true, "a.B.f is bound twice"},
		{"executable", `@jni("a.B", "static int f()") pub function f(env: usize, cls: usize): i32 { return 0; }
function main(): i32 { return 0; }`, false, "a JNI method needs -shared and a native target"},
		{"no methods", `pub function f(): i32 { return 0; }`, true, "-jni-java: the program has no @jni function"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			var args []string
			if tc.shared {
				args = append(args, "-shared")
				if tc.name == "no methods" {
					args = append(args, "-export", "f")
				}
			}
			_, out, err := jniBuild(t, tc.src+"\n", args...)
			if err == nil || !strings.Contains(out, tc.want) {
				t.Fatalf("want a refusal with %q, got %v:\n%s", tc.want, err, out)
			}
		})
	}
}

// jni.new_string in a real JVM: each Fern string reaches Java with the same
// characters, an embedded NUL and characters above U+FFFF included (#14032).
// A byte that does not start a whole UTF-8 character becomes U+FFFD.
func TestStdJNINewStringRoundTrip(t *testing.T) {
	host := e2eharness.HostSelfHostTarget()
	if runtime.GOOS != "linux" || host == "" {
		t.Skipf("-shared does not build for %s/%s", runtime.GOOS, runtime.GOARCH)
	}
	javac, err := exec.LookPath("javac")
	if err != nil {
		t.Skip("javac not on PATH")
	}
	java, err := exec.LookPath("java")
	if err != nil {
		t.Skip("java not on PATH")
	}
	const src = `import "std/jni";

function sample_text(k: i32): string {
  let samples: u8[][] = [
    [],
    [65 as u8, 0 as u8, 66 as u8],
    [104 as u8, 195 as u8, 169 as u8, 226 as u8, 130 as u8, 172 as u8],
    [240 as u8, 159 as u8, 152 as u8, 128 as u8],
    [244 as u8, 143 as u8, 191 as u8, 191 as u8],
    [255 as u8, 65 as u8, 226 as u8, 130 as u8],
  ];
  return unsafe { string_from_bytes_unchecked(samples[k]) };
}

@jni("dev.fern.strtest.Strings", "static String sample(int)")
pub function sample(env: usize, cls: usize, k: i32): usize {
  return jni.new_string(env, sample_text(k));
}
`
	dir := t.TempDir()
	path := filepath.Join(dir, "lib.fern")
	if err := os.WriteFile(path, []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	javaDir := filepath.Join(dir, "java")
	so := filepath.Join(dir, "libstrtest.so")
	cmd := exec.Command(e2eharness.SelfHostCLI(t), "-target", host, "-shared", "-jni-java", javaDir, "-o", so, path, e2eharness.SelfHostStdlibRoot(t))
	cmd.Env = e2eharness.ChildEnv()
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("build: %v\n%s", err, out)
	}
	check := `package dev.fern.strtest;

public class Check {
    public static void main(String[] args) {
        String[] want = {"", "A\u0000B", "hé€", "😀", "􏿿", "�A��"};
        for (int k = 0; k < want.length; k++) {
            String got = Strings.sample(k);
            if (!got.equals(want[k])) {
                StringBuilder units = new StringBuilder();
                for (char c : got.toCharArray()) units.append(Integer.toHexString(c)).append(' ');
                System.out.println("sample " + k + ": got units " + units);
                System.exit(1);
            }
        }
        System.out.println("ok");
    }
}
`
	checkPath := filepath.Join(javaDir, "dev", "fern", "strtest", "Check.java")
	if err := os.WriteFile(checkPath, []byte(check), 0o644); err != nil {
		t.Fatal(err)
	}
	classes := filepath.Join(dir, "classes")
	if out, err := exec.Command(javac, "-encoding", "UTF-8", "-d", classes, filepath.Join(javaDir, "dev", "fern", "strtest", "Strings.java"), checkPath).CombinedOutput(); err != nil {
		t.Fatalf("javac: %v\n%s", err, out)
	}
	out, err := exec.Command(java, "-Djava.library.path="+dir, "-cp", classes, "dev.fern.strtest.Check").CombinedOutput()
	if err != nil || !strings.Contains(string(out), "ok") {
		t.Fatalf("round trip: %v\n%s", err, out)
	}
}

// A Java byte, short or char is an i32 in Fern (#14268). The wrapper extends
// each argument and each result from its Java width, so the Fern function
// sees the Java value and Java sees the Fern result wrapped to its type.
func TestJNINarrowTypesRoundTrip(t *testing.T) {
	host := e2eharness.HostSelfHostTarget()
	if runtime.GOOS != "linux" || host == "" {
		t.Skipf("-shared does not build for %s/%s", runtime.GOOS, runtime.GOARCH)
	}
	javac, err := exec.LookPath("javac")
	if err != nil {
		t.Skip("javac not on PATH")
	}
	java, err := exec.LookPath("java")
	if err != nil {
		t.Skip("java not on PATH")
	}
	const src = `@jni("dev.fern.narrow.Narrow", "static int widen(byte, short, char)")
pub function widen(env: usize, cls: usize, b: i32, s: i32, c: i32): i32 {
  return b * 1000000 + s * 10 + c;
}

@jni("dev.fern.narrow.Narrow", "static byte negate(byte)")
pub function negate(env: usize, cls: usize, b: i32): i32 {
  return 0 - b;
}

@jni("dev.fern.narrow.Narrow", "static short add(short, short)")
pub function add(env: usize, cls: usize, a: i32, b: i32): i32 {
  return a + b;
}

@jni("dev.fern.narrow.Narrow", "static char next(char)")
pub function next(env: usize, cls: usize, c: i32): i32 {
  return c + 1;
}
`
	dir := t.TempDir()
	path := filepath.Join(dir, "lib.fern")
	if err := os.WriteFile(path, []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	javaDir := filepath.Join(dir, "java")
	so := filepath.Join(dir, "libnarrow.so")
	cmd := exec.Command(e2eharness.SelfHostCLI(t), "-target", host, "-shared", "-jni-java", javaDir, "-o", so, path, e2eharness.SelfHostStdlibRoot(t))
	cmd.Env = e2eharness.ChildEnv()
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("build: %v\n%s", err, out)
	}
	check := `package dev.fern.narrow;

public class Check {
    static void expect(String what, long got, long want) {
        if (got != want) {
            System.out.println(what + ": got " + got + ", want " + want);
            System.exit(1);
        }
    }

    public static void main(String[] args) {
        byte[] bs = {0, 1, -1, 127, -128};
        short[] ss = {0, 1, -1, 32767, -32768};
        char[] cs = {0, 1, 0x7fff, 0x8000, 0xffff};
        for (byte b : bs) {
            expect("negate(" + b + ")", Narrow.negate(b), (byte) -b);
            for (short s : ss) {
                expect("add(" + s + ", " + b + ")", Narrow.add(s, b), (short) (s + b));
                for (char c : cs) {
                    expect("widen(" + b + ", " + s + ", " + (int) c + ")", Narrow.widen(b, s, c), b * 1000000 + s * 10 + c);
                }
            }
        }
        for (short s : ss) {
            expect("add(" + s + ", " + s + ")", Narrow.add(s, s), (short) (s + s));
        }
        for (char c : cs) {
            expect("next(" + (int) c + ")", Narrow.next(c), (char) (c + 1));
        }
        System.out.println("ok");
    }
}
`
	checkPath := filepath.Join(javaDir, "dev", "fern", "narrow", "Check.java")
	if err := os.WriteFile(checkPath, []byte(check), 0o644); err != nil {
		t.Fatal(err)
	}
	classes := filepath.Join(dir, "classes")
	if out, err := exec.Command(javac, "-d", classes, filepath.Join(javaDir, "dev", "fern", "narrow", "Narrow.java"), checkPath).CombinedOutput(); err != nil {
		t.Fatalf("javac: %v\n%s", err, out)
	}
	out, err := exec.Command(java, "-Djava.library.path="+dir, "-cp", classes, "dev.fern.narrow.Check").CombinedOutput()
	if err != nil || !strings.Contains(string(out), "ok") {
		t.Fatalf("round trip: %v\n%s", err, out)
	}
}
