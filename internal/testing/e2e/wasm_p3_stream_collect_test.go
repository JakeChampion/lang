func TestWasmP3StreamCollect(t *testing.T) {
	skipIfPreview2Missing(t)

	comp := component.BuildStreamCollectComponent(
		p3StreamEOFProducerCore, p3StreamCollectConsumerCore, p3PendMemCore,
		p3Stream2SlotTramp, p3Stream2SlotFixup,
		component.CValtypeU8, component.CValtypeU32,
	)
	dir := t.TempDir()
	p := filepath.Join(dir, "streamcollect.wasm")
	if err := os.WriteFile(p, comp, 0o644); err != nil {
		t.Fatal(err)
	}
	out, err := exec.Command("wasmtime", "run",
		"-W", "component-model-async,component-model-async-stackful",
		"--invoke", "run()", p).CombinedOutput()
	if err != nil {
		t.Fatalf("wasmtime run (stream collect): %v\n%s", err, out)
	}
	if !bytes.Contains(out, []byte("42")) {
		t.Errorf("stream collect: got %q, want 42 (10+20+12)", bytes.TrimSpace(out))
	}
}
