package e2ecompiler

import (
	"crypto/md5"
	"encoding/hex"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"testing"
)

func TestImportFreeModulesDoNotDrift(t *testing.T) {
	paths, err := filepath.Glob(langSrcAbs(t, filepath.Join("compiler", "*.fern")))
	inDrivers, _ := filepath.Glob(langSrcAbs(t, filepath.Join("compiler", "drivers", "*.fern")))
	paths = append(paths, inDrivers...)
	if err != nil {
		t.Fatalf("glob self-host sources: %v", err)
	}
	if len(paths) == 0 {
		t.Fatal("no self-host sources found")
	}

	type copyOf struct {
		module string
		hash   string
		lines  int
	}
	bodies := map[string][]copyOf{}
	var free []string
	// The wide reference rows and wide range checks have independent contracts.
	independent := map[string]bool{
		"ssalargepushwidecases.rows":   true,
		"ssalargepushwideranges.valid": true,
	}

	for _, p := range paths {
		src, err := os.ReadFile(p)
		if err != nil {
			t.Fatalf("read %s: %v", p, err)
		}
		lines := strings.Split(string(src), "\n")
		mod := strings.TrimSuffix(filepath.Base(p), ".fern")
		if !hasImport(lines) {
			free = append(free, mod)
		} else if mod != sharedCopies {
			continue
		}
		// Generated runtime catalogs contain different data, not copied implementations.
		if strings.HasPrefix(string(src), "// Code generated by scripts/gen-runtime-bundle.py.") {
			continue
		}
		for name, body := range topLevelFuncs(lines) {
			if independent[mod+"."+name] {
				name = mod + "." + name
			}
			code := normaliseCode(body)
			sum := md5.Sum([]byte(strings.Join(code, "\n")))
			bodies[name] = append(bodies[name], copyOf{mod, hex.EncodeToString(sum[:]), len(code)})
		}
	}

	sort.Strings(free)
	wantFree := []string{
		"aborts", "aesref", "builtins", "capvocab", "docprintable", "rtbundle", "rtbytecopy", "rttemplates", "rtwasm",
		"sourcepos", "ssadecrementcount", "ssafixed", "ssalargepushwidecases", "ssalargepushwideranges", "stdlib_methods", "typeinfo", "wit_fern_world", "wit_proxy_world",
	}
	if strings.Join(free, ",") != strings.Join(wantFree, ",") {
		t.Errorf("the import-free module set changed.\n  got:  %v\n  want: %v\n"+
			"    A test that concatenates one of these modules with a driver main() breaks when the\n"+
			"    module gains an import. Load such a module with assemblerSource or copySelfHostDriver\n"+
			"    instead, then update wantFree.", free, wantFree)
	}

	allowed := map[string]string{
		"main": "every driver entry point is different by definition.",
	}

	var names []string
	for n := range bodies {
		names = append(names, n)
	}
	sort.Strings(names)

	for _, name := range names {
		copies := bodies[name]
		if len(copies) < 2 {
			continue
		}
		distinct := map[string]bool{}
		for _, c := range copies {
			distinct[c.hash] = true
		}
		if len(distinct) == 1 {
			continue
		}
		if why, ok := allowed[name]; ok {
			t.Logf("%s: %d copies differ, allowed — %s", name, len(copies), why)
			continue
		}
		var detail []string
		for _, c := range copies {
			detail = append(detail, fmt.Sprintf("        %-18s %s  %d code lines", c.module, c.hash[:12], c.lines))
		}
		sort.Strings(detail)
		t.Errorf("%s has %d copies across import-free modules and they have DIVERGED (%d distinct bodies):\n%s\n"+
			"    A copy in an import-free module is kept in step BY HAND. A fix applied to one copy and\n"+
			"    not the others is silent: every driver still builds and the fixpoint still converges.\n"+
			"    Delete the copy and import the module that owns it. If the module must stay import-free,\n"+
			"    apply the change to every copy. If the copies must differ, add the name to `allowed`.",
			name, len(copies), len(distinct), strings.Join(detail, "\n"))
	}
}

const sharedCopies = "util"

var (
	importRe = regexp.MustCompile(`^import\s`)
	funcRe   = regexp.MustCompile(`^(?:pub )?function (\w+)`)
	lineCmt  = regexp.MustCompile(`\s*//.*$`)
)

func hasImport(lines []string) bool {
	for _, l := range lines {
		if importRe.MatchString(l) {
			return true
		}
	}
	return false
}

func topLevelFuncs(lines []string) map[string][]string {
	out := map[string][]string{}
	for i := 0; i < len(lines); i++ {
		m := funcRe.FindStringSubmatch(lines[i])
		if m == nil {
			continue
		}
		j := i
		for j < len(lines) && lines[j] != "}" {
			j++
		}
		if j < len(lines) {
			out[m[1]] = append([]string{}, lines[i:j+1]...)
		}
		i = j
	}
	return out
}

func normaliseCode(body []string) []string {
	var out []string
	for i, l := range body {
		if i == 0 {
			l = strings.Replace(l, "pub ", "", 1)
		}
		l = strings.TrimRight(lineCmt.ReplaceAllString(l, ""), " \t")
		if strings.TrimSpace(l) == "" {
			continue
		}
		out = append(out, l)
	}
	return out
}
