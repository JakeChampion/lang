// The corpus of the sed port. GNU sed 4.9 is the oracle: each case runs on
// both sides and the streams, the status and the tree must match. The cases
// come from the documented behaviour of GNU sed and from runs of the GNU
// binary. No case is copied from the GNU test suite.

func init() {
	registerCorpus("sed", sedCases)
}

func sedCases(t *testing.T) []invocation {
	var cases []invocation
	cases = append(cases, sedScriptCases()...)
	cases = append(cases, sedOptionCases()...)
	cases = append(cases, sedBigCases()...)
	cases = append(cases, sedCaptureCases()...)
	return cases
}

// sedCaptureCases: the groups of a match where more than one division of the
// match is possible.
func sedCaptureCases() []invocation {
	var cases []invocation
	for _, script := range []string{
		`s/\(a\|ab\)\(c\|bcd\)\(d*\)/[\1|\2|\3]/`, `s/\(a*\)\(ab\)*b/[\1|\2]/`, `s/\(a*\)\(a*\)/[\1|\2]/`,
		`s/\(x*\)\(\w*\)/[\1|\2]/g`, `s/\(.*\)\(b\)/[\1|\2]/`, `s/\(a\)\|\(b\)/[\1|\2]/g`,
		`s/\(a*\)*/[\1]/g`, `s/\(ab\|a\)\(bc\|c\)*/[\1|\2]/`,
	} {
		cases = append(cases, invocation{name: "groups " + script, args: []string{script}, stdin: "abcdab\nabcabc\naaa\n"})
	}
	return cases
}

// sedTree holds the input files, the script files, the directories and
// two links of the cases that read files or edit them in place.
func sedTree(t *testing.T, dir string) {
	t.Helper()
	files := map[string]string{
		"f3": "1\n2\n3\n", "f4": "1\n2\n3\n4\n", "na": "a", "nonl": "x", "empty": "",
		"s1.sed": "p\n{p\n", "s2.sed": "p\ns/a/b\np\n", "s3.sed": "s//x/\n", "s4.sed": "#n\np\n",
		"s5.sed": "a\\\nfoo\\\n", "s6.sed": "p\nk\n", "s7.sed": "p;k", "sub/f": "x\ny\n",
	}
	for name, content := range files {
		if err := os.MkdirAll(filepath.Dir(filepath.Join(dir, name)), 0o755); err != nil {
			t.Fatal(err)
		}
		writeFile(t, dir, name, content)
	}
	for _, sub := range []string{"d", "old_sub", "bak/sub"} {
		if err := os.MkdirAll(filepath.Join(dir, sub), 0o755); err != nil {
			t.Fatal(err)
		}
	}
	for link, target := range map[string]string{"link": "f3", "dlink": "sub/f"} {
		if err := os.Symlink(target, filepath.Join(dir, link)); err != nil {
			t.Fatal(err)
		}
	}
}

// sedFullTree adds the link "full" to /dev/full, a w file that cannot be
// written.
func sedFullTree(t *testing.T, dir string) {
	t.Helper()
	if runtime.GOOS != "linux" {
		t.Skip("/dev/full is a Linux device")
	}
	sedTree(t, dir)
	if err := os.Symlink("/dev/full", filepath.Join(dir, "full")); err != nil {
		t.Fatal(err)
	}
}

// sedBigTree holds files larger than the read buffer of the port: many
// lines, a line of 200000 bytes, and lines that end at the buffer edge.
func sedBigTree(t *testing.T, dir string) {
	t.Helper()
	var big strings.Builder
	for i := 1; i <= 60000; i++ {
		big.WriteString("line ")
		big.WriteString(strconv.Itoa(i))
		big.WriteString(" foo bar\n")
	}
	writeFile(t, dir, "big", big.String())
	writeFile(t, dir, "long", strings.Repeat("x", 200000)+"\nshort\n"+strings.Repeat("y", 70000))
	writeFile(t, dir, "exact", strings.Repeat("a", 65535)+"\n"+strings.Repeat("b", 65535)+"\n")
}

// GNU sed writes its whole usage after a bad option. The usage is the text
// of each program, as --help is, so the comparison stops at it.
// darwinSedGetopt is why the Darwin reference is wrong for an option error.
const darwinSedGetopt = "the Darwin build of GNU sed words its getopt errors in an older form, with a backtick and no quotes round an option letter"

func sedUsageMask(s string) string {
	if i := strings.Index(s, "Usage:"); i >= 0 {
		return s[:i] + "<usage>"
	}
	return s
}

