// TestWasmP3AsyncPendingAwait is the WASI Preview-3 PENDING-await payoff,
// assembled through the Go composer (component.BuildPendingAwaitComponent): a
// consumer awaits a genuinely-deferring async import (the provider `thread.yield`s
// before returning, so the `canon lower async` returns STARTED), drives the
// waitable-set await loop (new → join → wait → subtask.drop), reads the result,
// and re-returns it from its own async export `run`. Runs under wasmtime's async
// features → 42. This converts the proven pending-await spike into a permanent,
// CI-tested artifact and exercises the full waitable canon-builtin set
// (waitable-set.new/wait/drop, waitable.join, subtask.drop, thread.yield) end to
// end — the last async ABI capability. See docs/WASI-PREVIEW3-ASYNC-PLAN.md.
func TestWasmP3AsyncPendingAwait(t *testing.T) {
	skipIfPreview2Missing(t) // ensures wasmtime on PATH

	comp := component.BuildPendingAwaitComponent(p3PendProviderCore, p3PendConsumerCore, p3PendMemCore, component.CValtypeU32)
	dir := t.TempDir()
	p := filepath.Join(dir, "pending.wasm")
	if err := os.WriteFile(p, comp, 0o644); err != nil {
		t.Fatal(err)
	}
	out, err := exec.Command("wasmtime", "run",
		"-W", "component-model-async,component-model-async-stackful",
		"--invoke", "run()", p).CombinedOutput()
	if err != nil {
		t.Fatalf("wasmtime run (pending await): %v\n%s", err, out)
	}
	if !bytes.Contains(out, []byte("42")) {
		t.Errorf("pending await: got %q, want 42", bytes.TrimSpace(out))
	}
}
