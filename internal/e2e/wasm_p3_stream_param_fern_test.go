// TestWasmP3StreamParamFromFern is the colorless `stream[T]` PARAMETER payoff from
// REAL Fern source — the produce mirror of TestWasmP3StreamImportFromFern:
//
//	@import("test:dep/d","sink") async function sink(s: stream[u8]): i32;
//	async function run(): i32 {
//	    var xs: u8[] = [10 as u8, 20 as u8, 12 as u8];
//	    return sink(xs);                       // colorless: streams xs out to the host
//	}
//
// The checker rewrites the `stream[u8]` param to `u8[]` (the eager array the call
// site passes) and stashes the element type; the wasmbin produce-wrapper creates a
// stream, passes the readable end to the host, and write-streams the array's
// elements out over the wire (write-await), drops-writable, and awaits the host.
// The WASMBIN-GENERATED consumer (which exports its own memory) is composed against
// the bundled host sink via BuildAsyncStreamParamImportComponent — the dep-lower,
// waitable-set.wait and stream.write each trampolined over the consumer's exported
// memory. Running `run()` under wasmtime's async features returns 42 (10+20+12) —
// a `u8[]` flows colorlessly OUT of Fern source as a `stream[u8]` the host
// collect-reads, driving the slice-P2a produce-wrapper end to end.
func TestWasmP3StreamParamFromFern(t *testing.T) {
	skipIfPreview2Missing(t) // ensures wasmtime on PATH

	src := `@import("test:dep/d", "sink") async function sink(s: stream[u8]): i32;
async function run(): i32 {
	var xs: u8[] = [10 as u8, 20 as u8, 12 as u8];
	return sink(xs);
}
function main(): i32 { return 0; }
`
	dir := t.TempDir()
	srcPath := filepath.Join(dir, "main.fern")
	if err := os.WriteFile(srcPath, []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	prog, _, err := modload.Load(srcPath)
	if err != nil {
		t.Fatalf("modload: %v", err)
	}
	if err := constfold.Fold(prog, nil); err != nil {
		t.Fatalf("constfold: %v", err)
	}
	info, err := checker.Check(prog)
	if err != nil {
		t.Fatalf("check: %v", err)
	}
	if err := monomorph.Run(prog, info); err != nil {
		t.Fatalf("monomorph: %v", err)
	}
	core, err := wasmbin.BuildWithOptions(prog, info, wasmbin.BuildOptions{
		Preview2WASI:    true,
		AsyncExportName: "__async_run",
		AsyncSourceFunc: "run",
	})
	if err != nil {
		t.Fatalf("wasmbin.Build: %v", err)
	}

	comp := component.BuildAsyncStreamParamImportComponent(
		core, p3StreamSinkProviderCore, p3Stream2SlotTramp, p3Stream2SlotFixup,
		"test:dep/d", "sink", "__async_run", "run",
		component.CValtypeU8, component.CValtypeU32,
	)

	p := filepath.Join(dir, "fern_stream_param.wasm")
	if err := os.WriteFile(p, comp, 0o644); err != nil {
		t.Fatal(err)
	}
	out, err := exec.Command("wasmtime", "run",
		"-W", "component-model-async,component-model-async-stackful",
		"--invoke", "run()", p).CombinedOutput()
	if err != nil {
		t.Fatalf("wasmtime run (stream param from Fern): %v\n%s", err, out)
	}
	if !bytes.Contains(out, []byte("42")) {
		t.Errorf("Fern stream[u8] param: got %q, want 42 (10+20+12)", bytes.TrimSpace(out))
	}
}
