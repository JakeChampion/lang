// TestWasmP3StreamF64ForIn exercises LAZY `for x in body()` over an f64 stream —
// the 8-byte-element coverage that, together with the u8 (1-byte) and i32
// (4-byte) lazy e2es, pins the general-T cursor path across every element width
// AND the float read/load. Real Fern:
//
//	@import("test:dep/d","prod") async function body(): stream[f64];
//	async function run(): i32 {
//	    var sum: f64 = 0.0;
//	    for x in body() { sum = sum + x; }   // x: f64, pulled one at a time
//	    return sum as i32;
//	}
//
// The checker desugars to the cursor loop with `__stream_elem_f64` (an 8-byte
// f64.load of the buffered element); `__stream_next` is element-agnostic. Composed
// against the f64 EOF producer (writes [10.0,20.0,12.0], write-awaits, drops) → 42.
// See docs/STREAM-TYPE-SURFACE.md.
func TestWasmP3StreamF64ForIn(t *testing.T) {
	skipIfPreview2Missing(t)

	src := `@import("test:dep/d", "prod") async function body(): stream[f64];
async function run(): i32 {
	var sum: f64 = 0.0;
	for x in body() {
		sum = sum + x;
	}
	return sum as i32;
}
function main(): i32 { return 0; }
`
	dir := t.TempDir()
	srcPath := filepath.Join(dir, "main.fern")
	if err := os.WriteFile(srcPath, []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	prog, _, err := modload.Load(srcPath)
	if err != nil {
		t.Fatalf("modload: %v", err)
	}
	if err := constfold.Fold(prog, nil); err != nil {
		t.Fatalf("constfold: %v", err)
	}
	info, err := checker.Check(prog)
	if err != nil {
		t.Fatalf("check: %v", err)
	}
	if err := monomorph.Run(prog, info); err != nil {
		t.Fatalf("monomorph: %v", err)
	}
	core, err := wasmbin.BuildWithOptions(prog, info, wasmbin.BuildOptions{
		Preview2WASI:    true,
		AsyncExportName: "__async_run",
		AsyncSourceFunc: "run",
	})
	if err != nil {
		t.Fatalf("wasmbin.Build: %v", err)
	}

	comp := component.BuildAsyncStreamImportComponent(
		core, p3StreamF64EOFProducerCore, p3Stream2SlotTramp, p3Stream2SlotFixup,
		"test:dep/d", "prod", "__async_run", "run",
		component.CValtypeF64, component.CValtypeU32,
	)

	p := filepath.Join(dir, "fern_stream_f64_forin.wasm")
	if err := os.WriteFile(p, comp, 0o644); err != nil {
		t.Fatal(err)
	}
	out, err := exec.Command("wasmtime", "run",
		"-W", "component-model-async,component-model-async-stackful",
		"--invoke", "run()", p).CombinedOutput()
	if err != nil {
		t.Fatalf("wasmtime run (lazy for-in over stream[f64]): %v\n%s", err, out)
	}
	if !bytes.Contains(out, []byte("42")) {
		t.Errorf("lazy for-in over stream[f64]: got %q, want 42 (10+20+12)", bytes.TrimSpace(out))
	}
}
