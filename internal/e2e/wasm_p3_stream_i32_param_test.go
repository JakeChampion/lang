// TestWasmP3StreamI32ParamFromFern is the produce-side (stride-4) mirror of
// TestWasmP3StreamI32ResultFromFern, completing the 2×2 matrix (result/param ×
// u8/i32). Real Fern:
//
//	@import("test:dep/d","sink") async function sink(s: stream[i32]): i32;
//	async function run(): i32 { var xs: i32[] = [10,20,12]; return sink(xs); }
//
// The produce-wrapper streams the eager i32[] out (write ptr advances by
// wrote*stride with stride 4), and the host sink collect-reads + sums the i32
// elements → 42. Confirms the stride-aware write path on stream<s32>.
func TestWasmP3StreamI32ParamFromFern(t *testing.T) {
	skipIfPreview2Missing(t)

	src := `@import("test:dep/d", "sink") async function sink(s: stream[i32]): i32;
async function run(): i32 {
	var xs: i32[] = [10, 20, 12];
	return sink(xs);
}
function main(): i32 { return 0; }
`
	dir := t.TempDir()
	srcPath := filepath.Join(dir, "main.fern")
	if err := os.WriteFile(srcPath, []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	prog, _, err := modload.Load(srcPath)
	if err != nil {
		t.Fatalf("modload: %v", err)
	}
	if err := constfold.Fold(prog, nil); err != nil {
		t.Fatalf("constfold: %v", err)
	}
	info, err := checker.Check(prog)
	if err != nil {
		t.Fatalf("check: %v", err)
	}
	if err := monomorph.Run(prog, info); err != nil {
		t.Fatalf("monomorph: %v", err)
	}
	core, err := wasmbin.BuildWithOptions(prog, info, wasmbin.BuildOptions{
		Preview2WASI:    true,
		AsyncExportName: "__async_run",
		AsyncSourceFunc: "run",
	})
	if err != nil {
		t.Fatalf("wasmbin.Build: %v", err)
	}

	comp := component.BuildAsyncStreamParamImportComponent(
		core, p3StreamI32SinkProviderCore, p3Stream2SlotTramp, p3Stream2SlotFixup,
		"test:dep/d", "sink", "__async_run", "run",
		component.CValtypeS32, component.CValtypeU32,
	)

	p := filepath.Join(dir, "fern_stream_i32_param.wasm")
	if err := os.WriteFile(p, comp, 0o644); err != nil {
		t.Fatal(err)
	}
	out, err := exec.Command("wasmtime", "run",
		"-W", "component-model-async,component-model-async-stackful",
		"--invoke", "run()", p).CombinedOutput()
	if err != nil {
		t.Fatalf("wasmtime run (stream[i32] param from Fern): %v\n%s", err, out)
	}
	if !bytes.Contains(out, []byte("42")) {
		t.Errorf("Fern stream[i32] param: got %q, want 42 (10+20+12)", bytes.TrimSpace(out))
	}
}
