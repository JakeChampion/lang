func f64InverseTrigCases() []f64Case {
	cs := make([]f64Case, len(f64InverseTrigTable))
	for i, c := range f64InverseTrigTable {
		cs[i] = f64Case{call: c.call, want: math.Float64frombits(c.want)}
	}
	return cs
}

func f64InverseTrigProg(cs []f64Case) string {
	var b strings.Builder
	b.WriteString("import \"std/i64\";\nimport \"std/float\";\n")
	b.WriteString("function emit(v: f64): i32 { print(f64_bits(v).to_string()); return 0; }\n")
	b.WriteString("function main(): i32 {\n")
	for _, c := range cs {
		fmt.Fprintf(&b, "    emit(%s);\n", c.call)
	}
	b.WriteString("    return 0;\n}\n")
	return b.String()
}

