var updateStdlibMethods = flag.Bool("update", false, "rewrite the generated stdlib method index files")

const (
	stdlibMethodsGo   = "stdlib_methods.go"
	stdlibMethodsFern = "../../../compiler/stdlib_methods.fern"
)

var indexedReceivers = map[string]bool{
	"string": true, "i32": true, "u8": true, "i64": true, "u32": true, "u64": true,
	"usize": true, "f32": true, "f64": true, "boolean": true, "char": true,
	"Option": true, "Result": true,
}

func buildStdlibMethodIndex(t *testing.T) (map[string]map[string]string, map[string]map[string]string) {
	t.Helper()
	index := map[string]map[string]string{}
	narrow := map[string]map[string]string{}
	walk := func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() || !strings.HasSuffix(path, ".fern") {
			return nil
		}
		mod := strings.TrimSuffix(path, ".fern")
		src, ok := stdlib.Resolve(mod)
		if !ok {
			return fmt.Errorf("no source for %s", mod)
		}
		prog, err := parser.Parse(src)
		if err != nil {
			return fmt.Errorf("parse %s: %w", mod, err)
		}
		inImpl := map[*ast.FuncDecl]bool{}
		for _, im := range prog.Impls {
			for _, m := range im.Methods {
				inImpl[m] = true
			}
		}
		for _, f := range prog.Funcs {
			if f.Receiver == nil || !(f.Public || inImpl[f]) {
				continue
			}
			recv, ok := ast.ReceiverTypeName(f.Receiver.Type)
			if !ok || !indexedReceivers[recv] {
				continue
			}
			if index[recv] == nil {
				index[recv] = map[string]string{}
			}
			if prev, dup := index[recv][f.Name]; dup && prev != mod {
				return fmt.Errorf("%s.%s is declared in both %s and %s, so E043 cannot name one module", recv, f.Name, prev, mod)
			}
			index[recv][f.Name] = mod
			if !generalStdlibReceiver(f, prog) {
				if narrow[recv] == nil {
					narrow[recv] = map[string]string{}
				}
				narrow[recv][f.Name] = f.Receiver.Type.String()
			}
		}
		return nil
	}
	for _, root := range []string{"std", "core"} {
		if err := fs.WalkDir(stdlib.FS(), root, walk); err != nil {
			t.Fatal(err)
		}
	}
	return index, narrow
}

func generalStdlibReceiver(f *ast.FuncDecl, prog *ast.Program) bool {
	c := stdlibReceiverContext(prog)
	var params []string
	c.collectFreeTypeVars(f.Receiver.Type, &params, map[string]bool{}, "")
	var args []ast.Type
	switch r := f.Receiver.Type.(type) {
	case ast.EnumType:
		args = r.Args
	case ast.StructType:
		args = r.Args
	}
	seen := map[string]bool{}
	for _, a := range args {
		name := a.String()
		if !slices.Contains(append(params, f.TypeParams...), name) || seen[name] {
			return false
		}
		seen[name] = true
	}
	return true
}

func stdlibReceiverContext(prog *ast.Program) *checker {
	c := &checker{info: &Info{Structs: map[string]*ast.StructDecl{}, Enums: map[string]*ast.EnumDecl{}}}
	for _, d := range append(builtinStructDecls(), prog.Structs...) {
		c.info.Structs[d.Name] = d
	}
	for _, d := range append(builtinEnumDecls(), prog.Enums...) {
		c.info.Enums[d.Name] = d
	}
	return c
}

func stdlibReceiverPattern(module, spelling string) (ast.Type, []string) {
	src, ok := stdlib.Resolve(module)
	if !ok {
		panic("missing stdlib module " + module)
	}
	prog, err := parser.Parse(src)
	if err != nil {
		panic(err)
	}
	for _, f := range prog.Funcs {
		if f.Receiver == nil || f.Receiver.Type.String() != spelling {
			continue
		}
		c := stdlibReceiverContext(prog)
		var params []string
		c.collectFreeTypeVars(f.Receiver.Type, &params, map[string]bool{}, "")
		for _, name := range f.TypeParams {
			if typeMentionsParam(f.Receiver.Type, name) && !slices.Contains(params, name) {
				params = append(params, name)
			}
		}
		set := map[string]bool{}
		for _, name := range params {
			set[name] = true
		}
		pattern := f.Receiver.Type
		c.resolveType(&pattern, set, ast.Position{})
		if len(c.errors) != 0 {
			panic(c.errors[0])
		}
		return pattern, params
	}
	panic("missing receiver " + spelling + " in " + module)
}

const generatedNote = "TestStdlibMethodIndex generates this file from the standard library sources.\n" +
	"Use `go test ./internal/check/checker -run TestStdlibMethodIndex -update` to regenerate it."

func stdlibMethodsGoSource(index, narrow map[string]map[string]string) string {
	var b strings.Builder
	b.WriteString("// Code generated by TestStdlibMethodIndex; DO NOT EDIT.\n\n")
	b.WriteString("package checker\n\n")
	b.WriteString("import \"github.com/jakechampion/lang/internal/syntax/ast\"\n\n")
	b.WriteString("// " + strings.ReplaceAll(generatedNote, "\n", "\n// ") + "\n//\n")
	b.WriteString("// stdlibMethodIndex maps receiver and method names to their standard library modules.\n")
	b.WriteString("var stdlibMethodIndex = map[string]map[string]string{\n")
	for _, recv := range sortedKeys(index) {
		fmt.Fprintf(&b, "\t%q: {\n", recv)
		for _, m := range sortedKeys(index[recv]) {
			fmt.Fprintf(&b, "\t\t%q: %q,\n", m, index[recv][m])
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	b.WriteString("\nvar stdlibMethodReceivers = map[string]map[string]string{\n")
	for _, recv := range sortedKeys(narrow) {
		fmt.Fprintf(&b, "\t%q: {\n", recv)
		for _, method := range sortedKeys(narrow[recv]) {
			fmt.Fprintf(&b, "\t\t%q: %q,\n", method, narrow[recv][method])
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	b.WriteString("\nvar stdlibMethodReceiverPatterns = map[string]ast.Type{\n")
	for _, recv := range sortedKeys(narrow) {
		for _, method := range sortedKeys(narrow[recv]) {
			pattern, _ := stdlibReceiverPattern(index[recv][method], narrow[recv][method])
			fmt.Fprintf(&b, "\t%q: %#v,\n", recv+"."+method, pattern)
		}
	}
	b.WriteString("}\n")
	out, err := format.Source([]byte(b.String()))
	if err != nil {
		panic(err)
	}
	return string(out)
}

func stdlibMethodsFernSource(index, narrow map[string]map[string]string) string {
	var recvs, methods, mods, receivers []string
	for _, recv := range sortedKeys(index) {
		for _, m := range sortedKeys(index[recv]) {
			recvs = append(recvs, recv)
			methods = append(methods, m)
			mods = append(mods, index[recv][m])
			receivers = append(receivers, narrow[recv][m])
		}
	}
	list := func(xs []string) string {
		quoted := make([]string, len(xs))
		for i, x := range xs {
			quoted[i] = fmt.Sprintf("%q", x)
		}
		return "[" + strings.Join(quoted, ", ") + "]"
	}
	var b strings.Builder
	b.WriteString("// This module maps receiver and method names to their standard library modules.\n//\n")
	b.WriteString("// " + strings.ReplaceAll(generatedNote, "\n", "\n// ") + "\n\n")
	b.WriteString("const RECEIVERS: string[] = " + list(recvs) + ";\n\n")
	b.WriteString("const METHODS: string[] = " + list(methods) + ";\n\n")
	b.WriteString("const MODULES: string[] = " + list(mods) + ";\n\n")
	b.WriteString("const DECLARED_RECEIVERS: string[] = " + list(receivers) + ";\n\n")
	b.WriteString("// receiver_params returns the declaration's type parameters.\n")
	b.WriteString("pub function receiver_params(receiver: string, method: string): string[] {\n")
	for _, recv := range sortedKeys(narrow) {
		for _, method := range sortedKeys(narrow[recv]) {
			_, params := stdlibReceiverPattern(index[recv][method], narrow[recv][method])
			if len(params) > 0 {
				fmt.Fprintf(&b, "  if (receiver == %q && method == %q) {\n    return %s;\n  }\n", recv, method, list(params))
			}
		}
	}
	b.WriteString("  return [];\n}\n\n")
	b.WriteString(`pub function module_of(receiver: string, method: string): string {
  let i: i32 = 0;
  while (i < METHODS.len()) {
    if (METHODS[i] == method && RECEIVERS[i] == receiver) {
      return MODULES[i];
    }
    i = i + 1;
  }
  return "";
}

pub function receiver_of(receiver: string, method: string): string {
  let i: i32 = 0;
  while (i < METHODS.len()) {
    if (METHODS[i] == method && RECEIVERS[i] == receiver) {
      return DECLARED_RECEIVERS[i];
    }
    i = i + 1;
  }
  return "";
}

pub function methods_on(receiver: string): string[] {
  let out: string[] = [];
  let i: i32 = 0;
  while (i < METHODS.len()) {
    if (RECEIVERS[i] == receiver) {
      out = out.append(METHODS[i]);
    }
    i = i + 1;
  }
  return out;
}
`)
	return b.String()
}

func TestStdlibMethodIndex(t *testing.T) {
	index, narrow := buildStdlibMethodIndex(t)
	if len(index["string"]) < 100 || index["string"]["trim"] != "std/string" {
		t.Fatalf("the index is missing std/string's methods, so the extraction has gone stale: %d string methods", len(index["string"]))
	}
	for _, f := range []struct{ path, want string }{
		{stdlibMethodsGo, stdlibMethodsGoSource(index, narrow)},
		{stdlibMethodsFern, stdlibMethodsFernSource(index, narrow)},
	} {
		if *updateStdlibMethods {
			if err := os.WriteFile(f.path, []byte(f.want), 0o644); err != nil {
				t.Fatal(err)
			}
			continue
		}
		got, err := os.ReadFile(f.path)
		if err != nil {
			t.Fatal(err)
		}
		if string(got) != f.want {
			t.Errorf("%s does not match the stdlib sources; run `go test ./internal/check/checker -run TestStdlibMethodIndex -update`", f.path)
		}
	}
}
