package mvs

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/jakechampion/lang/internal/pkg/manifest"
)

const LockFileName = "fern.lock"

// Lock is a parsed fern.lock. IndexSerial is the serial of the index the
// lock was resolved from, "" when that index had none.
type Lock struct {
	IndexSerial string
	Packages    map[string]Selected
}

func WriteLock(dir, serial string, sel []Selected) error {
	sorted := append([]Selected(nil), sel...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Name < sorted[j].Name })
	var b strings.Builder
	b.WriteString("# generated by `fern -resolve`; do not edit by hand\n")
	if serial != "" {
		fmt.Fprintf(&b, "index_serial = %s\n", serial)
	}
	for _, s := range sorted {
		b.WriteString("\n[[package]]\n")
		fmt.Fprintf(&b, "name = %q\n", s.Name)
		fmt.Fprintf(&b, "version = %q\n", s.Version.String())
		if s.Source.Path != "" {
			fmt.Fprintf(&b, "path = %q\n", filepath.ToSlash(s.Source.Path))
		} else {
			fmt.Fprintf(&b, "url = %q\n", s.Source.URL)
			fmt.Fprintf(&b, "hash = %q\n", s.Source.Hash)
		}
	}
	return os.WriteFile(filepath.Join(dir, LockFileName), []byte(b.String()), 0o644)
}

// ReadLock returns nil when dir has no lock.
func ReadLock(dir string) (*Lock, error) {
	file := filepath.Join(dir, LockFileName)
	b, err := os.ReadFile(file)
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	lock := &Lock{Packages: map[string]Selected{}}
	out := lock.Packages
	var cur *Selected
	haveVersion := false
	flush := func() error {
		if cur == nil {
			return nil
		}
		if cur.Name == "" || !haveVersion {
			return fmt.Errorf("%s: incomplete [[package]] entry", file)
		}
		out[cur.Name] = *cur
		cur = nil
		return nil
	}
	for ln, raw := range strings.Split(string(b), "\n") {
		line := manifest.Line(raw)
		if line == "" {
			continue
		}
		if line == "[[package]]" {
			if err := flush(); err != nil {
				return nil, err
			}
			cur = &Selected{}
			haveVersion = false
			continue
		}
		if cur == nil {
			if err := lock.topLevel(line); err != nil {
				return nil, fmt.Errorf("%s line %d: %w", file, ln+1, err)
			}
			continue
		}
		eq := strings.Index(line, "=")
		if eq < 0 {
			return nil, fmt.Errorf("%s line %d: expected `key = value`", file, ln+1)
		}
		k := strings.TrimSpace(line[:eq])
		v, err := unquote(strings.TrimSpace(line[eq+1:]))
		if err != nil {
			return nil, fmt.Errorf("%s line %d: %s: %w", file, ln+1, k, err)
		}
		switch k {
		case "name":
			cur.Name = v
		case "version":
			ver, err := ParseVersion(v)
			if err != nil {
				return nil, fmt.Errorf("%s line %d: %w", file, ln+1, err)
			}
			cur.Version = ver
			haveVersion = true
		case "path":
			cur.Source.Path = filepath.FromSlash(v)
		case "url":
			cur.Source.URL = v
		case "hash":
			if !validHashShape(v) {
				return nil, fmt.Errorf("%s line %d: hash must be `sha256:` + 64 lowercase hex digits of the archive bytes, got %q", file, ln+1, v)
			}
			cur.Source.Hash = v
		default:
			return nil, fmt.Errorf("%s line %d: unknown key %q", file, ln+1, k)
		}
	}
	if err := flush(); err != nil {
		return nil, err
	}
	return lock, nil
}

// topLevel reads a line above the first entry: only `index_serial = N`.
func (l *Lock) topLevel(line string) error {
	k, v, ok := strings.Cut(line, "=")
	if !ok || strings.TrimSpace(k) != "index_serial" {
		return fmt.Errorf("%q outside a [[package]] entry", line)
	}
	if l.IndexSerial != "" {
		return fmt.Errorf("index_serial given twice")
	}
	v = strings.TrimSpace(v)
	if err := ValidateSerial(v); err != nil {
		return fmt.Errorf("index_serial %w", err)
	}
	l.IndexSerial = v
	return nil
}

func validHashShape(s string) bool {
	hex, ok := strings.CutPrefix(s, "sha256:")
	if !ok || len(hex) != 64 {
		return false
	}
	for _, r := range hex {
		if (r < '0' || r > '9') && (r < 'a' || r > 'f') {
			return false
		}
	}
	return true
}
