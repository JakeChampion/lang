#!/usr/bin/env python3
"""Regenerate internal/stdlib/std/encoding/indexes.fern, the indexes of the
Encoding Standard (https://encoding.spec.whatwg.org/) that std/encoding
decodes with, and the labels of each encoding.

Run:  python3 cmd/encodinggen/gen.py INDEXES LIB_RS > internal/stdlib/std/encoding/indexes.fern

INDEXES is encoding-indexes.js of the npm package text-encoding 0.7.0,
which holds each index of the standard as a JSON array. LIB_RS is
src/lib.rs of the crate encoding_rs 0.8.33, which holds the labels in
LABELS_SORTED and their encodings in ENCODINGS_IN_LABEL_SORT.

An index is a string of tokens. A token is a run of characters of the
alphabet below: each character holds five bits, low bits first, and a
character with the value 32 or more continues the number. An even number
2n is a value that is n after zigzag coding plus the value before it, and
an odd number 2n + 1 is a run of n pointers with no value.
"""

import json
import re
import sys

ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"

NAMES = {
    "UTF_8": "UTF-8", "IBM866": "IBM866", "ISO_8859_2": "ISO-8859-2", "ISO_8859_3": "ISO-8859-3",
    "ISO_8859_4": "ISO-8859-4", "ISO_8859_5": "ISO-8859-5", "ISO_8859_6": "ISO-8859-6", "ISO_8859_7": "ISO-8859-7",
    "ISO_8859_8": "ISO-8859-8", "ISO_8859_8_I": "ISO-8859-8-I", "ISO_8859_10": "ISO-8859-10",
    "ISO_8859_13": "ISO-8859-13", "ISO_8859_14": "ISO-8859-14", "ISO_8859_15": "ISO-8859-15",
    "ISO_8859_16": "ISO-8859-16", "KOI8_R": "KOI8-R", "KOI8_U": "KOI8-U", "MACINTOSH": "macintosh",
    "WINDOWS_874": "windows-874", "WINDOWS_1250": "windows-1250", "WINDOWS_1251": "windows-1251",
    "WINDOWS_1252": "windows-1252", "WINDOWS_1253": "windows-1253", "WINDOWS_1254": "windows-1254",
    "WINDOWS_1255": "windows-1255", "WINDOWS_1256": "windows-1256", "WINDOWS_1257": "windows-1257",
    "WINDOWS_1258": "windows-1258", "X_MAC_CYRILLIC": "x-mac-cyrillic", "GBK": "GBK", "GB18030": "gb18030",
    "BIG5": "Big5", "EUC_JP": "EUC-JP", "ISO_2022_JP": "ISO-2022-JP", "SHIFT_JIS": "Shift_JIS",
    "EUC_KR": "EUC-KR", "REPLACEMENT": "replacement", "UTF_16BE": "UTF-16BE", "UTF_16LE": "UTF-16LE",
    "X_USER_DEFINED": "x-user-defined",
}

INDEXES = [
    "big5", "euc-kr", "gb18030", "jis0208", "jis0212", "ibm866", "iso-8859-2", "iso-8859-3", "iso-8859-4",
    "iso-8859-5", "iso-8859-6", "iso-8859-7", "iso-8859-8", "iso-8859-10", "iso-8859-13", "iso-8859-14",
    "iso-8859-15", "iso-8859-16", "koi8-r", "koi8-u", "macintosh", "windows-874", "windows-1250",
    "windows-1251", "windows-1252", "windows-1253", "windows-1254", "windows-1255", "windows-1256",
    "windows-1257", "windows-1258", "x-mac-cyrillic",
]


def number(out, n):
    while True:
        low = n & 31
        n >>= 5
        if n:
            out.append(ALPHABET[low | 32])
        else:
            out.append(ALPHABET[low])
            return


def encode(values):
    out = []
    prev = 0
    i = 0
    while i < len(values):
        if values[i] is None:
            j = i
            while j < len(values) and values[j] is None:
                j += 1
            number(out, (j - i) * 2 + 1)
            i = j
            continue
        d = values[i] - prev
        z = d * 2 if d >= 0 else -d * 2 - 1
        number(out, z * 2)
        prev = values[i]
        i += 1
    return "".join(out)


def labels(lib_rs):
    text = open(lib_rs).read()
    names = re.findall(r'"([^"]*)"', re.search(r"static LABELS_SORTED[^=]*=\s*\[(.*?)\];", text, re.S).group(1))
    encs = re.findall(r"&(\w+)_INIT", re.search(r"static ENCODINGS_IN_LABEL_SORT[^=]*=\s*\[(.*?)\];", text, re.S).group(1))
    assert len(names) == len(encs)
    return sorted(zip(names, (NAMES[e] for e in encs)))


def main():
    js = open(sys.argv[1]).read()
    body = js[js.index('global["encoding-indexes"] =') + len('global["encoding-indexes"] ='):]
    idx = json.JSONDecoder().raw_decode(body.strip())[0]
    out = sys.stdout
    out.write("// The indexes and the labels of the Encoding Standard for std/encoding.\n")
    out.write("//\n")
    out.write("// Generated by cmd/encodinggen/gen.py from the indexes of text-encoding\n")
    out.write("// 0.7.0 and the labels of encoding_rs 0.8.33. Do not edit by hand.\n")
    out.write("\n// Each label and its encoding, as \"label=name;\", in the order of the labels.\n")
    out.write('pub const LABELS: string = "%s";\n' % "".join("%s=%s;" % (l, n) for l, n in labels(sys.argv[2])))
    ranges = idx["gb18030-ranges"]
    out.write("\n// The pointers and the code points of the ranges of gb18030.\n")
    out.write("pub const GB18030_RANGES: i32[] = [%s];\n" % ", ".join("%d, %d" % (p, c) for p, c in ranges))
    out.write("\n// The name of each index, and its tokens.\n")
    out.write("pub const INDEX_NAMES: string[] = [%s];\n" % ", ".join('"%s"' % n for n in INDEXES))
    out.write("\npub const INDEXES: string[] = [\n")
    for n in INDEXES:
        out.write('  "%s",\n' % encode(idx[n]))
    out.write("];\n")


if __name__ == "__main__":
    main()
