#!/usr/bin/env python3
"""Generate the regex property ranges absent from Go's Unicode tables."""
import argparse
from itertools import groupby

from gen_bididata import ucd_file


def properties(text, names):
    values = {name: set() for name in names}
    for line in text.splitlines():
        fields = line.partition("#")[0].strip().split(";")
        if len(fields) != 2 or fields[1].strip() not in values:
            continue
        limits = fields[0].strip().split("..")
        lo, hi = int(limits[0], 16), int(limits[-1], 16)
        values[fields[1].strip()].update(range(lo, hi + 1))
    if not all(values.values()):
        raise ValueError("missing Unicode property")
    return values


def emit(name, points):
    print(f"\nvar {name} = [][2]rune{{")
    for _, group in groupby(enumerate(sorted(points)), lambda pair: pair[1] - pair[0]):
        span = [cp for _, cp in group]
        print(f"\t{{0x{span[0]:04X}, 0x{span[-1]:04X}}},")
    print("}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("version")
    parser.add_argument("--ucd", help="read UCD files from a local directory")
    args = parser.parse_args()
    core = ucd_file(args.version, args.ucd, "DerivedCoreProperties.txt")
    ids = properties(core, ("ID_Start", "ID_Continue", "XID_Start", "XID_Continue"))
    bidi = properties(ucd_file(args.version, args.ucd, "extracted/DerivedBinaryProperties.txt"),
                      ("Bidi_Mirrored",))
    print(f"// Code generated by gen_regexprops.py from Unicode {args.version}. DO NOT EDIT.")
    print("\npackage main")
    for prop, table in (("Start", "xidStartExcluded"), ("Continue", "xidContinueExcluded")):
        regular, normalized = ids["ID_" + prop], ids["XID_" + prop]
        if not normalized <= regular:
            raise ValueError("XID_" + prop + " exceeds ID_" + prop)
        emit(table, regular - normalized)
    emit("bidiMirrored", bidi["Bidi_Mirrored"])
    # Go supplies the simple mappings from UnicodeData. Keep only the
    # differences for the full case properties defined on decomposed text.
    rows = [line.split(";") for line in ucd_file(args.version, args.ucd, "UnicodeData.txt").splitlines()]
    mappings = (("Lowercased", 13), ("Uppercased", 12), ("Titlecased", 14), ("Casefolded", 13))
    changes = properties(core, ["Changes_When_" + op for op, _ in mappings] + ["Changes_When_Casemapped"])
    for op, field in mappings:
        simple = {int(row[0], 16) for row in rows if row[field] and row[field] != row[0]}
        emit("changes" + op + "Delta", changes["Changes_When_" + op] ^ simple)
    mapped = changes["Changes_When_Lowercased"] | changes["Changes_When_Uppercased"] | changes["Changes_When_Titlecased"]
    if changes["Changes_When_Casemapped"] != mapped:
        raise ValueError("unexpected Changes_When_Casemapped definition")


if __name__ == "__main__":
    main()
