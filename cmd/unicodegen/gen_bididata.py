#!/usr/bin/env python3
"""Regenerate bididata.txt — the source data of the Unicode Bidirectional
Algorithm (UAX #9), and the joining types that Arabic shaping needs.

Neither Go's `unicode` package nor CPython's `unicodedata` gives the
paired brackets or the mirrored glyphs, so the data is read from the
Unicode Character Database files of the release named on the command line,
the one that Go's `unicode` tracks.

Run:  python3 cmd/unicodegen/gen_bididata.py 17.0.0 > cmd/unicodegen/bididata.txt

The UCD files are fetched from unicode.org; `--ucd DIR` reads
DerivedBidiClass.txt, BidiBrackets.txt, BidiMirroring.txt and
DerivedJoiningType.txt from DIR instead.

Only the code points whose Bidi_Class is not L are emitted: L is the
default of most of the code space. The defaults of the `@missing` lines
apply to unassigned code points, as the algorithm requires.
"""

import os
import sys
import urllib.request

MAX_CP = 0x110000


def ucd_file(version: str, ucd_dir: str, path: str) -> str:
    if ucd_dir:
        with open(os.path.join(ucd_dir, os.path.basename(path)), encoding="utf-8") as f:
            return f.read()
    url = "https://www.unicode.org/Public/%s/ucd/%s" % (version, path)
    with urllib.request.urlopen(url) as r:
        return r.read().decode("utf-8")


# The long names of the `@missing` lines and their short forms.
LONG = {
    "Left_To_Right": "L", "Right_To_Left": "R", "Arabic_Letter": "AL",
    "European_Terminator": "ET", "Boundary_Neutral": "BN",
}


def cp_range(text: str):
    lo, _, hi = text.strip().partition("..")
    return int(lo, 16), int(hi or lo, 16)


def bidi_classes(text: str):
    classes = ["L"] * MAX_CP
    for line in text.splitlines():
        if line.startswith("# @missing:"):
            cps, value = line[len("# @missing:"):].split(";")
            lo, hi = cp_range(cps)
            value = value.strip()
            classes[lo:hi + 1] = [LONG.get(value, value)] * (hi - lo + 1)
    for line in text.splitlines():
        body = line.split("#", 1)[0].strip()
        if not body:
            continue
        cps, value = [x.strip() for x in body.split(";")[:2]]
        lo, hi = cp_range(cps)
        classes[lo:hi + 1] = [value] * (hi - lo + 1)
    return classes


def joining_types(text: str):
    """The Joining_Type of each code point, U where the file names none."""
    types = ["U"] * MAX_CP
    for line in text.splitlines():
        body = line.split("#", 1)[0].strip()
        if not body:
            continue
        cps, value = [x.strip() for x in body.split(";")[:2]]
        lo, hi = cp_range(cps)
        types[lo:hi + 1] = [value] * (hi - lo + 1)
    return types


def runs(values, skip):
    out = []
    run = None
    for cp, v in enumerate(values):
        if run is not None and run[2] == v:
            run = (run[0], cp, v)
            continue
        if run is not None and run[2] != skip:
            out.append(run)
        run = (cp, cp, v)
    if run is not None and run[2] != skip:
        out.append(run)
    return out


def pairs(text: str):
    """(code point, its pair, the rest of the fields) for each data line."""
    for line in text.splitlines():
        body = line.split("#", 1)[0].strip()
        if not body:
            continue
        fields = [x.strip() for x in body.split(";")]
        yield int(fields[0], 16), int(fields[1], 16), fields[2:]


def parse_args():
    args = sys.argv[1:]
    if len(args) == 3 and args[1] == "--ucd":
        return args[0], args[2]
    if len(args) != 1:
        sys.exit("usage: %s VERSION [--ucd DIR]" % os.path.basename(sys.argv[0]))
    return args[0], ""


def main() -> None:
    version, ucd_dir = parse_args()
    classes = bidi_classes(ucd_file(version, ucd_dir, "extracted/DerivedBidiClass.txt"))
    out = sys.stdout
    out.write("# Generated by gen_bididata.py -- do not edit by hand.\n")
    out.write("# UCD %s (unicode.org)\n" % version)
    out.write("#\n")
    out.write("# B;<lo>;<hi>;<class>   Bidi_Class (not L only)\n")
    out.write("# P;<cp>;<pair>;<o|c>   Bidi_Paired_Bracket and Bidi_Paired_Bracket_Type\n")
    out.write("# M;<cp>;<mirror>       Bidi_Mirroring_Glyph\n")
    out.write("# J;<lo>;<hi>;<type>    Joining_Type (not U only)\n")
    for lo, hi, v in runs(classes, skip="L"):
        out.write("B;%04X;%04X;%s\n" % (lo, hi, v))
    for cp, pair, rest in pairs(ucd_file(version, ucd_dir, "BidiBrackets.txt")):
        out.write("P;%04X;%04X;%s\n" % (cp, pair, rest[0]))
    for cp, mirror, _ in pairs(ucd_file(version, ucd_dir, "BidiMirroring.txt")):
        out.write("M;%04X;%04X\n" % (cp, mirror))
    joins = joining_types(ucd_file(version, ucd_dir, "extracted/DerivedJoiningType.txt"))
    for lo, hi, v in runs(joins, skip="U"):
        out.write("J;%04X;%04X;%s\n" % (lo, hi, v))


if __name__ == "__main__":
    main()
