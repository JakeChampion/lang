// Unit tests for the benchmark history loader.

import assert from "node:assert/strict";
import { readFileSync, readdirSync } from "node:fs";
import { test } from "node:test";

import { coreutilsRuns, machineOf, onRunner, startupRuns } from "../src/lib/bench-history.mjs";

const read = (dir) => Object.fromEntries(
  readdirSync(new URL(dir, import.meta.url)).filter((f) => f.endsWith("-bench.md"))
    .map((f) => [`${dir}${f}`, readFileSync(new URL(dir + f, import.meta.url), "utf8")]));

test("names the machine of a run", () => {
  assert.equal(machineOf("# x\n\nGenerated by .github/workflows/x.yml on a GitHub-hosted ubuntu-24.04 runner.\n"), "GitHub-hosted runner");
  assert.equal(machineOf("# x\n\nbuilt on a 4-core container with nothing else running\n"), "another machine (see the log)");
});

test("reads every coreutils run in date order, and keeps runs by hand out of the series", () => {
  const runs = coreutilsRuns(read("../../docs/coreutils-log/"));
  assert.ok(runs.length >= 2);
  assert.deepEqual(runs.map((r) => r.date), [...runs.map((r) => r.date)].sort());
  assert.equal(runs.find((r) => r.date === "2026-10-12").machine, "another machine (see the log)");
  assert.ok(onRunner(runs).every((r) => r.machine === "GitHub-hosted runner"));
  assert.ok(runs.every((r) => r.vsGnu > 0 && r.workloads > 0));
});

test("reads every startup run with its rows", () => {
  const runs = startupRuns(read("../../docs/startup-log/"));
  assert.ok(runs.length >= 1);
  assert.ok(runs[0].rows.some((r) => r.language === "Fern"));
});
