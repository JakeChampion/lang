// Refreshes the self-hosted webfonts: downloads the woff2 files into
// src/assets/fonts/ and regenerates src/styles/fonts.css to point at them.
//
//   node scripts/fetch-fonts.mjs
//
// The site used to link Google Fonts' stylesheet directly, which cost two
// preconnects and a render-blocking cross-origin round trip on every page,
// and put a third party in the path of the site rendering at all. Serving
// the same files ourselves removes both. Vite hashes and emits whatever
// fonts.css references, so nothing here is coupled to the site's `base`.
//
// Google's CSS is generated per user-agent; the modern UA below is what
// makes it hand back woff2 and one `unicode-range` block per subset. Only
// the subsets in SUBSETS are kept — the docs are English, and the fallback
// stack covers any glyph that isn't.
//
// Both families are SIL OFL 1.1; src/assets/fonts/OFL.txt travels with
// them, as the licence requires.

import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const CSS_URL =
  "https://fonts.googleapis.com/css2" +
  "?family=Fraunces:opsz,wght,SOFT,WONK@9..144,400..700,0..100,0..1" +
  "&family=IBM+Plex+Mono:wght@400;500;600" +
  "&display=swap";

const UA =
  "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) " +
  "Chrome/120.0 Safari/537.36";

const SUBSETS = new Set(["latin", "latin-ext"]);

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const fontDir = here("../src/assets/fonts");

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

const css = await fetch(CSS_URL, { headers: { "user-agent": UA } }).then((r) => {
  if (!r.ok) throw new Error(`${CSS_URL} → HTTP ${r.status}`);
  return r.text();
});

const blocks = [
  ...css.matchAll(/\/\* (?<subset>[\w-]+) \*\/\s*@font-face \{(?<body>[^}]*)\}/g),
];
if (blocks.length === 0) throw new Error("no @font-face blocks parsed");

await mkdir(fontDir, { recursive: true });
for (const name of await readdir(fontDir)) {
  if (name.endsWith(".woff2")) await rm(`${fontDir}/${name}`);
}

const field = (body, key) => body.match(new RegExp(`${key}: ([^;]+);`))?.[1].trim();
const rules = [];

for (const { groups } of blocks) {
  const { subset, body } = groups;
  if (!SUBSETS.has(subset)) continue;

  const family = field(body, "font-family").replace(/^['"]|['"]$/g, "");
  const weight = field(body, "font-weight");
  const url = body.match(/url\((https:[^)]+)\)/)[1];
  const file = `${slug(family)}-${slug(weight)}-${subset}.woff2`;

  const bytes = await fetch(url).then(async (r) => {
    if (!r.ok) throw new Error(`${url} → HTTP ${r.status}`);
    return Buffer.from(await r.arrayBuffer());
  });
  await writeFile(`${fontDir}/${file}`, bytes);

  rules.push(
    [
      `/* ${family} ${weight} — ${subset} */`,
      "@font-face {",
      `  font-family: "${family}";`,
      `  font-style: ${field(body, "font-style")};`,
      `  font-weight: ${weight};`,
      "  font-display: swap;",
      `  src: url("../assets/fonts/${file}") format("woff2");`,
      `  unicode-range: ${field(body, "unicode-range")};`,
      "}",
    ].join("\n"),
  );
  console.log(`${file} — ${(bytes.length / 1024).toFixed(1)} kB`);
}

const header = [
  "/* Self-hosted webfonts — GENERATED by scripts/fetch-fonts.mjs.",
  " *",
  " * Edit that script (the family request, the subset allowlist) and",
  " * re-run it rather than editing this file; the woff2 files it",
  " * references live in src/assets/fonts/ and are hashed into the build",
  " * by Vite, so these relative URLs work under any `base`.",
  " *",
  " * Fraunces and IBM Plex Mono are both SIL OFL 1.1 — see",
  " * src/assets/fonts/OFL.txt.",
  " */",
  "",
].join("\n");

await writeFile(here("../src/styles/fonts.css"), `${header}${rules.join("\n\n")}\n`);
console.log(`wrote src/styles/fonts.css — ${rules.length} faces`);
